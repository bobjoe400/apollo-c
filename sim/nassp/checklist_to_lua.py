"""nassp_cl2lua.py WORKBOOK.xls OUT.lua: compile a NASSP checklist workbook into a Lua table of steps.

Host tool for the NASSP mission runs (needs the third-party xlrd for .xls): the workbooks are
NASSP's Config/ProjectApollo/Checklists/*.xls (GPL, not in this repository); the output is the
cl_lm.lua / cl_csm.lua the scripts in sim/nassp/lua load (copy to <install>/Script/apollo-c).

Each sheet becomes CL["<sheet>"] = { step, ... }; a step is a table with
t = 'switch' | 'dsky' | 'call' | 'note', plus item/pos/keys/sheet,
delay (HIDDEN_DELAY seconds before), met (MISSION_TIME to wait for), text.
"""
import sys
import xlrd

def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def dsky_keys(item):
    # "DSKY V 3 7 E 4 0 E" -> "V37E40E"; "DSKY P" -> "P"
    toks = item.split()[1:]
    return ''.join(toks)

def num(v):
    try:
        return float(v)
    except ValueError:
        return None

def main(path, out):
    b = xlrd.open_workbook(path)
    lines = ['-- generated by cl2lua.py from ' + path.split('/')[-1], 'CL = {}']
    for sh in b.sheets():
        if sh.nrows < 2 or sh.name in ('GROUPS', 'Flightplan'):
            continue
        hdr = [str(c.value).strip() for c in sh.row(0)]
        col = {h: i for i, h in enumerate(hdr)}
        if 'Item' not in col:
            continue
        steps = []
        for r in range(1, sh.nrows):
            row = [str(c.value).strip() for c in sh.row(r)]
            get = lambda k: row[col[k]] if k in col and col[k] < len(row) else ''
            text, time, ev, item, pos, auto, call = get('Text'), get('Time'), get('Relative Event'), get('Item'), get('Position'), get('Automatic'), get('Call Group')
            if not (text or item or call):
                continue
            f = ['text=' + lua_str(text)]
            if ev == 'HIDDEN_DELAY' and num(time) is not None:
                f.append('delay=%g' % num(time))
            elif ev == 'MISSION_TIME' and num(time) is not None:
                f.append('met=%g' % num(time))
            elif ev:
                f.append('event=' + lua_str(ev))
            if call:
                f.insert(0, "t='call', sheet=" + lua_str(call))
            elif item.startswith('DEDA'):
                # the AGS keyboard: not the AGC; listed for the user
                f.insert(0, "t='note'"); f.append('manual=true')
                f[1] = 'text=' + lua_str('DEDA ' + ' '.join(item.split()[1:]) + ' (' + text + ')')
            elif item.startswith('DSKY'):
                f.insert(0, "t='dsky', keys=" + lua_str(dsky_keys(item)))
            elif item and pos and pos.rstrip('G') and num(pos.rstrip('G')) is not None and num(pos.rstrip('G')) >= -100 and not (num(pos) == -1.0):
                f.insert(0, "t='switch', item=%s, pos=%d" % (lua_str(item), int(num(pos.rstrip('G')))))
            else:
                f.insert(0, "t='note'")
            if auto and num(auto) == 0.0:
                f.append('manual=true')
            steps.append('{' + ', '.join(f) + '}')
        lines.append('CL[%s] = {\n  %s\n}' % (lua_str(sh.name), ',\n  '.join(steps)))
    open(out, 'w').write('\n'.join(lines) + '\n')

main(sys.argv[1], sys.argv[2])
