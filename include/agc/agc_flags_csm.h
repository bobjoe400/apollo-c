/*
 * agc_flags_csm.h -- Comanche055 (CSM) flagword bits that are NOT in agc_flags_common.h.
 * Source: Comanche055/ERASABLE_ASSIGNMENTS.agc, FLAGWRD0..FLGWRD11 (STATE+0..+11D).
 * Includes agc_flags_common.h. Do not include together with agc_flags_lm.h:
 * names whose position differs between vehicles would collide (by design,
 * the compiler rejects it). Code needing both uses agc_state_vehicle().
 */
#ifndef AGC_FLAGS_CSM_H
#define AGC_FLAGS_CSM_H

#include "agc_flags_common.h"

/*
 * Flag id encoding (agc_flag_id_t, see agc_state.h):
 *     id = (flagword << 4) | bit
 * flagword is the index n of FLAGWRDn (STATE + n); bit is the AGC bit
 * number 1..15 as printed in the AGC listing (bit 1 is the least
 * significant bit, bit 15 the most significant of the 15-bit word).
 * The AGC "decimal number" nnnD of a flag is 15*flagword + (15 - bit).
 * SET / RESET text is the AGC listing's own description of the two states.
 * C name: AGC_FLAG_<AGCNAME>, AGCNAME upper case, '/', '-' and '.' -> '_'.
 */

enum agc_flag_csm_id {
    /* KFLAG  FLAGWRD0 bit 1 (014D)
     * SET: SEARCH SECTOR MORE THAN 180 DEGREES  RESET: SEARCH SECTOR LESS THAN
     * 180 DEGREES */
    AGC_FLAG_KFLAG = 0x01,
    /* AMOONFLG  FLAGWRD0 bit 2 (013D)
     * SET: STATE VECTOR IN LUNAR SPHERE AT MIDTOAVE  RESET: STATE VECTOR IN
     * EARTH SPHERE AT MIDTOAVE */
    AGC_FLAG_AMOONFLG = 0x02,
    /* TRUNFLAG  FLAGWRD0 bit 4 (011D)
     * SET: DRIVING OF TRUNNION ALLOWED  RESET: DRIVING OF TRUNNION NOT ALLOWED */
    AGC_FLAG_TRUNFLAG = 0x04,
    /* F2RTE  FLAGWRD0 bit 5 (010D)
     * SET: IN TIME CRITICAL MODE  RESET: NOT IN TIME CRITICAL MODE */
    AGC_FLAG_F2RTE = 0x05,
    /* R53FLAG  FLAGWRD0 bit 6 (009D)
     * SET: V51 INITIATED  RESET: V51 NOT INITIATED */
    AGC_FLAG_R53FLAG = 0x06,
    /* NEEDLFLG  FLAGWRD0 bit 9 (006D)  [LM: FLAGWRD0 bit 4]
     * SET: TOTAL ATTITUDE ERROR DISPLAYED  RESET: A/P FOLLOWING ERROR DISPLAYED */
    AGC_FLAG_NEEDLFLG = 0x09,
    /* ZMEASURE  FLAGWRD0 bit 10 (005D)
     * SET: MEASUREMENT PLANET AND PRIMARY PLANET DIFFERENT  RESET: MEASUREMENT
     * PLANET AND PRIMARY PLANET SAME */
    AGC_FLAG_ZMEASURE = 0x0A,
    /* NORFHOR  FLAGWRD0 bit 11 (004D)
     * SET: FAR HORIZON  RESET: NEAR HORIZON */
    AGC_FLAG_NORFHOR = 0x0B,
    /* CPHIFLAG  FLAGWRD0 bit 15 (000D)
     * SET: OUTPUT OF CALCGA IS CPHIX  RESET: OUTPUT OF CALCGA IS THETAD */
    AGC_FLAG_CPHIFLAG = 0x0F,
    /* AVEGFLAG  FLAGWRD1 bit 1 (029D)  [LM: FLAGWRD7 bit 5]
     * SET: AVERAGEG (SERVICER) TO CONTINUE  RESET: AVERAGEG (SERVICER) TO CEASE */
    AGC_FLAG_AVEGFLAG = 0x11,
    /* TRM03FLG  FLAGWRD1 bit 4 (026D)
     * SET: REQUEST TO TERMINATE P03 HAS BEEN ENTERED  RESET: NO REQUEST TO
     * TERMINATE P03 HAS BEEN ENTERED */
    AGC_FLAG_TRM03FLG = 0x14,
    /* IDLEFAIL  FLAGWRD1 bit 6 (024D)
     * SET: INHIBIT R41  RESET: ENABLE R41 (ENGFAIL) */
    AGC_FLAG_IDLEFAIL = 0x16,
    /* R23FLG  FLAGWRD1 bit 9 (021D)
     * R23 MARKING */
    AGC_FLAG_R23FLG = 0x19,
    /* TARG2FLG  FLAGWRD1 bit 9 (021D)
     * SET: SIGHTING LANDMARK  RESET: SIGHTING STAR */
    AGC_FLAG_TARG2FLG = 0x19,
    /* TARG1FLG  FLAGWRD1 bit 10 (020D)
     * SET: SIGHTING LEM  RESET: NOT SIGHTING LEM */
    AGC_FLAG_TARG1FLG = 0x1A,
    /* ENG2FLAG  FLAGWRD1 bit 11 (019D)
     * SET: RCS BURN  RESET: SPS BURN */
    AGC_FLAG_ENG2FLAG = 0x1B,
    /* NODOP01  FLAGWRD1 bit 12 (018D)
     * SET: P01 NOT ALLOWED  RESET: P01 ALLOWED */
    AGC_FLAG_NODOP01 = 0x1C,
    /* STIKFLAG  FLAGWRD1 bit 14 (016D)
     * SET: RHC CONTROL  RESET: CMC CONTROL */
    AGC_FLAG_STIKFLAG = 0x1E,
    /* FIRSTFLG  FLAGWRD2 bit 7 (038D)
     * SET: FIRST PASS THRU S40.9  RESET: SUCCEEDING PASS THRU S40.9 Same bit as
     * ETPIFLAG. */
    AGC_FLAG_FIRSTFLG = 0x27,
    /* SKIPVHF  FLAGWRD2 bit 10 (035D)
     * SET: DISREGARD RADAR READ BECAUSE OF SFTWRE OR HDWRE RESTART  RESET: RADAR
     * READ TO PROCEED NORMALLY */
    AGC_FLAG_SKIPVHF = 0x2A,
    /* P21FLAG  FLAGWRD2 bit 12 (033D)  [LM: FLAGWRD0 bit 11]
     * SET: SUCCEEDING PASS THRU P21, USE BASE VECTOR FOR CALC.  RESET: 1ST PASS
     * THRU P21, CALCULATE BASE VECTOR */
    AGC_FLAG_P21FLAG = 0x2C,
    /* 22DSPFLG  FLAGWRD2 bit 13 (032D)
     * SET: DISPLAY DR,DV  RESET: DO NOT DISPLAY DR,DV */
    AGC_FLAG_22DSPFLG = 0x2D,
    /* R21MARK  FLAGWRD2 bit 14 (031D)
     * SET: OPTION ONE FOR MARKRUPT  RESET: OPTION TWO FOR MARKRUPT */
    AGC_FLAG_R21MARK = 0x2E,
    /* P22MKFLG  FLAGWRD3 bit 11 (049D)
     * SET: P22 DOWNLINKED MARK DATA WAS JUST TAKEN  RESET: P22 DOWNLINK MARK
     * DATA NOT JUST TAKEN */
    AGC_FLAG_P22MKFLG = 0x3B,
    /* R60FLAG  FLAGWRD5 bit 4 (086D)
     * SET: R61 MUST USE R60  RESET: NORMAL R61 */
    AGC_FLAG_R60FLAG = 0x54,
    /* GRRBKFLG  FLAGWRD5 bit 5 (085D)
     * SET: BACKUP GRR RECEIVED  RESET: BACKUP GRR NOT RECEIVED */
    AGC_FLAG_GRRBKFLG = 0x55,
    /* COMPUTER  FLAGWRD5 bit 8 (082D)
     * SET: COMPUTER IS CMC  RESET: COMPUTER IS LGC */
    AGC_FLAG_COMPUTER = 0x58,
    /* PRFTRKAT  FLAGWRD5 bit 10 (080D)
     * SET: PREF TRACK ATT  RESET: +K AXIS TRACK ATT Same bit as RNGSCFLG. */
    AGC_FLAG_PRFTRKAT = 0x5A,
    /* INCORFLG  FLAGWRD5 bit 11 (079D)
     * SET: FIRST INCORPORATION  RESET: SECOND INCORPORATION */
    AGC_FLAG_INCORFLG = 0x5B,
    /* V59FLAG  FLAGWRD5 bit 12 (078D)
     * SET: CALIBRATING FOR P23  RESET: NORMAL MARKING FOR P23 */
    AGC_FLAG_V59FLAG = 0x5C,
    /* SLOWFLG  FLAGWRD5 bit 13 (077D)
     * SET: P37 TRANSEARTH COAST SLOW DOWN IS DESIRED  RESET: SLOW DOWN IS NOT
     * DESIRED */
    AGC_FLAG_SLOWFLG = 0x5D,
    /* RETROFLG  FLAGWRD5 bit 14 (076D)
     * SET: P37 PREMANEUVER ORBIT IS RETROGRADE  RESET: ORBIT NOT RETROGRADE */
    AGC_FLAG_RETROFLG = 0x5E,
    /* GYMDIFSW  FLAGWRD6 bit 1 (104D)
     * SET: CDU DIFFERENCES AND BODY RATES COMPUTED  RESET: CDU DIFFERENCES AND
     * BODY RATES NOT COMPUTED */
    AGC_FLAG_GYMDIFSW = 0x61,
    /* CM/DSTBY  FLAGWRD6 bit 2 (103D)
     * SET: ENTRY DAP ACTIVATED  RESET: ENTRY DAP NOT ACTIVATED */
    AGC_FLAG_CM_DSTBY = 0x62,
    /* .05GSW  FLAGWRD6 bit 3 (102D)
     * SET: DRAG OVER .05G  RESET: DRAG LESS THAN .05G */
    AGC_FLAG__05GSW = 0x63,
    /* LATSW  FLAGWRD6 bit 4 (101D)
     * SET: DOWNLIFT NOT INHIBITED  RESET: DOWNLIFT INHIBITED */
    AGC_FLAG_LATSW = 0x64,
    /* INRLSW  FLAGWRD6 bit 5 (100D)
     * SET: INITIAL ROLL V(LV) ATTITUDE NOT HELD  RESET: INITIAL ROLL V(LV)
     * ATTITUDE HELD */
    AGC_FLAG_INRLSW = 0x65,
    /* HIND  FLAGWRD6 bit 6 (099D)
     * SET: ITERATING HUNTEST CALCULATIONS TO BE DONE AFTER RANGE PREDICTION
     * RESET: ITERATING OF HUNTEST CALCULATIONS TO BE OMITTED AFTER RANGE
     * PREDICTION */
    AGC_FLAG_HIND = 0x66,
    /* NOSWITCH  FLAGWRD6 bit 7 (098D)
     * SET: LATERAL ROLL MANEUVER INHIBITED IN ENTRY  RESET: LATERAL ROLL
     * MANEUVER PERMITTED IN ENTRY */
    AGC_FLAG_NOSWITCH = 0x67,
    /* EGSW  FLAGWRD6 bit 8 (097D)
     * SET: IN FINAL PHASE  RESET: NOT IN FINAL PHASE */
    AGC_FLAG_EGSW = 0x68,
    /* KNOWNFLG  FLAGWRD6 bit 8 (097D)
     * SET: LANDMARK KNOWN  RESET: LANDMARK UNKNOWN Same bit as EGSW. */
    AGC_FLAG_KNOWNFLG = 0x68,
    /* R57FLAG  FLAGWRD6 bit 8 (097D)
     * SET: DO NOT DO R57 TRUNION BIAS HAS BEEN OBTAINED.  RESET: DO R57, TRUNION
     * BIAS NEEDED Same bit as KNOWNFLG. */
    AGC_FLAG_R57FLAG = 0x68,
    /* RELVELSW  FLAGWRD6 bit 9 (096D)
     * SET: TARGETING USES EARTH-RELATIVE VELOCITY.  RESET: TARGETING USES
     * INERTIAL VELOCITY */
    AGC_FLAG_RELVELSW = 0x69,
    /* GONEPAST  FLAGWRD6 bit 10 (095D)
     * SET: LATERAL CONTROL CALCULATIONS TO BE OMITTED  RESET: LATERAL CONTROL
     * CALCULATIONS TO BE DONE */
    AGC_FLAG_GONEPAST = 0x6A,
    /* GAMDIFSW  FLAGWRD6 bit 11 (094D)
     * SET: CALCULATE GAMDOT  RESET: GAMDOT NOT TO BE CALCULATED */
    AGC_FLAG_GAMDIFSW = 0x6B,
    /* CMDAPARM  FLAGWRD6 bit 12 (093D)
     * SET: ALLOW ENTRY FIRINGS AND CALCULATIONS  RESET: INHIBIT ENTRY FIRING AND
     * CONTROL FUNCTION */
    AGC_FLAG_CMDAPARM = 0x6C,
    /* ENTRYDSP  FLAGWRD6 bit 13 (092D)
     * SET: DO ENTRY DISPLAY VIA ENTRYVN.  RESET: OMIT ENTRY DISPLAY Same bit as
     * STRULLSW. */
    AGC_FLAG_ENTRYDSP = 0x6D,
    /* STRULLSW  FLAGWRD6 bit 13 (092D)
     * SET: DO STEERULL  RESET: DO ULAGEOFF ONLY */
    AGC_FLAG_STRULLSW = 0x6D,
    /* DAPBIT2  FLAGWRD6 bit 14 (091D)
     * SET: 1 A/P  RESET: 0 A/P 1 A/P 0 A/P */
    AGC_FLAG_DAPBIT2 = 0x6E,
    /* DAPBIT1  FLAGWRD6 bit 15 (090D)
     * SET: 1 SATURN 1 TVC  RESET: 0 RCS 0 NO */
    AGC_FLAG_DAPBIT1 = 0x6F,
    /* ATTCHFLG  FLAGWRD7 bit 2 (118D)
     * SET: LM,CM ATTACHED  RESET: LM,CM NOT ATTACHED */
    AGC_FLAG_ATTCHFLG = 0x72,
    /* GONEBY  FLAGWRD7 bit 8 (112D)
     * SET: PASSED TARGET  RESET: APPROACHING TARGET */
    AGC_FLAG_GONEBY = 0x78,
    /* TIMRFLAG  FLAGWRD7 bit 11 (109D)
     * SET: CLOKTASK OPERATING  RESET: CLOKTASK INOPERATIVE */
    AGC_FLAG_TIMRFLAG = 0x7B,
    /* ITSWICH  FLAGWRD7 bit 14 (106D)  [LM: FLAGWRD7 bit 15]
     * SET: ACCEPT NEXT LAMBERT TPI SEARCH SOLUTION  RESET: TEST LAMBERT ANSWER
     * AGAINST LIMITS */
    AGC_FLAG_ITSWICH = 0x7E,
    /* TERMIFLG  FLAGWRD7 bit 15 (105D)
     * SET: TERMINATE R52  RESET: DO NOT TERMINATE R52 */
    AGC_FLAG_TERMIFLG = 0x7F,
    /* V96ONFLG  FLAGWRD8 bit 3 (132D)
     * SET: P00 INTEGRATION HAS BEEN INHIBITED BY V96  RESET: P00 INTEGRATION IS
     * PROCEEDING REGULARLY */
    AGC_FLAG_V96ONFLG = 0x83,
    /* ADVTRK  FLAGWRD8 bit 10 (125D)
     * SET: ADVANCE GROUND TRACK SIGHTING WANTED  RESET: NOT ADVANCED GROUND
     * TRACK */
    AGC_FLAG_ADVTRK = 0x8A,
    /* R31FLAG  FLAGWRD9 bit 4 (146D)
     * SET: R31 SELECTED (V63)  RESET: R34 SELECTED (V65) */
    AGC_FLAG_R31FLAG = 0x94,
    /* N22ORN17  FLAGWRD9 bit 6 (144D)
     * SET: COMPUTE TOTAL ATTITUDE ERRORS W.R.T. N22 (V62)  RESET: COMPUTE TOTAL
     * ATTITUDE ERRORS W.R.T. N17 (V63) */
    AGC_FLAG_N22ORN17 = 0x96,
    /* R22CAFLG  FLAGWRD9 bit 7 (143D)
     * SET: R-22 CALCULATIONS ARE GOING ON  RESET: R-22 CALCULATIONS ARE NOT
     * GOING ON */
    AGC_FLAG_R22CAFLG = 0x97,
    /* SOURCFLG  FLAGWRD9 bit 8 (142D)
     * SET: SOURCE OF INPUT DATA IS FROM VHF RADAR  RESET: SOURCE OF INPUT DATA
     * IS FROM OPTICS MARK */
    AGC_FLAG_SOURCFLG = 0x98,
    /* VHFRFLAG  FLAGWRD9 bit 9 (141D)
     * SET: ALLOW R22 TO ACCEPT RANGE DATA  RESET: STOP ACCEPTANCE OF RANGE DATA */
    AGC_FLAG_VHFRFLAG = 0x99,
    /* SAVECFLG  FLAGWRD9 bit 10 (140D)
     * SET: P23 DISPLAY AND DATA STORAGE AFTER MARK IS DONE  RESET: P23 DISPLAY
     * AND DATA STORAGE BEFORE MARK IS DONE */
    AGC_FLAG_SAVECFLG = 0x9A,
    /* V94FLAG  FLAGWRD9 bit 11 (139D)
     * SET: V94 ALLOWED DURING P23  RESET: V94 NOT ALLOWED */
    AGC_FLAG_V94FLAG = 0x9B,
    /* MAXDBFLG  FLAGWRD9 bit 12 (138D)
     * SET: MAX DB SELECTED  RESET: MIN DB SELECTED */
    AGC_FLAG_MAXDBFLG = 0x9C,
    /* V82EMFLG  FLAGWRD9 bit 13 (137D)  [LM: FLAGWRD7 bit 2]
     * SET: MOON VICINITY  RESET: EARTH VICINITY */
    AGC_FLAG_V82EMFLG = 0x9D,
    /* SWTOVER  FLAGWRD9 bit 15 (135D)
     * SET: SWITCHOVER HAS OCCURRED.  RESET: NO SWITCHOVER YET */
    AGC_FLAG_SWTOVER = 0x9F,
    /* S32.1F3B  FLAGWRD11 bit 12 (168D)  [LM: FLAGWRD6 bit 12]
     * Low bit of the S32.1F3 pair: (0,1) first Newton iteration being done;
     * (0,0) first pass of 2nd Newton iteration; (1,1) 50 ft/s (50 fps) stage of
     * 2nd Newton iteration; (1,0) remainder of 2nd Newton iteration */
    AGC_FLAG_S32_1F3B = 0xBC,
    /* S32.1F3A  FLAGWRD11 bit 13 (167D)  [LM: FLAGWRD6 bit 13]
     * Bit 13 and bit 12 (S32.1F3A, S32.1F3B) form an ordered pair (13,12) giving
     * the possible occurrence of 2 Newton iterations for S32.1 */
    AGC_FLAG_S32_1F3A = 0xBD,
    /* S32.1F2  FLAGWRD11 bit 14 (166D)  [LM: FLAGWRD6 bit 14]
     * SET: FIRST PASS OF NEWTON INTEGRATION  RESET: REITERATION OF NEWTON */
    AGC_FLAG_S32_1F2 = 0xBE,
    /* S32.1F1  FLAGWRD11 bit 15 (165D)  [LM: FLAGWRD6 bit 15]
     * SET: DELTAN AT CSI TIME ONE EXCEEDS MAX  RESET: DVT1 LESS THAN MAX */
    AGC_FLAG_S32_1F1 = 0xBF,
};

#endif /* AGC_FLAGS_CSM_H */
