#!/usr/bin/env python3
"""Generate tools/oracle/cases/targeting.spec (Comanche055).  Run from
tools/oracle/cases/gen: python3 -I gen_targeting.py && cd ../.. && make cases"""
import math, os, re, subprocess, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agcw import sp, dp, vec, _w
from specgen import Spec, gets_dp, gets_vec
from snip import YUL

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
TRAP_LO, TRAP_HI = '25751', '65105'

def consts(lines):
    """Assemble 2DEC/2DEC* lines with yaYUL; return the word pairs."""
    d = tempfile.mkdtemp(dir=os.environ.get('SNIPTMP'))
    src = ['\t\tBANK\t33', '\t\tCOUNT*\t$$/S'] + ['\t\t' + l for l in lines]
    open(os.path.join(d, 's.agc'), 'w').write('\n'.join(src) + '\n')
    out = subprocess.run([YUL, 's.agc'], capture_output=True, text=True, cwd=d).stdout
    res = []
    for line in out.splitlines():
        m = re.match(r'^\d+,\d+: 33,\d{4}\s+(\d{5}) (\d{5})', line)
        if m:
            res.append('%s,%s' % (m.group(1), m.group(2)))
    return res

def circ(mu, r, ang, inc=0.0):
    a = math.radians(ang)
    i = math.radians(inc)
    ur = [math.cos(a), math.sin(a) * math.cos(i), math.sin(a) * math.sin(i)]
    ut = [-math.sin(a), math.cos(a) * math.cos(i), math.cos(a) * math.sin(i)]
    v = math.sqrt(mu / r)
    return [x * r for x in ur], [x * v / 100 for x in ut]

MUE, MUM = 3.986032e14, 4.902778e12
# Executive core sets as in a running AGC: this job in set 0 (priority 37),
# sets 1-6 free (PRIORITY = -0); INTWAKE's JOBWAKE scans them for sleepers.
EXEC = [('NEWJOB', '00000'), ('PRIORITY', '37401')] + [
    ('%04o' % (0o167 + 12 * k), '77777') for k in range(1, 7)]

def main():
    mue, rtmue_inv, mum, rtmum_inv = consts([
        '2DEC*\t3.986032 E10 B-36*', '2DEC*\t.50087529 E-5 B+17*',
        '2DEC\t4.902778 E8 B-30', '2DEC*\t.45162595 E-4 B+14*'])
    s = Spec('Comanche055', [
        'targeting oracle cases (Comanche055).  Generated by gen/gen_targeting.py.',
        'Entry INTPRET, Q = label; low banks return to 25751 (ABTCONIC), high',
        'banks to 65105 (V2TERROR), stop POODOO.  The SELECTMU block is set as',
        'SELECTMU leaves it: RTX1 -2 / -10, RTX2 0 / 2, RTMU = MUE (B-36) /',
        'Core sets 1-6 free (PRIORITY -0) so INTWAKE/JOBWAKE terminate.',
        'MUM SR 6, RTSR1/MU = 1/SQRT(MU) (MUTABLE words assembled by yaYUL).',
        'INITVEL 11,2000: RINIT VINIT RTARG DELLT4 INTIME, push list 0D NUMIT',
        '  (SP), 2D E4 (rev), PUSHLOC = VAC1+4; GUESSW set by INITVEL -> RTARG',
        '  VIPRIME VTPRIME DELVEET3 (NUMIT > 0: INTSTALL + INTEGRVS precision).',
        'CDHMVR 05,3230: RACT2 VACT2 RPASS2 VPASS2 UP1 -> DIFFALT, VACT3 (over',
        '  UNVEC), DELVEET2, CSTH SNTH (TIMETHET inputs).',
        'S34/35.2 35,2526 (TPI required velocity, conic NN = 0): RPASS3 VPASS3',
        '  RACT3 VACT3 UNRM INTIME TPASS4 NN -> RTARG VPASS4 ACTCENT DELLT4',
        '  VIPRIME VTPRIME DELVEET3 DELVLVC.'], maxcycles=30000000)
    earth = [('RTX1', '77775,00000'), ('RTMU', mue), ('RTSR1/MU', rtmue_inv)]
    moonb = [('RTX1', '77765,00002'),
             ('RTMU', dp(4.902778e8 / 2.0**30 / 64, 0)), ('RTSR1/MU', rtmum_inv)]
    ig = (gets_vec('RTARG') + gets_vec('VIPRIME') + gets_vec('VTPRIME') +
          gets_vec('DELVEET3'))
    for tag, moon, ra, ang, dt, numit, e4 in (
            ('initvel_earth', False, 6.7e6, 120.0, 180000.0, 0, 0.125),
            ('initvel_earth_far', False, 6.9e6, 200.0, 300000.0, 0, 0.0277),
            ('initvel_moon', True, 1.85e6, 95.0, 250000.0, 0, 0.125),
            ('initvel_earth_prec', False, 6.7e6, 140.0, 200000.0, 1, 0.125)):
        mu = MUM if moon else MUE
        r1, v1 = circ(mu, ra, 0.0, 10.0)
        r2, _ = circ(mu, ra * 1.03, ang, 10.5)
        sets = EXEC + (moonb if moon else earth) + [
            ('VAC1+42', TRAP_LO), ('RINIT', vec(r1, 29)), ('VINIT', vec(v1, 7)),
            ('RTARG', vec(r2, 29)), ('DELLT4', dp(dt, 28)), ('INTIME', dp(1000.0, 28)),
            ('VAC1', _w(numit)), ('VAC1+2', dp(e4)), ('PUSHLOC', '@VAC1+4'),
            ('FLAGWRD0', '04000' if moon else '00000')]
        s.run(tag, '11,2000', 0o11, 'POODOO', sets, ig, ebank=7)
    cg = (['DIFFALT:dp'] + gets_vec('VACT3') + gets_vec('DELVEET2') +
          ['CSTH:dp', 'SNTH:dp'])
    for tag, ra, rp, lead, dh in (('cdh_earth', 6.75e6, 6.78e6, 4.0, 0.0),
                                  ('cdh_earth_ell', 6.70e6, 6.80e6, 9.0, 1.5)):
        r1, v1 = circ(MUE, ra, 0.0)
        v1 = [v1[0] * (1 + dh / 100.0), v1[1] * (1 - dh / 200.0), v1[2]]
        r2, v2 = circ(MUE, rp, lead)
        up = [0.0, 0.0, 0.5]
        s.run(tag, '05,3230', 0o05, 'POODOO',
              earth + [('VAC1+42', TRAP_LO), ('RACT2', vec(r1, 29)), ('VACT2', vec(v1, 7)),
                       ('RPASS2', vec(r2, 29)), ('VPASS2', vec(v2, 7)), ('UP1', vec(up))],
              cg, ebank=5)
    tg = (gets_vec('RTARG') + gets_vec('VPASS4') + ['ACTCENT:dp', 'DELLT4:dp'] +
          gets_vec('VIPRIME') + gets_vec('VTPRIME') + gets_vec('DELVEET3') +
          gets_vec('DELVLVC'))
    # inputs chosen so that dvcheck.sh reports no DV-bug run (conic INTINT)
    for tag, ra, rp, lead, dt in (('tpi_earth', 6.70e6, 6.76e6, 2.2, 216000.0),
                                  ('tpi_earth_b', 6.71e6, 6.76e6, 2.2, 200000.0)):
        r1, v1 = circ(MUE, ra, 0.0)
        r2, v2 = circ(MUE, rp, lead)
        un = [0.0, 0.0, 0.5]
        s.run(tag, '35,2526', 0o35, 'POODOO',
              EXEC + earth + [('VAC1+42', TRAP_HI), ('RACT3', vec(r1, 29)), ('VACT3', vec(v1, 7)),
                       ('RPASS3', vec(r2, 29)), ('VPASS3', vec(v2, 7)), ('UNRM', vec(un)),
                       ('INTIME', dp(5000.0, 28)), ('TPASS4', dp(5000.0 + dt, 28)),
                       ('NN', '00000'), ('FLAGWRD5', '00200')],
              tg, ebank=7)
    s.write(os.path.join(OUT, 'targeting.spec'))

if __name__ == '__main__':
    main()
