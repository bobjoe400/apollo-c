#!/usr/bin/env python3
"""Generate tools/oracle/cases/dsky.spec (Comanche055) and dsky_lm.spec
(Luminary099).  Run from tools/oracle/cases/gen:
    python3 -I gen_dsky.py && cd ../.. && make cases

Every run is an internal NVSUB "V06 Nnn" (decimal display, DECDSP) or a
verb paste (noun 0, UPDATVB): the display words DSPTAB+0..+10 that pinball
builds through MIXNOUN/DSPDCGET, the SF output routines (SFOUTABR: DEGOUTSF,
OPDEGOUT, ARTOUTSF, AROUT1SF, DP1-4OUTSF, HMSOUT, M/SOUT, 2INTOUT,
DPFRACOT, 360-CDUO), DSPDECWD/DSPDC2NR/DSPDECVN and DSPIN are compared.

Entry is NVSUB1 (bank 41), not NVSUB: NVSUBCOM selects the pinball
superbank with WRITE SUPERBNK, and the vendored yaAGC never copies a
channel-7 write into OutputChannel7 (agc_engine.c:3482 rewrites
InputChannel[7] from it), so the jump lands in bank 31.  The probe's fbank
041 sets the superbit once, and NVQTEM/NVBNKTEM/MONSAVE1/NVTEMP are poked
as NVMONOPT/NVSUBCOM would leave them.  check_banks() traces every run and
refuses one that executes in banks 30-37 (where the stale superbit would
fetch from 40-47).
DSPTAB+0..+10 = -BIT12, NOUT = 11, DSPCOUNT = -VD1 as STARTSB2 leaves them
(DSPIN's CCS on a +0 DSPTAB word goes to CCSHOLE)."""
import os, random, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agcw import _w
from specgen import Spec

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
ROOT = os.path.join(OUT, '..')
GETS = ['DSPTAB+%d' % k for k in range(11)] + ['NOUT', 'VERBREG', 'NOUNREG']
BASE = [('DSPTAB', ','.join(['73777'] * 11)), ('NOUT', '00013'),
        ('DSPCOUNT', '77754'), ('NVQTEM', '@ENDOFJOB'), ('NVBNKTEM', '00000'),
        ('MONSAVE1', '40000')]
R = random.Random(55)

def dpw(n):
    """signed integer (units 2^-28) -> sign-agreeing DP words."""
    s = -1 if n < 0 else 1
    a = abs(n)
    return '%s,%s' % (_w(s * (a >> 14)), _w(s * (a & 0o37777)))

def dprand(lim=2**28 - 1):
    return dpw(R.randint(-lim, lim))

def sprand(lim=16383):
    return _w(R.randint(-lim, lim))

def raw():
    return '%05o' % R.randint(0, 0o77777)

def vn(verb, noun):
    return '%05o' % ((verb << 7) | noun)

class Cases:
    def __init__(self, rope, comment):
        self.s = Spec(rope, comment, maxcycles=200000)
        self.rope = rope
        self.tags = []

    def run(self, tag, verb, noun, sets, mctbs=None):
        extra = [('NVTEMP', vn(verb, noun))]
        if mctbs is not None:
            extra.append(('MPAC+2', '%05o' % mctbs))
        self.s.run(tag, None, 0o41, 'ENDOFJOB POODOO DSPALARM',
                   BASE + extra + sets, GETS, ebank=7, entry='NVSUB1')
        self.tags.append(tag)

def check_banks(lines):
    """Trace every run; fail if any instruction executes in banks 30-37."""
    import re
    bad = []
    tag = None
    spec = []
    for l in lines:
        if l.startswith('run '):
            spec.append('trace 1')
        spec.append(l)
    out = subprocess.run([os.path.join(ROOT, 'bin', 'agc_probe')],
                         input='\n'.join(spec) + '\n', capture_output=True,
                         text=True, cwd=ROOT,
                         env=dict(os.environ, AGC_ORACLE_ROPES='ropes'))
    tags = [l.split()[1] for l in lines if l.startswith('run ')]
    runs = out.stderr.split('\n')
    k = -1
    for l in runs:
        f = l.split()
        if len(f) >= 2 and f[0] == '0':
            k += 1
        if len(f) >= 2 and re.match(r'^3[0-7],', f[1]):
            bad.append((tags[k] if 0 <= k < len(tags) else '?', f[1], f[2]))
    if bad:
        for b in sorted(set(bad))[:20]:
            print('BANK', *b)
        sys.exit('runs execute in banks 30-37')

def cm():
    c = Cases('Comanche055', [
        'dsky: pinball decimal display (V06 through NVSUB), Comanche055.',
        'Generated by gen/gen_dsky.py; compared by tests/oracle/dsky.c.'])
    # verb paste (noun 0): UPDATVB -> DSPDECVN of the verb
    for v in (1, 6, 9, 10, 37, 50, 77, 99):
        c.run('cm_paste_v%02d' % v, v, 0, [])
    # HMSOUT (noun 33 TIG, DP cs)
    for k, n in enumerate([1362295, -372345, 268000000, 0, 59 * 100,
                           R.randint(-2**28 + 1, 2**28 - 1)]):
        c.run('cm_n33_%d' % k, 6, 33, [('TIG', dpw(n))])
    # M/SOUT and DP3OUTSF (noun 40: TTOGO, VGDISP, DVTOTAL)
    for k, t in enumerate([12345, -12345, 359849, -359850, 400000, -5,
                           R.randint(-2**27, 2**27)]):
        c.run('cm_n40_%d' % k, 6, 40, [('TTOGO', dpw(t)), ('VGDISP', dprand(2**24)),
                                       ('DVTOTAL', dprand())])
    # DP4OUTSF degrees (LAT, LONG) and DP3 (ALT)
    for k in range(4):
        c.run('cm_n43_%d' % k, 6, 43, [('LAT', dprand()), ('LONG', dprand()),
                                       ('ALT', dprand())])
    # 2INTOUT (VHFCNT, TRKMKCNT), M/SOUT, DP4 (+MGA)
    for k in range(3):
        c.run('cm_n45_%d' % k, 6, 45, [
            ('VHFCNT', '%05o,%05o' % (R.randint(0, 99), R.randint(0, 99))),
            ('TTOGO', dprand(2**22)), ('E7,1625', dprand())])
    # AROUT1SF (masses), ARTOUTSF (trims), WHOLE (PIPAs)
    for k in range(3):
        c.run('cm_n47_%d' % k, 6, 47, [('CSMMASS', sprand()), ('LEMMASS', sprand())])
        c.run('cm_n48_%d' % k, 6, 48, [('PACTOFF', sprand()), ('YACTOFF', sprand())])
        c.run('cm_n21_%d' % k, 6, 21, [('PIPAX', sprand()), ('PIPAY', sprand()),
                                       ('PIPAZ', sprand())])
    # DEGOUTSF (CDUs, bit 15 = 180 deg)
    for k, w in enumerate([('00000', '40000', '77777'), ('00001', '37777', '40001')]
                          + [(raw(), raw(), raw()) for _ in range(2)]):
        c.run('cm_n20_%d' % k, 6, 20, [('CDUX', w[0]), ('CDUY', w[1]), ('CDUZ', w[2])])
    # OPDEGOUT (CDUT, optics trunnion) with DEGOUTSF (CDUS)
    for k, t in enumerate(['00000', '77777', '62000', '61737', '61740', '15737',
                           '37777', '57777', raw(), raw()]):
        c.run('cm_n91_%d' % k, 6, 91, [('CDUS', raw()), ('CDUT', t)])
    # DP2OUTSF (D), DP4 (VMAGI), DP3 (RTGO)
    for k in range(3):
        c.run('cm_n64_%d' % k, 6, 64, [('D', dprand()), ('VMAGI', dprand()),
                                       ('RTGO', dprand())])
    # DPFRACOT (STARSAV3)
    for k in range(3):
        c.run('cm_n88_%d' % k, 6, 88, [('STARSAV3', ','.join(dprand() for _ in range(3)))])
    # DP1OUTSF (RANGE), DP3 (RRATE), DP4 (RTHETA)
    for k in range(3):
        c.run('cm_n54_%d' % k, 6, 54, [('RANGE', dprand()), ('RRATE', dprand()),
                                       ('RTHETA', dprand())])
    # machine address nouns 01 (fraction), 02 (whole), 03 (degrees) at E7,1700
    for noun in (1, 2, 3):
        for k, w in enumerate([('00000', '37777', '40000'), ('77777', '00001', '77776'),
                               (raw(), raw(), raw())]):
            c.run('cm_n%02d_%d' % (noun, k), 6, noun, [('E7,1700', ','.join(w))],
                  mctbs=0o3700)
    # review-io-dsky: -0 and small negatives through DSPSIGN and PRSHRTMP
    # (ARTOUTSF / AROUT1SF), appended so the runs above keep their inputs
    for noun in (1, 2):
        c.run('cm_n%02d_neg' % noun, 6, noun,
              [('E7,1700', '77776,77777,77775')], mctbs=0o3700)
    c.run('cm_n47_neg', 6, 47, [('CSMMASS', '77776'), ('LEMMASS', '77775')])
    c.run('cm_n48_neg', 6, 48, [('PACTOFF', '77776'), ('YACTOFF', '77774')])
    c.run('cm_n21_neg', 6, 21, [('PIPAX', '77776'), ('PIPAY', '77775'),
                                 ('PIPAZ', '00001')])
    return c

def lm():
    c = Cases('Luminary099', [
        'dsky: pinball decimal display (V06 through NVSUB), Luminary099.',
        'Generated by gen/gen_dsky.py; compared by tests/oracle/dsky.c.'])
    for v in (6, 16, 99):
        c.run('lm_paste_v%02d' % v, v, 0, [])
    for k, n in enumerate([1362295, -372345]):
        c.run('lm_n33_%d' % k, 6, 33, [('TIG', dpw(n))])
    # 360-CDUO (CDUT) with DEGOUTSF (CDUS)
    for k, t in enumerate(['00000', '40000', '00001', '77777', raw(), raw()]):
        c.run('lm_n72_%d' % k, 6, 72, [('CDUT', t), ('CDUS', raw())])
    # DP3 (ABVEL, HDOTDISP), DP1 (HCALC1)
    for k in range(3):
        c.run('lm_n63_%d' % k, 6, 63, [('ABVEL', dprand()), ('HDOTDISP', dprand()),
                                       ('HCALC1', dprand())])
    # DP4 (RANGEDSP), M/SOUT (TTFDISP), DP1 (DELTAH)
    for k in range(3):
        c.run('lm_n68_%d' % k, 6, 68, [('RANGEDSP', dprand()), ('TTFDISP', dprand(2**22)),
                                       ('DELTAH', dprand())])
    # 2INTOUT (FUNNYDSP), DP3 (HDOTDISP), DP1 (HCALC)
    for k in range(3):
        c.run('lm_n64_%d' % k, 6, 64, [
            ('FUNNYDSP', '%05o,%05o' % (R.randint(0, 99), R.randint(0, 99))),
            ('HDOTDISP', dprand()), ('HCALC', dprand())])
    for k in range(3):
        c.run('lm_n47_%d' % k, 6, 47, [('LEMMASS', sprand()), ('CSMMASS', sprand())])
    return c

def main():
    for name, c in (('dsky', cm()), ('dsky_lm', lm())):
        check_banks(c.s.l)
        c.s.write(os.path.join(OUT, name + '.spec'))
        print(name, len(c.tags), 'runs')

if __name__ == '__main__':
    main()
