"""Generate tools/oracle/cases/core_words.spec (review-core-numeric).

The word-level MPAC API (include/agc/core/interp_words.h) against yaAGC:
each run pokes MPAC (three words, signs free to disagree), operand words
in the VAC1 work area and an interpretive snippet into VAC2USE, then
reads MPAC, MPAC+1, MPAC+2, OVFIND, DVSIGN, VAC1+24..25 and VAC1+30.

Run tags are OP<n> (one instruction) or a lane sequence name; the inputs
are the spec's set lines, which tests/oracle/core_words.c reads back.
Usage: python3 -I gen_core_words.py > ../core_words.spec
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import snip  # noqa: E402

random.seed(19690720)
ONE = 16384
MAXW = 16383


def w(v):
    """Signed word -> ones' complement octal (never -0)."""
    return '%05o' % (v if v >= 0 else 0o77777 + v)


def ws(lst):
    return ','.join(w(x) for x in lst)


def rw(lo=-MAXW, hi=MAXW):
    return random.randint(lo, hi)


def disagree(hi_lo=(1, MAXW)):
    """Major word of either sign with a minor word of the other sign."""
    hi = random.randint(*hi_lo) * random.choice((1, -1))
    lo = -random.randint(1, MAXW) if hi > 0 else random.randint(1, MAXW)
    return [hi, lo]


def dpw(v):
    """DP integer (2^-28 units) -> sign-agreeing words."""
    s = -1 if v < 0 else 1
    return [s * (abs(v) // ONE), s * (abs(v) % ONE)]


ERAS = {'MPAC': 0o154}
out = [
    '# core_words -- the word-level MPAC API (include/agc/core/interp_words.h)',
    '# against the real Comanche055 interpreter; generated by',
    '# tools/oracle/cases/gen/gen_core_words.py, read by tests/oracle/core_words.c.',
    '# MPAC is poked as three words whose signs may disagree, operands sit',
    '# in the VAC1 work area (10D DP/TP operand, 20D.. sequence inputs),',
    '# the snippet runs from VAC2USE through INTPRET to EXIT/TC ENDOFJOB.',
    'rope Comanche055',
    'entry INTPRET',
    'q VAC2USE',
    'stop ENDOFJOB',
    'stop POODOO',
    'maxcycles 200000',
    'get MPAC:tp',
    'get OVFIND',
    'get DVSIGN',
    'get FAILREG',
    'get VAC1+24:dp',
    'get VAC1+26:dp',
    'get VAC1+30',
]


# Runs where stock yaAGC's DV takes a -0 minor word in L for a borrow
# (SpToDecent; docs/modules/core-numeric.md): the quotient is one major
# LSB low there and the patched engine agrees with the C.  Left out.
YAAGC_DV_BUG = {'DDV11', 'BDDV7', 'BDDV8', 'BDDV15', 'BDDV24'}


def run(tag, body, mpac, vac):
    if tag in YAAGC_DV_BUG:
        return
    words = snip.assemble(body, eras=ERAS)
    out.extend(['set FIXLOC=@VAC1', 'set PUSHLOC=@VAC1', 'set MODE=0',
                'set MPAC=' + ws(mpac)])
    for off in sorted(vac):
        out.append('set VAC1+%d=%s' % (off, ws(vac[off])))
    words = words + ['@ENDOFJOB']
    for k in range(0, len(words), 8):
        out.append('set VAC2USE%s=%s' % ('+%d' % k if k else '', ','.join(words[k:k + 8])))
    out.append('run ' + tag)


def mpac_any():
    k = random.random()
    if k < 0.5:
        return disagree() + [rw()]
    if k < 0.8:
        return [rw(), rw(), rw()]
    return [0, rw(), rw()]


def operand_dp():
    return disagree() if random.random() < 0.6 else [rw(), rw()]


N = 16
counts = {}


def tag(op):
    counts[op] = counts.get(op, 0) + 1
    return '%s%d' % (op, counts[op])


# ---- one instruction, DP operand at 10D --------------------------------
for op in ('DAD', 'DSU', 'BDSU', 'DMP', 'DMPR', 'SIGN'):
    for _ in range(N):
        x = operand_dp()
        if op == 'SIGN' and random.random() < 0.4:
            x = [0, rw()]
        run(tag(op), ['\t\t%s\tEXIT' % op, '\t\t\t10D'], mpac_any(), {10: x})
for _ in range(N):
    run(tag('TAD'), ['\t\tTAD\tEXIT', '\t\t\t10D'], mpac_any(),
        {10: [rw(), rw(), rw()]})


def divide_pair():
    """Divisor major of a chosen class, dividend major at most as large."""
    cls = random.choice(('zero', 'one', 'small', 'big', 'big', 'big', 'near'))
    if cls == 'zero':
        b = [0, rw()]
    elif cls == 'one':
        b = [random.choice((1, -1)), rw()]
    elif cls == 'small':
        b = [rw(2, 300) * random.choice((1, -1)), rw()]
    else:
        b = [rw(300, MAXW) * random.choice((1, -1)), rw()]
    mag = abs(b[0])
    if cls == 'near':
        a0 = max(mag - random.randint(0, 1), 0)
    else:
        a0 = random.randint(0, max(mag - 1, 0))
    a = [a0 * random.choice((1, -1)), rw(), rw()]
    return a, b


for op in ('DDV', 'BDDV'):
    for _ in range(2 * N):
        a, b = divide_pair()
        if op == 'BDDV':
            run(tag(op), ['\t\tBDDV\tEXIT', '\t\t\t10D'], b + [rw()], {10: a[:2]})
        else:
            run(tag(op), ['\t\tDDV\tEXIT', '\t\t\t10D'], a, {10: b})

# ---- unary ---------------------------------------------------------------
for op in ('DSQ', 'ROUND', 'DCOMP', 'ABS', 'SIN', 'COS'):
    for _ in range(N):
        run(tag(op), ['\t\t%s\tEXIT' % op], mpac_any(), {})
for _ in range(2 * N):
    k = random.random()
    if k < 0.6:
        m = [rw(1, MAXW), rw(), rw()]
    elif k < 0.8:
        m = [0, rw(), rw()]
    else:
        m = [random.choice((-1, 0)), rw(), rw()]
    if m[0] == -1 and m[1] < 0:
        m[1] = -m[1]
    run(tag('SQRT'), ['\t\tSQRT\tEXIT'], m, {})
for op in ('ASIN', 'ACOS'):
    for _ in range(N):
        m = [rw(-8192, 8192), rw(), rw()]
        if random.random() < 0.3:
            m[0] = random.choice((8192, -8192, 8191, 8193, 0))
        run(tag(op), ['\t\t%s\tEXIT' % op], m, {})

# ---- shifts and NORM -----------------------------------------------------
for op, counts_ in (('SR', (1, 2, 4, 7, 11, 13, 14, 15, 20, 28, 30, 41)),
                    ('SRR', (1, 3, 13, 14, 15, 29)),
                    ('SL', (1, 2, 3, 4, 8, 14)),
                    ('SLR', (1, 2, 5, 14))):
    for n in counts_:
        run(tag(op), ['\t\t%s\tEXIT' % op, '\t\t\t%dD' % n], mpac_any(), {})
for _ in range(N):
    m = mpac_any()
    if random.random() < 0.5:
        m = [0, 0, rw()] if random.random() < 0.3 else [rw(-40, 40), rw(), rw()]
    run(tag('NORM'), ['\t\tNORM\tEXIT', '\t\t\t30D'], m, {})

# ---- lane sequences --------------------------------------------------------
D1_32 = [512, 0]
DPHALF = [8192, 0]
D1_64 = [256, 0]

# PARAM R1A (PUSH BDSU D1/32) then one GETX WLOOP pass (CONIC_SUBROUTINES p.1292)
WLOOP = ['\t\tDLOAD\tBDSU', '\t\t\t20D', '\t\t\t22D', '\t\tSTODL\t24D', '\t\t\t10D',
         '\t\tPUSH\tDSQ', '\t\tTLOAD\tPDDL', '\t\t\tMPAC', '\t\t\t24D',
         '\t\tSR4\tTAD', '\t\tSQRT\tROUND', '\t\tDAD', '\t\tEXIT']
for wv in (329590, 8724671, 20827920):
    run(tag('WLOOP'), WLOOP, [0, 0, 0], {10: dpw(wv), 20: [255, MAXW], 22: D1_32})
for _ in range(10):
    run(tag('WLOOP'), WLOOP, [0, 0, 0],
        {10: [rw(0, 3000), rw()], 20: [rw(0, 511), rw()], 22: D1_32})
# POLYCOEF: DSQ NORM X1 DMP R1A (R1A made as above)
POLY = ['\t\tDLOAD\tBDSU', '\t\t\t20D', '\t\t\t22D', '\t\tSTODL\t24D', '\t\t\t10D',
        '\t\tDSQ\tNORM', '\t\t\t30D', '\t\tDMP\tEXIT', '\t\t\t24D']
for _ in range(8):
    run(tag('POLYCOEF'), POLY, [0, 0, 0],
        {10: [rw(1, 9000), rw()], 20: [rw(0, 511), rw()], 22: D1_32})
# APSIDES GETECC: DMP SL4 R1A, BDSU SQRT D1/64 (p.1303)
GETECC = ['\t\tDLOAD\tBDSU', '\t\t\t20D', '\t\t\t22D', '\t\tSTODL\t24D', '\t\t\t26D',
          '\t\tDMP\tSL4', '\t\t\t24D', '\t\tBDSU\tSQRT', '\t\t\t28D', '\t\tEXIT']
for p in ([1024, 0], [rw(100, 1000), rw()], [rw(100, 1000), rw()], [rw(100, 1000), rw()]):
    run(tag('GETECC'), GETECC, [0, 0, 0],
        {20: [255, MAXW], 22: D1_32, 26: p, 28: D1_64})
for _ in range(4):
    run(tag('GETECC'), GETECC, [0, 0, 0],
        {20: [rw(300, 511), rw()], 22: D1_32, 26: [rw(100, 1000), rw()], 28: D1_64})
# DELCOMP (ANGLFIND p.407): SIN, COS, SR2, BDSU DPHALF = 1-cos A, COF DSQ DMP DAD SL3
DELCOMP = ['\t\tSETPD\tPUSH', '\t\t\t0', '\t\tSIN\tPDDL', '\t\tCOS\tPUSH',
           '\t\tSR2\tPDDL', '\t\tBDSU', '\t\t\t22D', '\t\tPDDL\tDSQ', '\t\t\t20D',
           '\t\tDMP\tDAD', '\t\t\t4', '\t\t\t2', '\t\tSL3\tEXIT']
for _ in range(10):
    a = [rw(-60, 60), rw(), rw()] if random.random() < 0.7 else mpac_any()
    run(tag('DELCOMP'), DELCOMP, a, {20: [rw(-8000, 8000), rw()], 22: DPHALF})
# ATMAG TBUP and AT (ASCENT_GUIDANCE p.843)
ATMAG = ['\t\tDMP\tDMP', '\t\t\t22D', '\t\t\t24D', '\t\tSL3\tPDDL', '\t\t\t26D',
         '\t\tSR1\tDAD', '\t\tDSU', '\t\t\t28D', '\t\tSTODL\t26D', '\t\t\t22D',
         '\t\tSR1\tDDV', '\t\t\t26D', '\t\tEXIT']
for _ in range(10):
    run(tag('ATMAG'), ATMAG, [rw(500, 4000), rw(), 0],
        {22: [rw(1500, 2500), rw()], 24: [6400, 0], 26: [rw(1000, 6000), rw()],
         28: [rw(1, 50), rw()]})
# MAINENG TGO, TTOGO (p.846): DMP TBUP, DSU TTO, STORE TGO, SR 11D, DCOMP
MAINENG = ['\t\tDMP\tDSU', '\t\t\t20D', '\t\t\t22D', '\t\tSTORE\t24D',
           '\t\tSR\tDCOMP', '\t\t\t11D', '\t\tEXIT']
for _ in range(10):
    run(tag('MAINENG'), MAINENG, [rw(100, 8000), rw(), rw()],
        {20: [rw(1000, 9000), rw()], 22: [rw(1, 40), rw()]})
# ASCENT: DLOAD TBUP DSU TGO DDV TBUP (1 - TGO/TBUP, p.845)
ASCENT = ['\t\tDLOAD\tDSU', '\t\t\t20D', '\t\t\t22D', '\t\tDDV\tEXIT', '\t\t\t20D']
for _ in range(10):
    run(tag('ASCENT'), ASCENT, [0, 0, 0],
        {20: disagree((1000, 9000)), 22: disagree((100, 900))})
# HUNTEST1 ALP chain (REENTRY p.866): DLOAD A0 DMP 2C1HS DDV V1 DDV V1 DDV LEWD
HUNT = ['\t\tDLOAD\tDMP', '\t\t\t20D', '\t\t\t22D', '\t\tDDV\tDDV', '\t\t\t24D',
        '\t\t\t24D', '\t\tDDV\tEXIT', '\t\t\t26D']


run(tag('HUNTEST'), HUNT, [0, 0, 0],
    {20: dpw(35781135), 22: dpw(5797757), 24: dpw(165392454), 26: dpw(40265318)})
for _ in range(7):
    run(tag('HUNTEST'), HUNT, [0, 0, 0],
        {20: [rw(500, 4000), rw()], 22: [rw(200, 800), rw()],
         24: [rw(8000, 12000), rw()], 26: [rw(2000, 5000), rw()]})
# LAT-LONG / ARCTAN style: SR1 leaves MPAC+2, ASIN takes it into SQRTSUB
ASR = ['\t\tDLOAD\tSR1', '\t\t\t20D', '\t\tASIN\tEXIT']
for _ in range(8):
    run(tag('SR1ASIN'), ASR, [0, 0, 0], {20: [rw(-8000, 8000), rw()]})
print('\n'.join(out))
