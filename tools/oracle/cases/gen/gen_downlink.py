"""Downlink oracle cases: every downlist of both ropes, sent by the rope.

Writes cases/downlink_csm.spec and cases/downlink_lm.spec (run from
tools/oracle; the AGC sources are
read from --src, the Virtual AGC Apollo-11 tree).  For each list code of
each rope one run loads a known erasable state into every word the
rope's DOWNLINK_LISTS names (a fixed pseudo-random word per name and
offset; never -0), points DNTMGOTO at DNPHASE1 with DNLSTCOD = the code,
and lets yaAGC run DODOWNTM on its own DOWNRUPTs (agc_probe 'downlink':
every other interrupt suppressed, the main program a TC-to-itself loop in
VAC1 at 0450) for 101 word pairs: the ID word, the 99 data words and the
next list's ID.  The probe prints the loaded words by ECADR (LOAD), the
channels the lists send (CHAN) and each word pair (DNLINK).
tests/io/service_verbs_telemetry.c loads the same words through the
erasable map and compares the C downlink word for word.

Constraints on the state: TIME2, TIME1 are 14-bit counts (small values so
TIME1 does not carry in 2 s); CMDAPMOD holds one of the four values the
entry DAP stores (-1, +0, +1, -0: the C keeps it as an enum); SPARE
(ERASZERO, register 7) and its +1 (ARUPT) are registers, not loaded.
"""
import argparse
import os
import re
import zlib

ROPES = (('Comanche055', 5, 'csm'), ('Luminary099', 6, 'lm'))  # list codes 0..n-1 (DNTABLE)
WORDS = 101                                        # ID + 99 words + next ID
LOOP = 0o450                                       # TC 0450 (VAC1): the main program
FIXED = {'TIME2': [1, 0o2000], 'CMDAPMOD': [1]}    # constrained words (see above)
SKIP = {'SPARE', 'UNKNOWN', 'DNTMBUFF'}


def operands(path):
    """(name, offset, words) of every nDNADR in DOWNLINK_LISTS.agc."""
    out = []
    for line in open(path):
        line = line.split('#')[0]
        m = re.search(r'-?(\d)DNADR\s+(\S+)(?:\s*\+\s*(\d+)D?)?', line)
        if m and m.group(2) not in SKIP:
            out.append((m.group(2), int(m.group(3) or 0), 2 * int(m.group(1))))
    return out


def word(name, k):
    """The known word of NAME +k: 1 .. 77776, deterministic."""
    return zlib.crc32(('%s+%d' % (name, k)).encode()) % 0o77776 + 1


def sets(ops):
    """set lines: the words of each name, up to 8 consecutive per line."""
    seen, runs = set(), {}
    for name, off, n in ops:
        for k in range(off, off + n):
            if (name, k) not in seen:
                seen.add((name, k))
                runs.setdefault(name, []).append(k)
    lines = []
    for name in sorted(runs):
        ks = sorted(runs[name])
        i = 0
        while i < len(ks):
            j = i
            while j + 1 < len(ks) and ks[j + 1] == ks[j] + 1 and j + 1 - i < 8:
                j += 1
            ws = [FIXED[name][k] if name in FIXED and k < len(FIXED[name]) else word(name, k) for k in ks[i:j + 1]]
            lines.append('set %s=%s' % (name if ks[i] == 0 else '%s+%d' % (name, ks[i]), ','.join('%o' % w for w in ws)))
            i = j + 1
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', required=True, help='Apollo-11 source tree (Comanche055/, Luminary099/)')
    ap.add_argument('--out', default='cases', help='directory of the .spec files')
    a = ap.parse_args()
    for rope, codes, tag in ROPES:
        ops = operands(os.path.join(a.src, rope, 'DOWNLINK_LISTS.agc'))
        L = ['# generated by gen/gen_downlink.py', 'rope %s' % rope]
        for code in range(codes):
            L += ['entry %o' % LOOP, 'maxcycles 40000000', 'set %o=%o' % (LOOP, LOOP),
                  'set DNTMGOTO=@DNPHASE1', 'set DNLSTCOD=%o' % code]
            L += sets(ops)
            L += ['downlink %d' % WORDS, 'run %s_%d' % (rope, code)]
        open(os.path.join(a.out, 'downlink_%s.spec' % tag), 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
