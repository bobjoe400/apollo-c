"""LM P07 drift filter (ALFLT) and PIP-rate (AINGOTN) oracle cases.

Writes cases/systems_test_lm.spec (run from tools/oracle).  ALFLT runs
from its entry to PERFERAS +1 (the EXIT before TC ATIGINC) on E5 with
random filter words; XSM and DELV get sign-agreeing words (the C keeps
them as values), every other word may disagree in sign.  The PIP cases
enter PIPJOBB +10 (CCS DATAPL +1, after CHECKG) with NDXCTR = 1 and stop
at COAALIGN.  tests/io/service_verbs_telemetry.c replays them.
"""
import random

def word(rng, mag):
    v = rng.randint(-mag, mag)
    return v if v >= 0 else 0o77777 + v

def agree(words):
    out = list(words)
    for i in range(0, len(out) - 1, 2):
        hneg, lneg = out[i] >= 0o40000, out[i + 1] >= 0o40000
        if hneg != lneg and out[i] not in (0, 0o77777) and out[i + 1] not in (0, 0o77777):
            out[i + 1] = 0o77777 - out[i + 1]
    return out

def sets(name, words):
    lines = []
    base, off = (name.split('+') + ['0'])[:2]
    off = int(off)
    for i in range(0, len(words), 8):
        chunk = ','.join('%o' % w for w in words[i:i + 8])
        if base.startswith('E4,'):
            nm = 'E4,%o' % (int(base[3:], 8) + off + i)
        else:
            nm = '%s+%d' % (base, off + i) if off + i else base
        lines.append('set %s=%s' % (nm, chunk))
    return lines

def main():
    rng = random.Random(7)
    L = ['# generated by gen/gen_systems_test_lm.py', 'rope Luminary099',
         'entry ALFLT', 'ebank 5', 'maxcycles 3000000',
         'stop PERFERAS+1', 'stop POODOO', 'stop BAILOUT']
    L += ['get AINLA+%d' % k for k in range(100)]
    for case in range(4):
        L += ['set FIXLOC=@VAC1', 'set PUSHLOC=@VAC1']
        L += sets('XSM', agree([word(rng, 0o20000) for _ in range(18)]))
        L += sets('DELVX', agree([word(rng, 0o400) for _ in range(6)]))
        L += sets('AINLA+10', [word(rng, 0o10000) for _ in range(12)])
        L += sets('AINLA+28', [word(rng, 0o4000) for _ in range(24)])
        L += sets('AINLA+52', [word(rng, 0o4000) for _ in range(8)])
        L += sets('AINLA+62', [word(rng, 0o1000) for _ in range(14)])
        L += ['set AINLA+9=%s' % ('77776' if case % 2 == 0 else '1'),
              'set AINLA+61=%s' % ('77776' if case == 0 else '0'),
              'set AINLA+8=%o' % (144 - 12 * case)]
        L += sets('E4,1400', [word(rng, 0o20000) for _ in range(18)])
        L += sets('E4,1422', [word(rng, 0o10000) for _ in range(40)])
        L.append('run alflt_%d' % case)
    L += ['entry PIPJOBB+10', 'clearstops', 'stop COAALIGN', 'stop CCSHOLE',
          'cleargets', 'get DSPTEM2', 'get DSPTEM2+1', 'get W+62', 'get W+63']
    pips = ['0,144,3,17500,21,30,7,12345', '0,77000,5,1000,21,76000,2,30000',
            '0,144,7,17500,21,30,3,12345', '0,1,2,0,21,0,0,10000']
    for n, p in enumerate(pips):
        L += ['set FIXLOC=@VAC1', 'set PUSHLOC=@VAC1', 'set W+12=1', 'set W+58=%s' % p,
              'run pip_%d' % n]
    open('cases/systems_test_lm.spec', 'w').write('\n'.join(L) + '\n')

main()
