#!/usr/bin/env python3
"""Generate tools/oracle/cases/entry.spec (Comanche055): a chain of entry
guidance passes.  Each stage after the first starts from the complete
erasable memory the previous stage left (copied word for word by running
the probe here), plus that pass's average-G data, so the AGC side sees the
state its own earlier passes built, as in flight; the C test runs the same
chain on its own state.  Run from tools/oracle/cases/gen:
    python3 -I gen_entry.py && cd ../.. && make cases"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agcw import sp, dp, vec, _w
from specgen import Spec, gets_dp, gets_vec, probe

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
GOTO = {'INITROLL': '52260', 'HUNTEST': '52373', 'UPCONTRL': '53035',
        'KEP2': '53317', 'PREFINAL': '53333', 'PREDICT3': '53343'}

def addrs():
    """Every erasable word but the registers/counters 0000-0060."""
    a = ['%04o' % k for k in range(0o61, 0o1400)]
    for b in range(3, 8):
        a += ['E%d,%04o' % (b, k) for k in range(0o1400, 0o2000)]
    return a

def full_dump(spec_lines_for_run, tag):
    """Run one stage several times with gets covering all of erasable."""
    words = {}
    al = addrs()
    for i in range(0, len(al), 240):
        part = al[i:i + 240]
        lines = list(spec_lines_for_run)
        k = lines.index('run ' + tag)
        lines[k:k] = ['cleargets'] + ['get ' + n for n in part]
        res = probe(lines)[tag]
        for n in part:
            words[n] = res[n]
    return words

def dump_sets(words):
    """Consecutive words as <= 8-word set lines with explicit addresses."""
    al = addrs()
    out, i = [], 0
    while i < len(al):
        n = al[i]
        bank = n.split(',')[0] if ',' in n else None
        chunk = [words[n]]
        j = i + 1
        while j < len(al) and len(chunk) < 8:
            m = al[j]
            if (',' in m) != (bank is not None) or (bank and m.split(',')[0] != bank):
                break
            chunk.append(words[m])
            j += 1
        out.append((n, ','.join(chunk)))
        i = j
    return out

def state(rkm, vkms, gam_deg, along_deg, drag_g, lift):
    """Inertial state in the x-y plane, `along_deg` before the target
    direction (x axis rotated); drag (g) along -V and lift along +up."""
    re = 6378166.0
    r = re + rkm * 1e3
    a = math.radians(along_deg)
    ur = [math.cos(a), math.sin(a), 0.0]
    ut = [-math.sin(a), math.cos(a), 0.0]
    g = math.radians(gam_deg)
    v = vkms * 1e3
    vv = [v * (math.cos(g) * ut[k] + math.sin(g) * ur[k]) for k in range(3)]
    uv = [x / v for x in vv]
    acc = drag_g * 9.80665
    dvref = [(-uv[k] + lift * ur[k]) * acc * 2.0 / 100 for k in range(3)]   # m/cs per 2 s
    pulses = [x * 100 / 0.0585 for x in dvref]   # m/cs -> m/s -> 5.85 cm/s pulses
    return ([x * r for x in ur], [x / 100 for x in vv], [x / 2 for x in ur],
            [int(round(p)) for p in pulses], dvref)

# Executive core sets: the running job in set 0, sets 1-6 free (PRIORITY
# = -0), so a mode change (NEWMODEX -> MMDSPLAY -> NOVAC) finds a core set;
# the running job gets priority 37 so the PRIO30 display job does not take
# over (in flight it would run until it waits for the DSKY).
EXEC = [('NEWJOB', '00000'), ('PRIORITY', '37401')] + [('%04o' % (0o167 + 12 * k), '77777')
                                  for k in range(1, 7)]

def avg_sets(st, t):
    r, v, ur, delv, dvref = st
    return [('RN', vec(r, 29)), ('VN', vec(v, 7)), ('PIPTIME', dp(t, 28)),
            ('UNITR', vec(ur)), ('DELV', ','.join('%s,00000' % _w(p) for p in delv)),
            ('DELVREF', vec(dvref, 7))]

OUTS = (['D:dp', 'V:dp', 'VSQUARE:dp', 'LEQ:dp', 'RDOT:dp', 'THETAH:dp',
         'LATANG:dp', 'ROLLC:dp', 'L/D:dp', 'L/D1:dp', 'K2ROLL:dp', 'GOTOADDR',
         'A0:dp', 'A1:dp', 'VL:dp', 'GAMMAL:dp', 'LEWD:dp', 'DIFF:dp', 'Q7:dp',
         'DTEAROT:dp', 'L/DCALC:dp', 'Q2:dp', 'KLAT:dp', 'LAD:dp', 'LOD:dp',
         'CM/FLAGS', 'FLAGWRD7', 'FX', 'FX+1', 'FX+2', 'FX+3', 'FX+4', 'FX+5',
         'JJ', 'GRAD', 'PREDANG'] + gets_vec('UNI') + gets_vec('RT') +
        gets_vec('RTINIT'))

def main():
    s = Spec('Comanche055', [
        'entry oracle cases (Comanche055).  Generated by gen/gen_entry.py.',
        'A chain of entry guidance passes; entry INTPRET, Q = label (bank 25).',
        'entry_startent: STARTENT (P63 initialisation, STARTEN1/LALOTORV/',
        '  EARROT1) from the pad loads LADPAD LODPAD HEADSUP LAT(SPL) LNG(SPL)',
        '  and RN VN PIPTIME UNITR, UNITW (pad, polar axis); stop SERVNOUT.',
        'entry_pass*: SCALEPOP (TARGETNG, REFAZE10, GOTO GOTOADDR, the phase,',
        '  ENDEXIT) with that pass\'s RN VN PIPTIME UNITR DELV (pulses) DELVREF;',
        '  stop OVERNOUT (the basic word after ENDEXIT\'s EXIT), STEEROFF or',
        '  SERVNOUT.  Each pass first restores all of erasable (0061-1377,',
        '  E3-E7) from the previous stage\'s end state (the long set blocks),',
        '  then the new average-G data; a forced GOTOADDR is noted per pass.',
        '  Core sets 1-6 are made free (PRIORITY = -0) each pass so that a mode',
        '  change (RTB P64 / P67 -> NEWMODEX -> NOVAC) gets its display job.',
        'GOTOADDR words: INITROLL 52260 HUNTEST 52373 UPCONTRL 53035 KEP2',
        '  53317 PREFINAL 53333 PREDICT3 53343.'], maxcycles=3000000)
    pad = [('LADPAD', sp(0.3)), ('LODPAD', sp(0.18)), ('HEADSUP', '00001'),
           ('LAT(SPL)', dp(0.012)), ('LNG(SPL)', dp(0.0)),
           ('UNITW', vec([0.0, 0.0, 0.99999994]))]
    st0 = state(122.0, 11.0, -6.5, 25.0, 0.0, 0.0)
    head = list(s.l)
    s.run('entry_startent', '25,2000', 0o25, 'SERVNOUT', EXEC + pad + avg_sets(st0, 0.0),
          OUTS, ebank=7)
    prev = full_dump(s.l, 'entry_startent')
    passes = [
        ('entry_pass_initroll', state(118.0, 10.99, -6.3, 24.6, 0.08, 0.0), 200.0, None),
        ('entry_pass_initroll2', state(85.0, 10.8, -4.5, 22.0, 1.2, 0.2), 4000.0, None),
        ('entry_pass_huntest', state(70.0, 10.2, -0.5, 20.0, 3.5, 0.25), 6000.0, None),
        ('entry_pass_next', state(69.5, 10.1, -0.2, 19.6, 3.3, 0.25), 6200.0, None),
        ('entry_pass_upcontrl', state(68.0, 9.9, 0.4, 18.5, 2.6, 0.25), 7000.0, 'UPCONTRL'),
        ('entry_pass_upcontrl2', state(70.0, 9.85, 0.6, 18.2, 2.2, 0.25), 7200.0, None),
        ('entry_pass_kep2', state(80.0, 8.9, 0.8, 14.0, 0.15, 0.0), 11000.0, 'KEP2'),
        ('entry_pass_predict3', state(55.0, 6.2, -3.0, 6.0, 2.2, 0.2), 20000.0, 'PREDICT3'),
        ('entry_pass_predict3b', state(45.0, 4.0, -4.5, 3.0, 2.8, 0.2), 25000.0, 'PREDICT3')]
    for tag, st, t, force in passes:
        sets = dump_sets(prev) + EXEC + avg_sets(st, t)
        if force:
            sets.append(('GOTOADDR', GOTO[force]))
        s.comment('%s: %s' % (tag, ('GOTOADDR forced to ' + force) if force
                              else 'GOTOADDR as the previous pass left it'))
        s.run(tag, '25,2115', 0o25, 'OVERNOUT STEEROFF SERVNOUT', sets, OUTS, ebank=7)
        prev = full_dump(head + s.l[len(head):], tag)
    # ---- CM body attitude ----------------------------------------------
    s.comment('CM body attitude: CM/POSE 37,3470 (basic TC INTPRET) through',
              '  CM/POSE2 and CM/TRIO to its final EXIT: stop CM/ATUP 37,3655.',
              '  VN UNITR UNITW REFSMMAT OLDUYA AOG/PIP AIG/PIP AMG/PIP (CDU, 2s',
              '  complement) -> -VREL UXA/2 UYA/2 UZA/2 OLDUYA UBX/2 UBY/2 UBZ/2,',
              '  push list 6D -(ROLL/180)/2, 7D -(BETA/180)/2, 8D -(ALFA/180)/2',
              '  (high words; each DP store overlaps the next), 10D -(GAMA/180)/2.')
    from gen_imu import mat, rows_half, mwords
    pg = (gets_vec('-VREL') + gets_vec('UXA/2') + gets_vec('UYA/2') +
          gets_vec('UZA/2') + gets_vec('OLDUYA') + gets_vec('UBX/2') +
          gets_vec('UBY/2') + gets_vec('UBZ/2') +
          ['VAC1+6', 'VAC1+7', 'VAC1+8:dp', 'VAC1+10:dp'])
    def cdu(deg):
        return '%05o' % (int(round(deg / 360.0 * 32768)) & 0o77777)
    for tag, st, ang, gim in (
            ('cm_pose_a', state(90.0, 10.8, -4.5, 22.0, 1.2, 0.2), [0.1, 0.2, -0.3], [10.0, 20.0, 5.0]),
            ('cm_pose_b', state(60.0, 7.5, -2.0, 10.0, 3.0, 0.2), [1.0, -0.5, 0.7], [170.0, 300.0, 25.0]),
            ('cm_pose_slow', state(40.0, 0.25, -30.0, 3.0, 1.0, 0.0), [0.0, 0.3, 0.2], [200.0, 45.0, 350.0])):
        r, v, ur, delv, dvref = st
        s.run(tag, None, 0o37, 'CM/ATUP',
              [('VN', vec(v, 7)), ('UNITR', vec(ur)), ('UNITW', vec([0.0, 0.0, 0.99999994])),
               ('REFSMMAT', mwords(rows_half(mat(ang)))),
               ('OLDUYA', vec([0.0, 0.5, 0.0])),
               ('AOG/PIP', ','.join(cdu(x) for x in gim))], pg,
              entry='37,3470', ebank=7)
    s.write(os.path.join(OUT, 'entry.spec'))

if __name__ == '__main__':
    main()
