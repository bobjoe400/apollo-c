#!/usr/bin/env python3
"""Generate tools/oracle/cases/align.spec (Comanche055) and align_lm.spec
(Luminary099) for the prog-align lane.  Run from tools/oracle/cases/gen:
python3 -I gen_align.py && cd ../.. && make cases

Every routine is interpretive and ends with RVQ (or GOTO to the saved
QPRET): entry INTPRET, Q = label, QPRET (VAC1+42) = an EXIT / TC <stop>
pair in the same half of fixed memory (low banks 0-17, high 20-37)."""
import math, os, random, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agcw import dp, vec, _w
from specgen import Spec, gets_dp

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
VAC4 = 0o605                # unswitched, same address in both ropes
# EXIT / TC POODOO at 12,3742 (both ropes); LM P39P79 34,3456 EXIT / TC
# DSPLY81; CM V2TERROR 32,3105 EXIT / TC POODOO.
TRAP_LO = [('VAC1+42', '25742')]
TRAP_HI_LM = [('VAC1+42', '71456')]
TRAP_HI_CM = [('VAC1+42', '65105')]

def cdu(deg):
    """CDU counter pattern: 2's complement, 2^15 = 360 deg."""
    return '%05o' % (int(round(deg / 360.0 * 32768)) & 0o77777)

def half_unit(v):
    n = math.sqrt(sum(x * x for x in v))
    return [x / n / 2 for x in v]

def rot(ax, a):
    c, s = math.cos(a), math.sin(a)
    if ax == 0:
        return [[1, 0, 0], [0, c, -s], [0, s, c]]
    if ax == 1:
        return [[c, 0, s], [0, 1, 0], [-s, 0, c]]
    return [[c, -s, 0], [s, c, 0], [0, 0, 1]]

def mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)]
            for i in range(3)]

def mat(angles):
    return mul(mul(rot(0, angles[0]), rot(1, angles[1])), rot(2, angles[2]))

def mwords(m):
    return ','.join(vec([x / 2 for x in r]) for r in m)

def mpac_vec(v, scale=0):
    """Vector MPAC: X at MPAC,+1; MPAC+2 unused; Y at +3,+4; Z at +5,+6."""
    w = [dp(c, scale) for c in v]
    return '%s,00000,%s,%s' % (w[0], w[1], w[2])

MPAC_VEC_GETS = ['MPAC:dp', 'MPAC+3:dp', 'MPAC+5:dp']

def lm():
    s = Spec('Luminary099', [
        'prog-align oracle cases (Luminary099).  Generated by gen/gen_align.py.',
        'QPRET (VAC1+42) = 71456 (P39P79 34,3456: EXIT, TC DSPLY81), stop',
        '  DSPLY81, for banks 20-37; 25742 (12,3742: EXIT, TC POODOO) for 0-17.',
        'RRNB 23,2041 (ebank 7): TANGNB, TANGNB+1 = trunnion, shaft CDU',
        '  (2s complement) -> 32D (VAC1+32..37) half-unit NB line of sight.',
        'RRANGLES 13,2133: MPAC = half-unit NB LOS (vector mode), RADMODES',
        '  ANTENBIT 04000 = RR in mode 2 -> MODEA, MODEB (T, S CDU words);',
        '  LOS along Y: BOVB LUNDESCH (stop LUNDESCH).',
        'SCALEVEC 32,2132 (ebank 3): RATT1 (VAC1+14, m 2^27), VATT1 (VAC1+20,',
        '  m/cs 2^5), REFSMMAT (half unit) -> MPAC vector words (RX VX RY VY RZ',
        '  VZ in MPAC, +1, +3, +4, +5, +6) and VATT1 (V, rounded, sign-agreed).',
        'R05 CONV4 42,3636 .. SBANDEX (stop 42,3746 = CA EXTVBACT), ebank 4:',
        '  RATT (VAC1, earth sphere 2^29 m), REFSMMAT identity, CDUs 0 ->',
        '  PITCHANG, YAWANG (revs).'])
    for tag, t, sh in (('rrnb_a', -25.0, 30.0), ('rrnb_b', 10.0, 200.0),
                       ('rrnb_c', -70.0, -135.0)):
        s.run(tag, 'RRNB', 0o23, 'DSPLY81',
              TRAP_HI_LM + [('TANGNB', cdu(t) + ',' + cdu(sh))],
              gets_dp('VAC1+32', 3), ebank=0o7)
    rr = [('rrangles_a', [0.3, 0.4, 0.8], False),
          ('rrangles_b', [-0.6, -0.2, -0.3], False),
          ('rrangles_mode2', [0.5, -0.7, 0.1], True),
          ('rrangles_alongy', [0.0, 1.0, 0.0], False),
          ('rrangles_y0', [0.6, 0.0, -0.8], False),     # ASIN(0): -0 words
          ('rrangles_x0', [0.0, 0.3, -0.9], True)]
    rnd = random.Random(52)
    for k in range(12):   # every ARCTRIG octant, both RR modes
        rr.append(('rrangles_r%d' % k, [rnd.uniform(-1, 1) for _ in range(3)],
                   k % 2 == 1))
    for tag, los, mode2 in rr:
        s.run(tag, 'RRANGLES', 0o13, 'POODOO LUNDESCH',
              TRAP_LO + [('MPAC', mpac_vec(half_unit(los))), ('MODE', '77776'),
                      ('RADMODES', '04000' if mode2 else '00000')],
              ['MODEA', 'MODEA+1', 'MODEB', 'MODEB+1'])
    ref = mat([0.4, -0.3, 1.1])
    for tag, r, v, m in (
            ('scalevec_a', [1.0e6, 2.5e5, -1.2e6], [1.2, -0.9, 0.35], ref),
            ('scalevec_small', [-93.6, -62.4, 31.0], [-9.144e-4, -6.1e-4, 3e-4],
             [[1, 0, 0], [0, 1, 0], [0, 0, 1]]),
            ('scalevec_b', [-1.7e6, 3.3e5, 4.4e5], [-0.4, 1.5, -0.8],
             mat([2.5, 0.7, -2.0]))):
        s.run(tag, 'SCALEVEC', 0o32, 'DSPLY81',
              TRAP_HI_LM + [('VAC1+14', vec(r, 27)), ('VAC1+20', vec(v, 5)),
                      ('REFSMMAT', mwords(m))],
              ['MPAC', 'MPAC+1', 'MPAC+3', 'MPAC+4', 'MPAC+5', 'MPAC+6',
               'VAC1+20', 'VAC1+22', 'VAC1+24'], ebank=0o3)
    # ---- S-band (R05) angle part: CONV4 .. SBANDEX ----
    ident = mwords([[1, 0, 0], [0, 1, 0], [0, 0, 1]])
    for tag, r in (('sband_lm_a', [-3.0e8, 1.0e8, -2.0e8]),
                   ('sband_lm_b', [2.0e8, 2.5e8, 1.0e8]),
                   ('sband_lm_c', [1.0e8, -3.0e8, 2.0e7]),
                   ('sband_lm_d', [-1.5e8, -2.0e8, 3.0e8])):
        s.run(tag, 'CONV4', 0o42, '42,3746',
              [('VAC1', vec(r, 29)), ('REFSMMAT', ident)],
              ['PITCHANG:dp', 'YAWANG:dp'], ebank=0o4)
    # ---- AOTMARK: OANB, OPTAXIS (stop GETMKS), SURFSTAR + AVEIT ----
    def sp_ones(deg):
        """SP ones' complement word of an angle scaled by pi (half revs)."""
        v = int(round(deg / 180.0 * 16384))
        return '%05o' % (v if v >= 0 else (0o77777 + v))
    aot = [('oanb_a', 60.0, 45.0, 10.0), ('oanb_b', 0.0, 45.0, 0.0),
           ('oanb_c', -60.0, 45.0, -10.0), ('oanb_d', 120.0, 45.0, 35.0),
           ('oanb_e', 180.0, 45.0, 0.0), ('oanb_f', -120.0, 45.0, -35.0),
           ('oanb_coas', 17.3, -23.9, 0.0)]
    for tag, az, el, rot in aot:
        s.run(tag, 'OANB', 0o4, 'POODOO',
              TRAP_LO + [('VAC1+8', cdu(az) + ',' + cdu(el))],
              gets_dp('SCAXIS', 3) + gets_dp('VAC1+18', 3) + gets_dp('VAC1+24', 3),
              ebank=0o7)
        s.run(tag.replace('oanb', 'optaxis'), 'OPTAXIS', 0o7, 'GETMKS',
              [('VAC1+8', cdu(az) + ',' + cdu(el) + ',' + sp_ones(rot))],
              gets_dp('VAC1+12', 3) + gets_dp('VAC1+18', 3), ebank=0o7)
    x1 = '%05o' % (0o77777 - VAC4)
    rnd = random.Random(57)
    surf = [('surfstar_zero', 0.0, 0.0), ('surfstar_spiral', 0.0, 200.0)]
    for k in range(8):
        surf.append(('surfstar_r%d' % k, rnd.uniform(-180, 180),
                     rnd.uniform(-180, 180)))
    for k, (tag, cur, spi) in enumerate(surf):
        oa = half_unit([rnd.uniform(-1, 1) for _ in range(3)])
        xp = [c / 2 for c in half_unit([rnd.uniform(-1, 1) for _ in range(3)])]
        yp = [c / 2 for c in half_unit([rnd.uniform(-1, 1) for _ in range(3)])]
        cd = [rnd.uniform(-180, 180) for _ in range(3)]
        mark = ','.join([cdu(cd[0]), cdu(cur), cdu(cd[1]), cdu(spi), cdu(cd[2]),
                         '00000'])
        # AVEIT runs on (interpretive code: no stop there) with MKDEX = 1/8
        # (one vector): 24D = VSR3 V/SC of the SURFSTAR vector; MARKCNTR 0
        # ends at ENDMARKS.
        s.run(tag, 'SURFSTAR', 0o15, 'ENDMARKS',
              [('VAC1+38', x1), ('VAC4', mark), ('SCAXIS', vec(oa)),
               ('VAC1+18', vec(xp)), ('VAC1+12', vec(yp)),
               ('MARKCNTR', '00000,00000,04000')],
              gets_dp('VAC1+24', 3), ebank=0o7)
    # ---- CODE1TO6: detent AZ/EL, rotation AOTAZ +1 MSU AZ, OPTAXIS (stop GETMKS)
    for k, az2 in enumerate((0.0, 0.7)):
        tbl = ','.join(cdu(a) for a in (-60.0, az2, 60.0, 120.0, 180.0, -120.0))
        els = ','.join(cdu(e) for e in (45.0, 44.5, 45.0, 45.2, 45.0, 44.8))
        for d in range(1, 7):
            s.run('code1to6_%d%d' % (k, d), None, 0o7, 'GETMKS',
                  [('XYMARK', '%05o' % d), ('AOTAZ', tbl), ('AOTEL', els)],
                  ['VAC1+10'] + gets_dp('VAC1+12', 3) + gets_dp('VAC1+18', 3),
                  ebank=0o7, entry='CODE1TO6')
    # ---- R59 INCAZ .. 79DISP (15,2437) / R59ALM (basic entry, six detents) ----
    aotaz = ','.join(cdu(a) for a in (-60.0, 0.0, 60.0, 120.0, 180.0, -120.0))
    stars = [('r59_center', [0.7071, 0.0012, 0.7071]),
             ('r59_behind', [-0.3, 0.2, -0.9])]
    for k in range(12):
        az = math.radians(rnd.choice([-60.0, 0.0, 60.0, 120.0, 180.0, -120.0])
                          + rnd.uniform(-25, 25))
        el = math.radians(45.0 + rnd.uniform(-25, 25))
        stars.append(('r59_r%d' % k, [math.sin(el), math.cos(el) * math.sin(az),
                                      math.cos(el) * math.cos(az)]))
    for tag, st in stars:
        s.run(tag, None, 0o15, '15,2437 R59ALM',   # 79DISP
              [('POSCODE', '00001'), ('AOTAZ', aotaz), ('STAR', vec(half_unit(st)))],
              ['CURSOR', 'SPIRAL', 'POSCODE'], entry='INCAZ')
    s.write(os.path.join(OUT, 'align_lm.spec'))

def cm():
    s = Spec('Comanche055', [
        'prog-align oracle cases (Comanche055).  Generated by gen/gen_align.py.',
        'QPRET (VAC1+42) = 65105 (V2TERROR 32,3105: EXIT, TC POODOO), stop POODOO.',
        'SXTNB 23,2000: X1 (VAC1+38) = -VAC4, VAC4+3 = SA, VAC4+5 = TA (CDU',
        '  words, 2s complement) -> 32D (VAC1+32..37) half-unit NB LOS.',
        'SXTANG 23,2053 (ebank 5): STAR, XNB YNB ZNB (half unit, same frame)',
        '  -> SAC, PAC (2s complement CDU words), CULTFLAG (FLAGWRD3 bit 7).',
        'LOG 23,2155: MPAC = x (DP, 0 < x < 1) -> MPAC = -ln(x)/32.',
        'R05 EISOI 42,3677 .. EXIT (stop 42,3751 = CA EXTVBACT), ebank 4: RATT',
        '  (VAC1, earth sphere 2^29 m), REFSMMAT, SINCDU/COSCDU (Y Z X, /2) ->',
        '  R (2D = VAC1+2, NB 2^29 via *SMNB*), RHOSB pitch, GAMMASB yaw (revs).'])
    x1 = '%05o' % (0o77777 - VAC4)
    for tag, ta, sa in (('sxtnb_a', 20.0, 40.0), ('sxtnb_b', 45.0, -120.0),
                        ('sxtnb_c', 3.0, 170.0)):
        s.run(tag, 'SXTNB', 0o23, 'POODOO',
              TRAP_HI_CM + [('VAC1+38', x1), ('VAC4+3', cdu(sa)),
                      ('VAC4+5', cdu(4.0 * ta - 79.1015625))],
              gets_dp('VAC1+32', 3))
    sx = [('sxtang_a', [0.3, 0.2, 0.9], [0.1, -0.2, 0.05]),
          ('sxtang_b', [-0.5, 0.6, 0.6], [0.6, 0.3, -1.2]),
          ('sxtang_wide', [0.9, -0.3, -0.2], [0.0, 0.0, 0.0]),
          ('sxtang_behind', [-0.5, 0.2, -0.8], [0.0, 0.0, 0.0]),
          ('sxtang_axis', None, [0.0, 0.0, 0.0])]
    rnd = random.Random(53)
    for k in range(12):   # stars within ~60 deg of the shaft axis
        a = math.radians(32.523)
        z1 = [math.sin(a), 0.0, math.cos(a)]
        st = [z1[i] + rnd.uniform(-0.8, 0.8) for i in range(3)]   # NB
        ang = [rnd.uniform(-3, 3) for _ in range(3)]
        m = mat(ang)     # rows XNB.. in the star's frame: star = m^T st
        sx.append(('sxtang_r%d' % k,
                   [sum(m[i][j] * st[i] for i in range(3)) for j in range(3)],
                   ang))
    for tag, star, ang in sx:
        nb = mat(ang)
        if star is None:   # along ZNB1 = (sin 32.523, 0, cos 32.523) in NB
            a = math.radians(32.523)
            star = [math.sin(a), 0.0, math.cos(a)]
        s.run(tag, 'SXTANG', 0o23, 'POODOO',
              TRAP_HI_CM + [('STAR', vec(half_unit(star))), ('XNB', mwords(nb))],
              ['SAC', 'PAC', 'FLAGWRD3'], ebank=0o5)
    for tag, x in (('log_half', 0.5), ('log_03', 0.3), ('log_small', 1.0e-4),
                   ('log_near1', 0.97)):
        s.run(tag, 'LOG', 0o23, 'POODOO',
              TRAP_HI_CM + [('MPAC', dp(x) + ',00000'), ('MODE', '00000')],
              ['MPAC:dp'])
    # ---- S-band (R05) angle part: EISOI .. EXIT (stop at CA EXTVBACT) ----
    for tag, r, c in (('sband_cm_a', [-3.0e8, 1.0e8, -2.0e8], [0.0, 0.0, 0.0]),
                      ('sband_cm_b', [2.0e8, 2.5e8, 1.0e8], [30.0, -50.0, 120.0]),
                      ('sband_cm_c', [1.0e8, -3.0e8, 2.0e7], [-100.0, 10.0, 200.0]),
                      ('sband_cm_d', [-1.5e8, -2.0e8, 3.0e8], [5.0, 80.0, -20.0])):
        yzx = [math.radians(c[1]), math.radians(c[2]), math.radians(c[0])]
        s.run(tag, 'EISOI', 0o42, '42,3751',
              TRAP_HI_CM + [('VAC1', vec(r, 29)),
                            ('REFSMMAT', mwords(mat([0.3, -0.6, 1.0]))),
                            ('SINCDU', vec([math.sin(a) for a in yzx], 1)),
                            ('COSCDU', vec([math.cos(a) for a in yzx], 1))],
              ['RHOSB:dp', 'GAMMASB:dp'] + gets_dp('VAC1+2', 3), ebank=0o4)
    s.write(os.path.join(OUT, 'align.spec'))

if __name__ == '__main__':
    lm()
    cm()
