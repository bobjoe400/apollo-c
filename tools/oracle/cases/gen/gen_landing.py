#!/usr/bin/env python3
"""Generate tools/oracle/cases/landing.spec (Luminary099).  Run from
tools/oracle/cases/gen: python3 -I gen_landing.py && cd ../.. && make cases"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agcw import sp, dp, vec, _w
from specgen import Spec, gets_dp, gets_vec
from gen_imu import mat, rows_half, mwords

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
TRAP_HI_LM = '71456'     # P39P79 34,3456: EXIT / TC DSPLY81 (LM high banks)

def unit(v, k=0.5):
    n = math.sqrt(sum(x * x for x in v))
    return [x / n * k for x in v]

def ttf8(cs):
    """TTF/8: DP whose high word is TTF/8 in cs (scale 2^14 cs)."""
    return dp(cs / 8.0, 14)

def target(rfg, vfg, afg, jdgz, gain, tcgf, tcgi):
    """28-word target block: RFG VFG AFG VFG* AFG* JFG* GAIN TCGF TCGI."""
    words = [vec(rfg, 24), vec(vfg, 10), vec(afg, -4),
             dp(18 * vfg[2] / 8, 10), dp(6 * afg[2], -4), dp(8 * jdgz, -18),
             dp(gain), _w(tcgf), _w(tcgi)]
    return ','.join(words)

BRAK = target([-1086.0, 0.0, -4315.0], [-0.52, 0.0, -1.87], [3.0e-5, 0.0, -0.8e-4],
              1.2e-9, -0.6, 400, 8000)
APPR = target([-40.0, 0.0, -150.0], [-0.06, 0.0, -0.20], [1.0e-5, 0.0, -0.3e-4],
              0.4e-9, -0.3, 60, 1500)

def main():
    s = Spec('Luminary099', [
        'landing oracle cases (Luminary099).  Generated by gen/gen_landing.py.',
        'Guidance pass: entry RGVGCALC 31,3013 (basic, TC INTPRET) through',
        '  TTF/8CL (ROOTPSRS), TDISPSET, QUADGUID, AFCCALC1-3 to the WCHPHASE',
        '  AFTRGUID jump: stop CGCALC.  Inputs R V (SM 2^24 m / 2^7 m/cs) WM CG',
        '  LAND XNBPIP ZNBPIP TTF/8 WCHPHASE FLPASS0 LEADTIME MASS GDT/2 and the',
        '  braking (RBRFG..TCGIBRAK) and approach (RAPFG..TCGIAPPR) targets.',
        '  Outputs ANGTERM VGU VHORIZ RGU RANGEDSP LOOKANGL TTF/8 TTFDISP TREDES',
        '  UNFC/2 /AFC/ FLPASS0 WCHPHOLD.',
        'CGCALC 31,3245: TTF/8 inside (TCGF, TCGI) -> CG; stop EXTLOGIC.',
        'Basic entries run with EBANK 7 (the callers\' EBANK=TTF/8 / PIF).',
        'THROTTLE 31,2216 (basic, returns through RTNHOLD = Q): Q = ENDOFJOB,',
        '  stop ENDOFJOB.  ABDELV /AFC/ MASS TTHROT TIME2/TIME1 FWEIGHT FCOLD',
        '  LOWCRIT HIGHCRIT MODREG PIPTIME THISTPIP -> FP FC FCODD FCOLD PIF',
        '  PIFPSET PSEUDO55 THRUST TTHROT FWEIGHT.',
        'FINDCDUW 30,3113 (interpretive, high bank): Q = FINDCDUW, QPRET =',
        '  VAC1+42 = 71456 (P39P79 34,3456: EXIT, TC DSPLY81), stop DSPLY81.',
        '  MPAC = thrust command, UNWC/2, UNFV/2 (filter, UNITX after INITCDUW),',
        '  DELV, CDUX..Z, XNBPIP ZNBPIP.  Channels 30/31 read as yaAGC leaves',
        '  them (not PNGCS auto), so it ends at NOATTCNT; out CPHI (CDU',
        '  commands for N22), -DELGMB, UNFV/2, push list UNX/2 UNY/2 UNZ/2.'])
    common = [('MASS', dp(15000.0, 16)), ('LEADTIME', _w(-220)),
              ('WM', vec([2.0e-9, 0.0, 2.65e-8], -17)),
              ('RBRFG', BRAK), ('RBRFG+28', APPR)]
    gg = (gets_vec('ANGTERM') + gets_vec('VGU') + ['VHORIZ:dp'] + gets_vec('RGU') +
          ['RANGEDSP:dp', 'LOOKANGL', 'TTF/8:dp', 'TTFDISP:dp', 'TREDES'] +
          gets_vec('UNFC/2') + ['/AFC/:dp', 'FLPASS0', 'WCHPHOLD'])
    cg_brak = rows_half(mat([0.0, -0.02, 0.01]))
    for tag, r, v, land, t, ph, xnb in (
            ('guid_brak_a', [1.753e6, 1.0e4, -3.2e5], [-0.4, 0.05, 15.5], [1.736e6, 0.0, 0.0], -480.0e2, 0, [0.4, 0.0, -0.3]),
            ('guid_brak_b', [1.748e6, -2.0e3, -1.1e5], [-0.6, 0.02, 9.0], [1.736e6, 0.0, 0.0], -230.0e2, 0, [0.6, 0.05, -0.2]),
            ('guid_appr', [1.7385e6, 5.0e2, -5.0e3], [-0.15, 0.01, 1.4], [1.7358e6, 0.0, 100.0], -95.0e2, 1, [0.8, 0.0, 0.5])):
        g = unit(r, -0.0162 * 0.999)
        s.run(tag, None, 0o31, 'CGCALC',
              common + [('R', vec(r, 24)), ('V', vec(v, 7)), ('LAND', vec(land, 24)),
                        ('CG', mwords(cg_brak)), ('XNBPIP', vec(unit(xnb))),
                        ('ZNBPIP', vec(unit([-xnb[2], 0.1, xnb[0]]))),
                        ('TTF/8', ttf8(t)), ('WCHPHASE', _w(ph)), ('FLPASS0', '00003'),
                        ('GDT/2', vec(g, 7))], gg, entry='31,3013', ebank=7)
    # ---- CGCALC ----
    cgg = gets_dp('CG', 9)
    for tag, r, v, land, t, ph in (
            ('cgcalc_brak', [1.753e6, 1.0e4, -3.2e5], [-0.4, 0.05, 15.5], [1.736e6, 0.0, 0.0], -480.0e2, 0),
            ('cgcalc_appr', [1.7385e6, 5.0e2, -5.0e3], [-0.15, 0.01, 1.4], [1.7358e6, 30.0, 100.0], -95.0e2, 1)):
        ang = [x for x in [0.1 * v[0], 0.1 * v[1], 0.1 * v[2]]]
        s.run(tag, None, 0o31, 'EXTLOGIC',
              common + [('R', vec(r, 24)), ('LAND', vec(land, 24)),
                        ('ANGTERM', vec(ang, 9)), ('TTF/8', ttf8(t)),
                        ('WCHPHASE', _w(ph)), ('CG', mwords(cg_brak))], cgg,
              entry='31,3245')
    # ---- THROTTLE ----
    tg = ['FP:dp', 'FC', 'FCODD:dp', 'FCOLD', 'PIF:dp', 'PIFPSET', 'PSEUDO55',
          'THRUST', 'TTHROT', 'FWEIGHT:dp', 'TIME1']
    for tag, abdelv, afc, fcold, tthrot, t1, fw in (
            ('throt_mid', 450, 2.0e-4, 2000, 4800, 5000, [3, 1000]),
            ('throt_old', 450, 2.0e-4, 2000, 1000, 5000, [3, 1000]),
            ('throt_up', 520, 3.4e-4, 2000, 4800, 5000, [0, 0]),
            ('throt_hold', 700, 3.6e-4, 3500, 4800, 5000, [-5, -200]),
            ('throt_down', 700, 1.5e-4, 3500, 4800, 5000, [0, 0]),
            ('throt_p66', 330, 1.7e-4, 2300, 4900, 5000, [2, 300])):
        mod = 66 if tag == 'throt_p66' else 63
        s.run(tag, 'ENDOFJOB', 0o31, 'ENDOFJOB',
              [('ABDELV', _w(abdelv)), ('/AFC/', dp(afc, -4)), ('MASS', dp(15000.0, 16)),
               ('TTHROT', _w(tthrot)), ('TIME2', '00000,%05o' % t1),
               ('FWEIGHT', _w(fw[0]) + ',' + _w(fw[1])), ('FCOLD', _w(fcold)),
               ('LOWCRIT', _w(2700) + ',' + _w(3000)), ('MODREG', _w(mod)),
               ('PIPTIME', '00000,%05o' % (t1 - 150)), ('THISTPIP', '00000,%05o' % (t1 - 80))],
              tg, entry='31,2216', ebank=7)
    # ---- FINDCDUW ----
    fg = ['CPHI', 'CPHI+1', 'CPHI+2', '-DELGMB', '-DELGMB+1', '-DELGMB+2'] + \
         gets_vec('UNFV/2') + gets_vec('VAC1') + gets_vec('VAC1+6') + gets_vec('VAC1+12')
    for tag, unfc, unwc, delv, cdu in (
            ('findcduw_a', [0.0012, 0.0001, 0.0021], [0.3, 0.0, 0.4], [400, 20, 700], [100, 32000, 2000]),
            ('findcduw_b', [0.0030, -0.0004, -0.0011], [0.1, 0.2, 0.4], [900, -100, -300], [30000, 1500, 31000])):
        mp = dp(unfc[0]) + ',00000,' + dp(unfc[1]) + ',' + dp(unfc[2])
        s.run(tag, '30,3113', 0o30, 'DSPLY81',
              [('VAC1+42', TRAP_HI_LM), ('MPAC', mp), ('MODE', '77776'),
               ('UNWC/2', vec(unwc)), ('UNFV/2', vec([0.5, 0.0, 0.0])),
               ('DELV', ','.join('%s,00000' % _w(x) for x in delv)),
               ('CDUX', ','.join(_w(x) for x in cdu)),
               ('XNBPIP', vec(unit([0.4, 0.0, -0.3]))), ('ZNBPIP', vec(unit([0.3, 0.1, 0.4])))],
              fg)
    s.write(os.path.join(OUT, 'landing.spec'))

if __name__ == '__main__':
    main()
