#!/usr/bin/env python3
"""Generate tools/oracle/cases/imu.spec (Comanche055).  Run from
tools/oracle/cases/gen: python3 -I gen_imu.py && cd ../.. && make cases"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agcw import sp, dp, vec, _w
from specgen import Spec, gets_dp, gets_vec

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
TRAP_HI = '65105'           # V2TERROR 32,3105: EXIT / TC POODOO

def rot(ax, a):
    c, s = math.cos(a), math.sin(a)
    if ax == 0:
        return [[1, 0, 0], [0, c, -s], [0, s, c]]
    if ax == 1:
        return [[c, 0, s], [0, 1, 0], [-s, 0, c]]
    return [[c, -s, 0], [s, c, 0], [0, 0, 1]]
def mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
def mat(angles):
    m = rot(0, angles[0])
    m = mul(m, rot(1, angles[1]))
    return mul(m, rot(2, angles[2]))
def rows_half(m):
    return [[x / 2 for x in r] for r in m]
def mwords(m, scale=0):
    return ','.join(vec(r, scale) for r in m)
def mvec(m, v):
    return [sum(m[i][k] * v[k] for k in range(3)) for i in range(3)]
def cdu(deg):
    """CDU counter pattern: 2's complement, 2^15 = 360 deg."""
    n = int(round(deg / 360.0 * 32768)) & 0o77777
    return '%05o' % n

def main():
    s = Spec('Comanche055', [
        'imu oracle cases (Comanche055).  Generated by gen/gen_imu.py.',
        'Interpretive routines in bank 23/22 (high): entry INTPRET, Q = label,',
        'QPRET = VAC1+42 = 65105 (V2TERROR: EXIT, TC POODOO), stop POODOO.',
        'CALCGTA 23,3205: XDC YDC ZDC (half-unit rows) -> OGC IGC MGC (rev).',
        'CALCGA 23,3311: XNB YNB ZNB, XSM YSM ZSM -> THETAD (CDU patterns),',
        '  OGC IGC MGC; > 60 deg middle gimbal -> ALARM 00401 (FAILREG), GLOKFAIL.',
        'AXISGEN 23,3401: STARAD, STARAD+6 (frame A), VAC1+6, VAC1+12 (frame B)',
        '  -> XDC YDC ZDC.',
        '1/PIPA 06,3262 (basic, BANKCALL target): stop SWRETURN.  DELVX..Z (DP',
        '  (1/PIPADT is set by address, 1074: agc_probe reads a name starting',
        '  with a digit as an octal address)',
        '  pulses x 2^14), PBIASX/PIPASCFX.. (interleaved), NBDX.., ADIAX..,',
        '  ADSRAX.., 1/PIPADT, GCOMP, GCOMPSW -> DELVX.., GCOMP, GCOMPSW.',
        'KALCMAN3 22,2000 (basic job entry): CDUX..Z (032-034) and CPHI CTHETA',
        '  CPSI, RATEINDX -> MIS MFI COFSKEW CAM AM COF; it runs on through',
        '  WCALC (DELCOMP of a 1 s rotation -> DEL, BRATE, TM) and NEWANGL to',
        '  MANUSTAT (EXIT): stop 20,2066 (MANUSTAT+1), or NOGO (< .25 deg).',
        'DELCOMP 22,2530: MPAC = A (rev x 2), COF -> DEL (scale 1).',
        'DCMTOCDU 22,2655: X1 (VAC1+38) = -(address of MIS) = 74457, MIS (scale',
        '  2) -> MPAC angles (rev), S1 (VAC1+40) = cos MGA.'])
    trap = [('VAC1+42', TRAP_HI)]
    # ---- CALCGTA ----
    for tag, ang in (('calcgta_small', [0.01, -0.02, 0.015]),
                     ('calcgta_large', [0.7, -0.4, 1.1]),
                     ('calcgta_back', [2.9, 0.3, -2.5])):
        m = rows_half(mat(ang))
        s.run(tag, '23,3205', 0o23, 'POODOO',
              trap + [('XDC', mwords(m))], ['OGC:dp', 'IGC:dp', 'MGC:dp'])
    # ---- CALCGA ----
    for tag, nb_ang, sm_ang in (('calcga_a', [0.3, 0.2, -0.1], [0.0, 0.0, 0.0]),
                                ('calcga_b', [1.2, -0.7, 0.4], [-0.3, 0.5, 0.2]),
                                ('calcga_c', [-2.0, 2.5, 0.6], [0.1, -0.2, 0.3]),
                                ('calcga_lock', [0.2, 0.1, 1.25], [0.0, 0.0, 0.0])):
        nb = rows_half(mat(nb_ang))
        sm = rows_half(mat(sm_ang))
        s.run(tag, '23,3311', 0o23, 'POODOO',
              trap + [('XNB', mwords(nb)), ('XSM', mwords(sm))],
              ['THETAD', 'THETAD+1', 'THETAD+2', 'OGC:dp', 'IGC:dp', 'MGC:dp',
               'FAILREG', 'FLAGWRD3'])
    # ---- AXISGEN ----
    for tag, ang, s1, s2 in (('axisgen_a', [0.3, -0.2, 0.5], [0.6, 0.48, 0.64], [-0.2, 0.9, 0.38]),
                             ('axisgen_b', [2.0, 1.0, -1.5], [0.1, -0.7, 0.7], [0.8, 0.5, -0.33])):
        def unit(v):
            n = math.sqrt(sum(x * x for x in v))
            return [x / n / 2 for x in v]
        a1, a2 = unit(s1), unit(s2)
        m = mat(ang)
        b1, b2 = mvec(m, a1), mvec(m, a2)
        s.run(tag, '23,3401', 0o23, 'POODOO',
              trap + [('STARAD', vec(a1) + ',' + vec(a2)), ('VAC1+6', vec(b1)),
                      ('VAC1+12', vec(b2))],
              gets_vec('XDC') + gets_vec('YDC') + gets_vec('ZDC'))
    # ---- 1/PIPA ----
    def wl(xs):
        return ','.join(_w(x) for x in xs)
    for tag, delv, scf, bias, nbd, adia, adsra, gsw in (
            ('pipa_small', [123, -45, 6], [200, -150, 75], [40, -25, 10],
             [30, -12, 7], [100, -80, 60], [-50, 40, 20], 0),
            ('pipa_burn', [3000, -1200, 450], [-300, 250, 410], [-60, 90, 15],
             [200, -300, 150], [2500, -1800, 3100], [900, -1500, 700], 0),
            ('pipa_bypass', [3000, -1200, 450], [-300, 250, 410], [-60, 90, 15],
             [200, -300, 150], [2500, -1800, 3100], [900, -1500, 700], -1),
            ('pipa_carry', [-16000, 15000, -9000], [500, -500, 300], [120, -120, 60],
             [-150, 150, -90], [-4000, 3500, 2200], [1600, -1400, 900], 0)):
        dv = ','.join('%s,00000' % _w(x) for x in delv)
        pb = wl([bias[0], scf[0], bias[1], scf[1], bias[2], scf[2]])
        g0 = wl([5, 1000, -3, -2000, 0, 300])
        s.run(tag, None, 0o06, 'SWRETURN',
              [('DELVX', dv), ('PBIASX', pb), ('NBDX', wl(nbd)), ('ADIAX', wl(adia)),
               ('ADSRAX', wl(adsra)), ('1074', '31000'), ('GCOMP', g0),
               ('GCOMPSW', _w(gsw))],
              ['DELVX:dp', 'DELVY:dp', 'DELVZ:dp', 'GCOMP:dp', 'GCOMP+2:dp',
               'GCOMP+4:dp', 'GCOMPSW'], entry='06,3262')
    # ---- KALCMAN3 ----
    kg = (gets_dp('MIS', 9) + gets_dp('MFI', 9) + gets_vec('COFSKEW') +
          ['CAM:dp', 'AM:dp'] + gets_vec('COF') + gets_dp('DEL', 9) +
          gets_vec('BRATE') + ['TM:dp', 'NCDU', 'NCDU+1', 'NCDU+2', 'BCDU',
                               'BCDU+1', 'BCDU+2'])
    for tag, c0, c1, ri in (('kalc_normal', [10.0, 20.0, 5.0], [40.0, -15.0, 25.0], 2),
                            ('kalc_large', [0.0, 0.0, 0.0], [175.0, 10.0, 3.0], 4),
                            ('kalc_neg', [-30.0, 100.0, -20.0], [15.0, 80.0, 40.0], 0),
                            ('kalc_small', [12.0, 34.0, 5.0], [12.1, 34.05, 5.0], 2)):
        s.run(tag, None, 0o22, 'NOGO 20,2066',
              [('CDUX', ','.join(cdu(x) for x in c0)),
               ('CPHI', ','.join(cdu(x) for x in c1)), ('RATEINDX', '%05o' % ri)],
              kg, entry='22,2000')
    # ---- DELCOMP ----
    for tag, u, a in (('delcomp_a', [0.6, 0.48, 0.64], 0.0022222222 / 16),
                      ('delcomp_b', [-0.2, 0.9, 0.38], 0.0888888889 / 16),
                      ('delcomp_c', [0.0, 0.0, 1.0], 0.2)):
        n = math.sqrt(sum(x * x for x in u))
        uu = [x / n / 2 for x in u]
        s.run(tag, '22,2530', 0o22, 'POODOO',
              trap + [('COF', vec(uu)), ('MPAC', dp(a) + ',00000')],
              gets_dp('DEL', 9))
    # ---- DCMTOCDU ----
    for tag, ang in (('dcmtocdu_a', [0.3, -0.5, 0.2]), ('dcmtocdu_b', [2.5, 1.0, -0.9]),
                     ('dcmtocdu_c', [-1.7, -2.9, 1.2])):
        m = rows_half(mat(ang))
        s.run(tag, '22,2655', 0o22, 'POODOO',
              trap + [('MIS', mwords(m)), ('VAC1+38', '74457')],
              ['MPAC:dp', 'MPAC+3:dp', 'MPAC+5:dp', 'VAC1+40'])
    s.write(os.path.join(OUT, 'imu.spec'))

if __name__ == '__main__':
    main()
