"""Downlink erasable dump oracle cases (DNDUMP, both ropes).

Writes cases/dndump_csm.spec and cases/dndump_lm.spec (run from tools/oracle).
One run per rope: a known word in every erasable address 0061-3777 (a fixed
pseudo-random word per address, never -0) except the words the run itself
uses (the main program's TC-to-itself at 0450, the down-telemetry program's
working words DNLSTCOD .. DNTMBUFF +21D), DUMPCNT = BIT12 (one complete
dump), DNTMGOTO = DNDUMPI, and yaAGC runs DODOWNTM on its own DOWNRUPTs
(agc_probe 'downlink') for one dump: per EBANK the ERASID word, DUMPLOC and
TIME1, 128 register pairs; then the downlist ID of DNLSTCOD's list.
tests/io/downlink_dump_oracle.c loads the same words through the erasable
map and compares the C's dump pair by pair.
"""
import argparse
import os
import zlib

ROPES = (('Comanche055', 'csm'), ('Luminary099', 'lm'))
PAIRS = 8 * 130 + 1           # 8 EBANKs x (ID, DUMPLOC + 128 pairs), the next list's ID
LOOP = 0o450                  # TC 0450 (VAC1): the main program
WORK = range(0o330, 0o366)    # DNLSTCOD .. DNTMBUFF +21D (both ropes): the program's own words


def word(a):
    """The known word of erasable address a: 1 .. 77776, deterministic."""
    return zlib.crc32(('E%04o' % a).encode()) % 0o77776 + 1


def loc(a):
    """agc_probe's name of flat erasable address a."""
    return '%04o' % a if a < 0o1400 else 'E%o,%04o' % (a >> 8, 0o1400 + (a & 0o377))


def sets():
    """set lines of 8 consecutive words, the excluded ones left out."""
    addrs = [a for a in range(0o61, 0o4000) if a != LOOP and a not in WORK]
    lines, i = [], 0
    while i < len(addrs):
        j = i
        while (j + 1 < len(addrs) and addrs[j + 1] == addrs[j] + 1 and j + 1 - i < 8 and
               (addrs[j + 1] >> 8) == (addrs[i] >> 8)):
            j += 1
        lines.append('set %s=%s' % (loc(addrs[i]), ','.join('%o' % word(a) for a in addrs[i:j + 1])))
        i = j + 1
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='cases', help='directory of the .spec files')
    a = ap.parse_args()
    for rope, tag in ROPES:
        L = ['# generated by gen/gen_dump.py', 'rope %s' % rope, 'entry %o' % LOOP, 'maxcycles 80000000',
             'set %o=%o' % (LOOP, LOOP), 'set DNTMGOTO=@DNDUMPI', 'set DUMPCNT=4000', 'set DNLSTCOD=0']
        L += sets()
        L += ['downlink %d' % PAIRS, 'run %s_dump' % rope]
        open(os.path.join(a.out, 'dndump_%s.spec' % tag), 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
