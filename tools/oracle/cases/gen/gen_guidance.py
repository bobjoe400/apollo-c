#!/usr/bin/env python3
"""Generate tools/oracle/cases/guidance.spec (Comanche055).  Run from
tools/oracle/cases/gen: python3 -I gen_guidance.py && cd ../.. && make cases"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agcw import sp, dp, vec, _w
from specgen import Spec, gets_dp, gets_vec
from gen_imu import mat, rows_half, mwords

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
TRAP_LO, TRAP_HI = '25751', '65105'   # ABTCONIC 12,3751 / V2TERROR 32,3105

def unit(v, k=1.0):
    n = math.sqrt(sum(x * x for x in v))
    return [x / n * k for x in v]

def main():
    s = Spec('Comanche055', [
        'guidance oracle cases (Comanche055).  Generated by gen/gen_guidance.py.',
        'Entry INTPRET, Q = label, QPRET = VAC1+42 = trap: 25751 (ABTCONIC) for',
        'low banks, 65105 (V2TERROR) for high banks; stop POODOO.',
        'CALCRVG 37,3420 (average-G one step): DELV (pulses, DP x 2^14) REFSMMAT',
        '  (half unit) GDT/2 VN (2^7 m/cs) RN (2^29 m) RTX2 (0 earth, 2 moon)',
        '  UNITW -> DELVREF RN1 VN1 GDT1/2 UNITR GOBL1/2.',
        'S40.1 16,2020 with XDELVFLG (FLAGWRD2 00200) and COMPUTER (FLAGWRD5',
        '  00200, set in every CMC; MIDGIM takes GET.LVC): RTIG VTIG DELVSIN',
        '  WEIGHT/G (kg 2^16) F (10^4 N 2^7) -> DELVSAB UT VGTIG RINIT VINIT,',
        '  and MIDGIM (AVFLAG set by S40.1) -> DELVLVC.',
        'S40.2,3 24,3574: UT REFSMMAT RTIG VTIG PACTOFF YACTOFF, ENG2FLAG',
        '  (FLAGWRD1 02000 = RCS) -> POINTVSM SCAXIS XSCREF YSCREF ZSCREF.',
        'DELTIME 12,2433 (conic, called by the steering/targeting conics):',
        '  push list 0D XSQ, 18D 1/ROOTMU, 20D X, 32D R1, 34D KEPC1, 36D KEPC2,',
        '  X1 (38D) = -N1, MPAC = 24D = XI, PUSHLOC = VAC1+2 (the caller pushed',
        '  XSQ) -> 26D S(XI), 28D XSQC(XI), 30D T.'])
    # ---- CALCRVG ----
    rg = (gets_vec('DELVREF') + gets_vec('RN1') + gets_vec('VN1') +
          gets_vec('GDT1/2') + gets_vec('UNITR') + gets_vec('GOBL1/2'))
    ref = rows_half(mat([0.3, -0.2, 0.7]))
    for tag, delv, r, v, moon in (
            ('calcrvg_coast', [0, 0, 0], [5.0e6, 3.0e6, 3.5e6], [-40.0, 60.0, 25.0], False),
            ('calcrvg_burn', [120, -35, 260], [5.0e6, 3.0e6, 3.5e6], [-40.0, 60.0, 25.0], False),
            ('calcrvg_tli', [1500, 900, -400], [-2.0e6, 6.0e6, 1.0e6], [-95.0, -20.0, 30.0], False),
            ('calcrvg_moon', [-300, 80, 150], [1.5e6, -0.8e6, 0.6e6], [8.0, 12.0, -6.0], True)):
        g = unit(r, -(4.9e12 if moon else 3.986e14) / sum(x * x for x in r) * 1.0 / 100)
        s.run(tag, '37,3420', 0o37, 'POODOO',
              [('VAC1+42', TRAP_HI),
               ('DELV', ','.join('%s,00000' % _w(x) for x in delv)),
               ('REFSMMAT', mwords(ref)), ('GDT/2', vec(g, 7)), ('VN', vec(v, 7)),
               ('RN', vec(r, 29)), ('RTX2', '00002' if moon else '00000'),
               ('UNITW', vec([0.01, -0.02, 0.9997], 0))], rg)
    # ---- S40.1 (external delta V) ----
    s1g = (['DELVSAB:dp'] + gets_vec('UT') + gets_vec('VGTIG') + gets_vec('RINIT') +
           gets_vec('VINIT') + gets_vec('DELVLVC') + ['FLAGWRD2'])
    for tag, r, v, dv, wg, f in (
            ('s40_1_posigrade', [6.7e6, 1.0e6, 0.5e6], [-10.0, 75.0, 12.0], [0.3, -0.1, 0.05], 28000.0, 9.17),
            ('s40_1_plane', [-3.0e6, 5.5e6, 2.2e6], [-60.0, -40.0, 20.0], [0.5, 1.2, -2.0], 21000.0, 9.17),
            ('s40_1_large', [6.7e6, 1.0e6, 0.5e6], [-10.0, 75.0, 12.0], [-8.1, 25.3, 4.2], 43000.0, 9.17)):
        s.run(tag, '16,2020', 0o16, 'POODOO',
              [('VAC1+42', TRAP_LO), ('RTIG', vec(r, 29)), ('VTIG', vec(v, 7)),
               ('DELVSIN', vec(dv, 7)), ('WEIGHT/G', dp(wg, 16)), ('F', dp(f, 7)),
               ('FLAGWRD2', '00200'), ('FLAGWRD5', '00200')], s1g)
    # ---- S40.2,3 ----
    s2g = (gets_vec('POINTVSM') + gets_vec('SCAXIS') + gets_vec('XSCREF') +
           gets_vec('YSCREF') + gets_vec('ZSCREF'))
    for tag, ut, r, v, pa, ya, rcs in (
            ('s40_2_sps', [0.2, 0.9, 0.1], [6.7e6, 1.0e6, 0.5e6], [-10.0, 75.0, 12.0], 120, -80, False),
            ('s40_2_sps_b', [-0.6, 0.3, 0.7], [-3.0e6, 5.5e6, 2.2e6], [-60.0, -40.0, 20.0], -300, 250, False),
            ('s40_2_rcs', [0.2, 0.9, 0.1], [6.7e6, 1.0e6, 0.5e6], [-10.0, 75.0, 12.0], 0, 0, True),
            ('s40_2_radial', [0.6, 0.48, 0.64], [6.0e6, 4.8e6, 6.4e6], [-50.0, 40.0, 17.0], 30, 40, False)):
        s.run(tag, '24,3574', 0o24, 'POODOO',
              [('VAC1+42', TRAP_HI), ('UT', vec(unit(ut, 0.5))), ('REFSMMAT', mwords(ref)),
               ('RTIG', vec(r, 29)), ('VTIG', vec(v, 7)), ('PACTOFF', _w(pa)),
               ('YACTOFF', _w(ya)), ('FLAGWRD1', '02000' if rcs else '00000')], s2g)
    # ---- DELTIME ----
    dg = ['VAC1+26:dp', 'VAC1+28:dp', 'VAC1+30:dp', 'MPAC:dp']
    for tag, xi, x, n1, r1, k1, k2 in (
            ('deltime_ell', 2.5, 1587.0, 12, 7.0e6, 93.0, 0.1),
            ('deltime_hyp', -4.0, 2400.0, 11, 6.6e6, -20.0, 0.6),
            ('deltime_small', 0.05, 300.0, 16, 6.8e6, 5.0, 0.02)):
        xsq = x * x / 2.0 ** (34 - n1)
        s.run(tag, '12,2433', 0o12, 'POODOO',
              [('VAC1+42', TRAP_LO), ('VAC1', dp(xsq)), ('VAC1+18', dp(1 / math.sqrt(3.986032e10), -17)),
               ('VAC1+20', dp(x, 17)), ('VAC1+32', dp(r1, 29)), ('VAC1+34', dp(k1, 17)),
               ('VAC1+36', dp(k2, 6)), ('VAC1+38', _w(-n1)), ('VAC1+24', dp(xi, 6)),
               ('MPAC', dp(xi, 6) + ',00000'), ('PUSHLOC', '@VAC1+2')], dg)
    s.write(os.path.join(OUT, 'guidance.spec'))

if __name__ == '__main__':
    main()
