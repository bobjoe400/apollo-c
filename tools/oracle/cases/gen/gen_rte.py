#!/usr/bin/env python3
"""Generate tools/oracle/cases/return_to_earth.spec (Comanche055).  Run
from tools/oracle/cases/gen: python3 -I gen_rte.py && cd ../.. && make cases"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agcw import dp, vec, _w
from specgen import Spec, gets_dp, gets_vec

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
EXEC = [('NEWJOB', '00000'), ('PRIORITY', '37401')] + [
    ('%04o' % (0o167 + 12 * k), '77777') for k in range(1, 7)]

def main():
    s = Spec('Comanche055', [
        'return_to_earth (P37) oracle cases (Comanche055).  Generated by',
        'gen/gen_rte.py.  One conic search: entry RTE299 36,2507 (basic, TC',
        'INTPRET) -> INVC100 (CSMPREC from the permanent CSM state; TIG =',
        'TETCSM makes it a zero-length integration, so R(T1) = RRECTCSM; the',
        '42-word permanent block is a rectified state, RCVCSM = RRECTCSM) ->',
        'RTE317..RTE390 (V2T100, TMRAD100, the X(T2)/RCON iteration) -> P37E ->',
        'RTEVN -> RTEDISP -> stop P370GOFR (the V06N61 display); an alarm ends',
        'at P370GOF.  Inputs RRECTCSM VRECTCSM TETCSM TIG, VPRED (-> RTEDVD),',
        'GAMMAEI (-> RTEGAM2D), RTED1 (pad, 1351: .205, which with the RTE369',
        'polynomial gives a -6.5 deg entry angle); core sets freed.  Outputs',
        'R(T1) UR1/ UH/ CFPA MAMAX2 RCON X(T2) BETA1 X(T1) PCON V2(T1)/ DV R(T2)/',
        'V(T2)/ T2 T12 NN1A, RTEDISP: VPRED T3TOT4 GAMMAEI LAT(SPL) LNG(SPL)',
        'DELVLVC.'], maxcycles=40000000)
    g = (['R(T1):dp'] + gets_vec('UR1/') + gets_vec('UH/') +
         ['CFPA:dp', 'MAMAX2:dp', 'RCON:dp', 'X(T2):dp', 'BETA1:dp', 'X(T1):dp',
          'PCON:dp'] + gets_vec('V2(T1)/') + ['DV:dp'] + gets_vec('R(T2)/') +
         gets_vec('V(T2)/') + ['T2:dp', 'T12:dp', 'NN1A:dp', 'VPRED:dp',
                               'T3TOT4:dp', 'GAMMAEI:dp', 'LAT(SPL):dp',
                               'LNG(SPL):dp'] + gets_vec('DELVLVC') + ['FAILREG'])
    for tag, r, v, dvd, gam in (
            ('rte_transearth', [3.0e8, 1.2e8, 0.2e8], [-9.0, -4.0, -0.5], 0.0, 0.0),
            ('rte_transearth_gam', [3.0e8, 1.2e8, 0.2e8], [-9.0, -4.0, -0.5], 0.0, -6.4 / 360),
            ('rte_midcourse', [1.6e8, -0.9e8, 0.1e8], [-12.0, 6.0, 0.4], 0.0, 0.0),
            ('rte_leo', [6.0e6, 3.2e6, 0.0], [-36.0, 67.0, 5.0], 0.0, 0.0)):
        t = 2.0e7
        s.run(tag, None, 0o36, 'P370GOFR P370GOF',
              EXEC + [('RRECTCSM', ','.join([vec(r, 29), vec(v, 7), dp(t, 28),
                                             vec([0.0] * 3), vec([0.0] * 3),
                                             vec(r, 29), vec(v, 7), dp(0), dp(0)])),
                      ('TIG', dp(t, 28)), ('VPRED', dp(dvd, 7)),
                      ('GAMMAEI', dp(gam)), ('1351', dp(0.205))],
              g, ebank=7, entry='36,2507')
    s.write(os.path.join(OUT, 'return_to_earth.spec'))

if __name__ == '__main__':
    main()
