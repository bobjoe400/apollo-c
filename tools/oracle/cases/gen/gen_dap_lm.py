#!/usr/bin/env python3
"""Generate tools/oracle/cases/dap_lm.spec (Luminary099).  Run from
tools/oracle/cases/gen: python3 -I gen_dap_lm.py && cd ../.. && make cases"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from agcw import sp, dp, _w
from specgen import Spec, probe

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
BLOCK = 0o1547          # BLOCKTOP, E6
JACC = 'E6,1530'        # 1JACC 1JACCQ 1JACCR 1JACCU 1JACCV (name starts with a digit)

def w(xs):
    return ','.join(_w(x) for x in xs)

def cdu(deg):
    return '%05o' % (int(round(deg / 360.0 * 32768)) & 0o77777)

def main():
    s = Spec('Luminary099', [
        'dap-lm oracle cases (Luminary099).  Generated by gen/gen_dap_lm.py.',
        'Basic routines, EBANK 6.  Names starting with a digit are written as',
        'addresses (agc_probe reads them as octal): 1JACC.. = E6,1530..1534,',
        '1/ACCJOB = 20,2454; L,PVT-CG (comma and minus in the name) = E6,1527.',
        '1/ACCS: entry 1/ACCJOB (BANKCALL 1/ACCS +2, TC ENDOFJOB), stop',
        '  ENDOFJOB.  MASS (DP 2^16 kg) CSMMASS ABDELV DB HIASCENT DAPBOOLS',
        '  (CSMDOCKD 010000) FLGWRD10 (APSFLAG 010000) -> LEMMASS 1JACC..1JACCV',
        '  COEFFQ COEFFR L,PVT-CG ACCDOTQ ACCDOTR KQ KRDAP QACCDOT RACCDOT',
        '  -2JETLIM ALLOWGTS and the 48-word TJETLAW block at BLOCKTOP (1/ACCONT).',
        'TJETLAW 17,3252: Q = ENDOFJOB (its TC HOLDQ executes the saved Q as an',
        '  instruction), stop ENDOFJOB.  E EDOT AXISCTR SENSETYP TJP TJU TJV and',
        '  the block from the 1/ACCS case named in the comment -> TJP TJU TJV',
        '  NUMBERT FIREFCT.',
        'GPMATRIX 06,3132 (T4RUPT DAP matrix): CDUX CDUZ -> M11 M21 M22 M31 M32',
        '  COSMG; stop RESUME.',
        'RATELOOP 16,3641 (KALMAN_FILTER: RATELOOP, ROTORQUE, BACKP rate',
        '  derivation, offset estimator): stop PRETIMCK.'])
    accs_out = (['LEMMASS', JACC, 'E6,1531', 'E6,1532', 'E6,1533', 'E6,1534',
                 'COEFFQ', 'COEFFR', 'E6,1527', 'ACCDOTQ', 'ACCDOTR', 'KQ',
                 'KRDAP', 'QACCDOT', 'RACCDOT', '-2JETLIM', 'ALLOWGTS', 'MASS:dp'] +
                ['E6,%04o' % (BLOCK + k) for k in range(48)])
    accs = {}
    # The accs_aos_* cases (review-dap-lm) put an offset acceleration
    # AOSQ, AOSR (DP at pi/2, LSB of the major word) into 1/ACCONT: NOAOS,
    # SOMEAOS, BIGAOS (DB4(3) = 2 DB), DB1 = -.5 DB above .1875 pi/2,
    # NETNEG / FIXMIN, the SKIPDB1 overflow rescale, failed jet pairs
    # (CH5MASK -U,+V = 0151; +U,-V = 0226), drift and ascent.
    for tag, mass, csm, docked, aps, abdelv, db, aos, ch5, drift in (
            ('accs_dps', 15000.0, 28000.0, False, False, 500, 0o144, None, 0, False),
            ('accs_aps', 4800.0, 28000.0, False, True, 900, 0o144, None, 0, False),
            ('accs_docked', 43000.0, 28000.0, True, False, 0, 0o1000, None, 0, False),
            # review-dap-lm: docked with thrust (ACCDOTQ/R from the CG fit),
            # docked ascent, docked MASSFIX (LEMMASS above HIDESCNT).
            ('accs_docked_thrust', 43000.0, 28000.0, True, False, 400, 0o144, None, 0, False),
            ('accs_docked_aps', 33000.0, 28000.0, True, True, 600, 0o144, None, 0, False),
            ('accs_docked_fix', 46500.0, 30000.0, True, False, 200, 0o144, None, 0, False),
            ('accs_dps_wide', 12000.0, 28000.0, False, False, 300, 0o2000, None, 0, False),
            ('accs_aos_small', 15000.0, 28000.0, False, False, 500, 0o144, (60, 30), 0, False),
            ('accs_aos_some', 15000.0, 28000.0, False, False, 500, 0o144, (200, 0), 0, False),
            ('accs_aos_big', 15000.0, 28000.0, False, False, 500, 0o144, (300, 100), 0, False),
            ('accs_aos_bigneg', 15000.0, 28000.0, False, False, 500, 0o144, (-250, -200), 0, False),
            ('accs_aos_netneg', 15000.0, 28000.0, False, False, 500, 0o144, (500, 200), 0, False),
            ('accs_aos_vbig', 15000.0, 28000.0, False, False, 500, 0o144, (3500, 1000), 0, False),
            ('accs_aos_ovf', 15000.0, 28000.0, False, False, 500, 0o144, (16000, 6000), 0, False),
            ('accs_aos_fail1', 15000.0, 28000.0, False, False, 500, 0o144, (300, 100), 0o151, False),
            ('accs_aos_fail2', 15000.0, 28000.0, False, False, 500, 0o144, (-300, 100), 0o226, False),
            ('accs_aos_drift', 15000.0, 28000.0, False, False, 0, 0o144, (300, 100), 0, True),
            ('accs_aos_aps', 4800.0, 28000.0, False, True, 900, 0o144, (300, -100), 0, False),
            ('accs_aos_wide', 12000.0, 28000.0, False, False, 300, 0o2000, (-150, 400), 0, False)):
        boolw = (0o10000 if docked else 0) | (0o200 if drift else 0)
        sets = [('MASS', dp(mass, 16)), ('CSMMASS', sp(csm, 16)),
                ('HIASCENT', sp(5500.0, 16)), ('ABDELV', _w(abdelv)), ('DB', _w(db)),
                ('DAPBOOLS', '%05o' % boolw),
                ('FLGWRD10', '10000' if aps else '00000')]
        if aos is not None:
            sets.append(('AOSQ', w([aos[0], 0, aos[1], 0])))
        if ch5:
            sets.append(('CH5MASK', '%05o' % ch5))
        s.run(tag, None, 0o20, 'ENDOFJOB', sets, accs_out, ebank=6, entry='20,2454')
        accs[tag] = probe(s.l)[tag]
    # ---- TJETLAW ----
    s.comment('TJETLAW cases use the block from accs_dps (and accs_aps for *_aps).')
    tj_out = ['TJP', 'TJU', 'TJV', 'NUMBERT', 'FIREFCT']
    for tag, src, e, edot, axis, sense in (
            ('tjet_p_small', 'accs_dps', 40, 10, -1, 0),
            ('tjet_p_neg', 'accs_dps', -60, -25, -1, 0),
            ('tjet_u_mid', 'accs_dps', 150, -40, 0, 0),
            ('tjet_v_rate', 'accs_dps', 20, 300, 1, 0),
            ('tjet_u_large', 'accs_dps', 1500, 50, 0, 1),
            ('tjet_v_coast', 'accs_dps', -5, 2, 1, 2),
            ('tjet_p_aps', 'accs_aps', 90, -60, -1, 0),
            ('tjet_u_aps', 'accs_aps', -300, 120, 0, 0)):
        blk = ','.join(accs[src]['E6,%04o' % (BLOCK + k)] for k in range(48))
        s.run(tag, 'ENDOFJOB', 0o17, 'ENDOFJOB',
              [('E', _w(e)), ('EDOT', _w(edot)), ('AXISCTR', _w(axis)),
               ('SENSETYP', _w(sense)), ('TJP', '00000,00000,00000'),
               ('BLOCKTOP', blk)], tj_out, ebank=6, entry='17,3252')
    # ---- GPMATRIX ----
    gp_out = ['M11', 'M21', 'M22', 'M31', 'M32', 'COSMG']
    gpm = {}
    for tag, x, z in (('gpm_a', 20.0, 10.0), ('gpm_b', 300.0, -50.0), ('gpm_c', 181.0, 85.0)):
        s.run(tag, None, 0o06, 'RESUME', [('CDUX', '%s,00000,%s' % (cdu(x), cdu(z)))],
              gp_out, ebank=6, entry='GPMATRIX')
        gpm[tag] = probe(s.l)[tag]
    # ---- Kalman filter pass ----
    k_out = (['OMEGAP', 'OMEGAQ', 'OMEGAR', 'TRAPEDP', 'TRAPEDQ', 'TRAPEDR',
              'NPTRAPS', 'NQTRAPS', 'NRTRAPS', 'AOSQ:dp', 'AOSR:dp', 'ALPHAQ',
              'ALPHAR', 'AOSQTERM', 'AOSRTERM', 'DXERROR:dp', 'DYERROR:dp',
              'DZERROR:dp', 'JETRATE', 'JETRATEQ', 'JETRATER', 'TJP', 'TJU', 'TJV',
              'OLDXFORP', 'OLDYFORP', 'OLDZFORQ'] +
             ['DOWNTORK+%d' % k if k else 'DOWNTORK' for k in range(6)])
    for tag, gp, tj, cdus, old, traps, ntr, om, drift, acc in (
            ('kal_coast', 'gpm_a', [0, 0, 0], [20.0, 5.0, 10.0], [19.9, 5.05, 9.98],
             [3, -2, 1], [4, 5, 6], [10, -12, 4], True, [0, 0]),
            ('kal_jets', 'gpm_a', [200, -120, 40], [20.3, 4.8, 10.1], [20.0, 5.0, 10.0],
             [-150, 220, 90], [3, 3, 3], [-40, 60, 25], True, [0, 0]),
            ('kal_powered', 'gpm_b', [-300, 80, 0], [300.5, 12.0, -49.5], [300.0, 12.4, -50.0],
             [400, -500, 30], [9, 2, 11], [100, -80, 33], False, [12, -7]),
            ('kal_bigtrap', 'gpm_c', [180, 0, -170], [181.6, -3.0, 84.2], [181.0, -2.0, 85.0],
             [-9000, 8000, -7000], [6, 7, 8], [-300, 250, -200], False, [-30, 22])):
        m = gpm[gp]
        sets = [('TJP', w(tj)), ('NO.PJETS', w([2, 2, 2])), (JACC, w([350, 280, 300])),
                ('DAPTREG4', ','.join(cdu(x) for x in cdus)),
                ('OLDXFORP', ','.join(cdu(x) for x in old)),
                ('TRAPEDP', w(traps) + ',' + w(ntr)), ('OMEGAP', w(om)),
                ('AOSQTERM', w([15, -8])), ('AOSQ', w([300, 120, -200, -50])),
                ('DXERROR', w([20, 100, -15, -30, 5, 9])), ('PLAST', w([10, -20, 30])),
                ('M11', ','.join(m[n] for n in ('M11', 'M21', 'M31', 'M22', 'M32'))),
                ('LMTRAP', w([-200, 10, 60])), ('DAPBOOLS', '00200' if drift else '00000'),
                ('QACCDOT', _w(acc[0])), ('RACCDOT', _w(acc[1]))]
        s.run(tag, None, 0o16, 'PRETIMCK', sets, k_out, ebank=6, entry='16,3641')
    # ---- GTS and TIMEGMBL (review-dap-lm) ----
    s.comment('GTS 21 (trim gimbal control law, both axes): stop CLOSEOUT.')
    s.comment('TIMEGMBL 21 (Q = ENDOFJOB): stop ENDOFJOB.')
    g_out = ['NEGUQ', 'NEGUQ+2', 'QACCDOT', 'RACCDOT', 'RCSFLAGS', 'COTROLER',
             'SKIPU', 'SKIPV', 'INGTS', 'QGIMTIMR', 'QGIMTIMR+2', 'ALLOWGTS']
    for tag, aos, edot, k, err, negu, acc in (
            ('gts_a', (200, -150), (30, -20), (1342, 1328), (-100, 80), (0, 0), (2238, 2214)),
            ('gts_b', (3000, -2600), (-400, 350), (1342, 1328), (900, -700), (1, -1), (2238, 2214)),
            ('gts_c', (40, 25), (5, -3), (700, 0), (12, -9), (-1, 1), (1200, 1100)),
            ('gts_d', (0, 0), (0, 0), (1342, 1328), (0, 3), (1, 1), (2238, 2214)),
            ('gts_e', (-60, 90), (-2, 1), (3000, 2500), (-2, 1), (0, -1), (3000, 2500)),
            ('gts_f', (1000, -800), (250, -200), (400, 300), (4000, -3000), (-1, 0), (900, 800))):
        sets = [('AOSQ', w([aos[0], 0, aos[1], 0])), ('EDOTQ', w(list(edot))),
                ('KQ', w([k[0], 0, k[1]])), ('DXERROR', w([0, 0, err[0], 0, err[1], 0])),
                ('NEGUQ', w([negu[0], 0, negu[1]])),
                ('ACCDOTQ', w([acc[0], 0, acc[1], 0])), ('RCSFLAGS', '00000')]
        s.run(tag, None, 0o21, 'CLOSEOUT', sets, g_out, ebank=6, entry='GTS')
    for tag, aos, acc, negu in (
            ('tg_a', (300, -100), (2238, 2214), (0, 0)),
            ('tg_b', (12000, -3000), (2238, 2214), (1, 1)),
            ('tg_c', (0, 500), (0, 2214), (-1, 1)),
            ('tg_d', (-40, 7), (3000, 9000), (0, 0))):
        sets = [('AOSQ', w([aos[0], 0, aos[1], 0])), ('ACCDOTQ', w([acc[0], 0, acc[1], 0])),
                ('NEGUQ', w([negu[0], 0, negu[1]])), ('QGIMTIMR', w([-16383, 0, -16383])),
                ('RCSFLAGS', '00020')]
        s.run(tag, 'ENDOFJOB', 0o21, 'ENDOFJOB', sets, g_out, ebank=6, entry='TIMEGMBL')
    s.write(os.path.join(OUT, 'dap_lm.spec'))

if __name__ == '__main__':
    main()
