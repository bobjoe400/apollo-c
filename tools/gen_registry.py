#!/usr/bin/env python3
"""gen_registry.py -- write the job/task registry from tools/registry.tsv.

Usage:  python3 -I tools/gen_registry.py [--check]
        make format        (Uncrustify lays the two generated files out)

tools/registry.tsv has one row per executive job or waitlist task:

    kind  id  csm_handler  lm_handler  group  comment

kind is `job` or `task`; a handler is a function name (a job function takes
`agc_job_ctx_t *ctx`, a task function takes no argument), `-` when the id
has no meaning for that vehicle, or `expr:<C expression>` for a call that
needs arguments (the switch variable is `task` for tasks, `ctx` for jobs).
group is the src/ folder that owns the handler; it orders the enums and
names the dispatch functions.

Outputs (both carry a GENERATED banner; edit the table, not the files):

* include/agc/exec/jobs.h -- `agc_job_id_t` and `agc_task_id_t`, one
  enumerator per row, grouped by owning folder in layer order.
* src/exec/dispatch.c -- agc_dispatch_job() and agc_dispatch_task(): the
  one switch from id to function (rule 9: no function pointers), split
  into functions of at most CHUNK cases (rule 4: <= 60 lines) chosen by
  enum range.  An id dispatched on the wrong vehicle returns
  AGC_STATUS_NOT_FOUND.

--check exits 1 when a handler is defined nowhere in src/ or declared in
no public header under include/agc/ (the dispatch file would not build).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, 'tools', 'registry.tsv')
JOBS_H = os.path.join(ROOT, 'include', 'agc', 'exec', 'jobs.h')
DISPATCH_C = os.path.join(ROOT, 'src', 'exec', 'dispatch.c')
CHUNK = 24
BUDGET = 44  # case lines per function; the rest of the body is <= 14
LAYERS = ['exec', 'io', 'imu', 'nav', 'guidance', 'programs', 'csm', 'lm']


def load():
    rows = []
    with open(TABLE) as f:
        for line in f:
            if line.startswith('#') or not line.strip():
                continue
            kind, ident, csm, lm, group, comment = (line.rstrip('\n').split('\t') + [''])[:6]
            rows.append({'kind': kind, 'id': ident, 'csm': '' if csm == '-' else csm,
                         'lm': '' if lm == '-' else lm, 'group': group,
                         'comment': comment.replace('*/', '* /')})
    return rows


def layer(group):
    top = group.split('/')[0]
    return LAYERS.index(top) if top in LAYERS else len(LAYERS)


def ordered(rows, kind):
    sel = [r for r in rows if r['kind'] == kind]
    return sorted(sel, key=lambda r: (layer(r['group']), r['group'], r['id']))


def write_jobs_h(rows):
    out = ['/*',
           ' * jobs.h -- the registry of executive jobs and waitlist tasks.',
           ' *',
           ' * GENERATED by tools/gen_registry.py from tools/registry.tsv. Do not',
           ' * edit: change the table, run `python3 -I tools/gen_registry.py`, then',
           ' * `make format`. src/exec/dispatch.c is generated from the same table.',
           ' *',
           ' * A job or task is named by its AGC entry label (or the NAMING.md stem);',
           ' * the comment gives the label and the restart/phase use. The ids are',
           ' * grouped by the src/ folder that owns the handler, in layer order.',
           ' */',
           '#ifndef AGC_JOBS_H',
           '#define AGC_JOBS_H',
           '']
    for kind, tname, none, count in (('job', 'agc_job_id', 'AGC_JOB_NONE', 'AGC_JOB_COUNT'),
                                     ('task', 'agc_task_id', 'AGC_TASK_NONE', 'AGC_TASK_COUNT')):
        out.append('typedef enum %s' % tname)
        out.append('{')
        out.append('    %s = 0, /* no %s (+0 in a 2CADR word) */' % (none, kind))
        group = None
        for r in ordered(rows, kind):
            if r['group'] != group:
                group = r['group']
                out.append('')
                out.append('    /* ---- src/%s */' % group)
            com = r['comment'] or ''
            veh = ''
            if r['csm'] and not r['lm']:
                veh = 'CSM'
            elif r['lm'] and not r['csm']:
                veh = 'LM'
            if veh:
                com = (veh + ': ' + com) if com else veh
            out.append('    %s,%s' % (r['id'], ('  /* %s */' % com) if com else ''))
        out.append('')
        out.append('    %s /* number of ids; not a %s */' % (count, kind))
        out.append('} %s_t;' % tname)
        out.append('')
    out.append('#endif /* AGC_JOBS_H */')
    with open(JOBS_H, 'w') as f:
        f.write('\n'.join(out) + '\n')


def call(handler, kind):
    if handler.startswith('expr:'):
        return handler[5:]
    return '%s(%s)' % (handler, 'ctx' if kind == 'job' else '')


def case_body(r, kind):
    c, l = r['csm'], r['lm']
    if c and l and c == l:
        return call(c, kind)
    if c and l:
        return 'lm ? %s : %s' % (call(l, kind), call(c, kind))
    if c:
        return 'lm ? AGC_STATUS_NOT_FOUND : %s' % call(c, kind)
    return 'lm ? %s : AGC_STATUS_NOT_FOUND' % call(l, kind)


def case_cost(r, kind):
    """Code lines one case takes after Uncrustify (80 columns)."""
    text = '            return (%s);' % case_body(r, kind)
    return 1 + (len(text) + 75) // 76


def chunks(rows, kind):
    """Split each layer's rows into runs whose cases fit BUDGET lines."""
    out = []
    for top in LAYERS + ['other']:
        sel = [r for r in rows if (r['group'].split('/')[0] if r['group'].split('/')[0] in LAYERS else 'other') == top]
        run, used, n = [], 0, 0
        for r in sel:
            cost = case_cost(r, kind)
            if run and (used + cost > BUDGET or len(run) >= CHUNK):
                out.append((top, n, run))
                run, used, n = [], 0, n + 1
            run.append(r)
            used += cost
        if run:
            out.append((top, n, run))
    return out


def first_assert(kind):
    """A job needs its context; a task runs with interrupts inhibited."""
    cond = 'ctx != NULL' if kind == 'job' else 'agc_interrupts_inhibited()'
    return ['    if (!AGC_ASSERT(%s))' % cond, '    {', '        return (AGC_STATUS_BAD_ARG);', '    }', '']


def emit_chunk(top, n, sel, kind):
    var = 'ctx->id' if kind == 'job' else 'task'
    arg = 'agc_job_ctx_t *ctx' if kind == 'job' else 'agc_task_id_t task'
    name = '%s_%s_%d' % (kind, top, n)
    needs_lm = any(not (r['csm'] and r['lm'] and r['csm'] == r['lm']) for r in sel)
    out = ['/* %s .. %s */' % (sel[0]['id'], sel[-1]['id']),
           'static agc_status_t %s(%s)' % (name, arg), '{']
    out += first_assert(kind)
    out += ['    if (!AGC_ASSERT(%s >= %s && %s <= %s))' % (var, sel[0]['id'], var, sel[-1]['id']),
            '    {', '        return (AGC_STATUS_BAD_ARG);', '    }', '']
    if needs_lm:
        out.append('    bool lm = agc_state_vehicle() == AGC_VEHICLE_LM;')
        out.append('')
    out.append('    switch ((int) %s)' % var)
    out.append('    {')
    for r in sel:
        out.append('        case %s:' % r['id'])
        out.append('            return (%s);' % case_body(r, kind))
    out += ['        default:', '            break;', '    }', '', '    return (AGC_STATUS_NOT_FOUND);', '}', '']
    return name, out


def emit_kind(rows, kind):
    """Chunk functions, then one function per layer choosing a chunk by
    enum range; returns [(layer function, first id)] and the code."""
    sel = ordered(rows, kind)
    parts = chunks(sel, kind)
    out = []
    layers = []
    for top in LAYERS + ['other']:
        mine = [(n, c) for t, n, c in parts if t == top]
        if not mine:
            continue
        names = []
        for n, chunk in mine:
            name, body = emit_chunk(top, n, chunk, kind)
            names.append((name, chunk[0]['id']))
            out += body
        if len(names) == 1:
            layers.append(names[0])
            continue
        lname = '%s_%s' % (kind, top)
        out += ['/* src/%s: %s .. %s */' % (top, mine[0][1][0]['id'], mine[-1][1][-1]['id'])]
        out += range_select('static agc_status_t %s(%s)' % (lname, 'agc_job_ctx_t *ctx' if kind == 'job' else 'agc_task_id_t task'),
                            kind, names, mine[0][1][0]['id'], mine[-1][1][-1]['id'])
        layers.append((lname, mine[0][1][0]['id']))
    return layers, out


def range_select(sig, kind, names, lo, hi):
    var = 'ctx->id' if kind == 'job' else 'task'
    arg = 'ctx' if kind == 'job' else 'task'
    out = [sig, '{']
    out += first_assert(kind)
    out += ['    if (!AGC_ASSERT(%s >= %s && %s <= %s))' % (var, lo, var, hi),
            '    {', '        return (AGC_STATUS_BAD_ARG);', '    }', '']
    for i, (name, firstid) in enumerate(names):
        if i + 1 < len(names):
            out += ['    if (%s < %s)' % (var, names[i + 1][1]), '    {',
                    '        return (%s(%s));' % (name, arg), '    }', '']
        else:
            out.append('    return (%s(%s));' % (name, arg))
    return out + ['}', '']


def headers_for(rows):
    decl = {}
    inc = os.path.join(ROOT, 'include', 'agc')
    for dp, _, files in os.walk(inc):
        for fn in sorted(files):
            if fn.endswith('.h'):
                path = os.path.join(dp, fn)
                text = open(path).read()
                for m in re.finditer(r'\b(agc_\w+)\s*\(', text):
                    decl.setdefault(m.group(1), os.path.relpath(path, os.path.join(ROOT, 'include')))
    need = set()
    missing = []
    for r in rows:
        for h in (r['csm'], r['lm']):
            if not h:
                continue
            name = re.match(r'(?:expr:)?(\w+)', h).group(1)
            if name.startswith('AGC_'):
                continue
            if name in decl:
                need.add(decl[name])
            else:
                missing.append((r['id'], name))
    return sorted(need), missing


def top_level(kind, names, count):
    if kind == 'job':
        sig = 'agc_status_t agc_dispatch_job(agc_job_ctx_t *ctx)'
        var = 'ctx->id'
        arg = 'ctx'
        none = 'AGC_JOB_NONE'
        first = ['    if (!AGC_ASSERT(ctx != NULL))', '    {', '        return (AGC_STATUS_BAD_ARG);', '    }', '']
    else:
        sig = 'agc_status_t agc_dispatch_task(agc_task_id_t task)'
        var = 'task'
        arg = 'task'
        none = 'AGC_TASK_NONE'
        first = ['    if (!AGC_ASSERT(agc_interrupts_inhibited()))', '    {', '        return (AGC_STATUS_BAD_ARG);', '    }', '']
    out = [sig, '{'] + first
    out += ['    if (!AGC_ASSERT(%s > %s && %s < %s))' % (var, none, var, count),
            '    {', '        return (AGC_STATUS_BAD_ARG);', '    }', '']
    for i, (name, firstid) in enumerate(names):
        if i + 1 < len(names):
            out.append('    if (%s < %s)' % (var, names[i + 1][1]))
            out.append('    {')
            out.append('        return (%s(%s));' % (name, arg))
            out.append('    }')
            out.append('')
        else:
            out.append('    return (%s(%s));' % (name, arg))
    out.append('}')
    out.append('')
    return out


def write_dispatch(rows):
    headers, missing = headers_for(rows)
    jnames, jbody = emit_kind(rows, 'job')
    tnames, tbody = emit_kind(rows, 'task')
    if len(jnames) > 25 or len(tnames) > 25:
        sys.exit('gen_registry: too many chunks for one top-level function; raise CHUNK')
    out = ['/*',
           ' * dispatch.c -- the switch from agc_job_id_t to the job functions and the',
           ' * one from agc_task_id_t to the task functions (the AGC\'s 2CADRs; rule 9:',
           ' * no function pointers).',
           ' *',
           ' * GENERATED by tools/gen_registry.py from tools/registry.tsv. Do not',
           ' * edit: change the table, run `python3 -I tools/gen_registry.py`, then',
           ' * `make format`.',
           ' *',
           ' * LAYERING: this is the one place where src/exec/ calls every other',
           ' * layer (documented exception, docs/ARCHITECTURE.md). The cases are',
           ' * split by enum range into functions of at most %d ids (rule 4).' % CHUNK,
           ' */',
           '#include <stdbool.h>',
           '#include <stddef.h>',
           '',
           '#include "agc/core/assert.h"',
           '#include "agc/core/state.h"',
           '#include "agc/exec/exec.h"']
    for h in headers:
        if h not in ('agc/exec/exec.h',):
            out.append('#include "%s"' % h)
    out.append('')
    out += jbody + tbody
    out += top_level('job', jnames, 'AGC_JOB_COUNT')
    out += top_level('task', tnames, 'AGC_TASK_COUNT')
    with open(DISPATCH_C, 'w') as f:
        f.write('\n'.join(out).rstrip('\n') + '\n')
    return missing


def main():
    rows = load()
    ids = [r['id'] for r in rows]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        sys.exit('gen_registry: duplicate ids: ' + ' '.join(dup))
    if '--check' not in sys.argv:
        write_jobs_h(rows)
    missing = write_dispatch(rows) if '--check' not in sys.argv else headers_for(rows)[1]
    for ident, name in missing:
        print('undeclared handler: %s -> %s' % (ident, name))
    print('%d jobs, %d tasks' % (sum(r['kind'] == 'job' for r in rows),
                                 sum(r['kind'] == 'task' for r in rows)))
    return 1 if missing else 0


if __name__ == '__main__':
    sys.exit(main())
