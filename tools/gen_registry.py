#!/usr/bin/env python3
"""gen_registry.py -- write the job/task registry from tools/registry.tsv.

Usage:  python3 -I tools/gen_registry.py [--check]
        make format        (Uncrustify lays the two generated files out)

tools/registry.tsv has one row per executive job or waitlist task:

    kind  id  csm_handler  lm_handler  group  comment

kind is `job` or `task`; a handler is a function name (a job function takes
`agc_job_ctx_t *ctx`, a task function takes no argument), `-` when the id
has no meaning for that vehicle, or `expr:<C expression>` for a call that
needs arguments (the switch variable is `task` for tasks, `ctx` for jobs).
group is the src/ folder that owns the handler; it orders the enums and
names the dispatch functions.

Outputs (both carry a GENERATED banner; edit the table, not the files):

* include/agc/exec/jobs.h -- `agc_job_id_t` and `agc_task_id_t`, one
  enumerator per row, grouped by owning folder in layer order.
* src/exec/dispatch.c -- agc_dispatch_job() and agc_dispatch_task(), which
  pick the vehicle, and four flat switches (agc_dispatch_job_csm,
  agc_dispatch_task_csm, agc_dispatch_job_lm, agc_dispatch_task_lm), one
  `case AGC_JOB_X: return (agc_job_x(ctx));` per registry row in table
  order (rule 9: no function pointers; each rope has its own labels), or
  `case AGC_JOB_X: agc_job_x(ctx); return (AGC_STATUS_OK);` for a handler
  that cannot fail and is declared void (rule 7), each
  with a boxed prolog (docs/STYLE.md).  The file carries the rule 4
  exemption marker.  An id with no function on the vehicle being flown
  returns AGC_STATUS_NOT_FOUND.

--check exits 1 when a handler is defined nowhere in src/ or declared in
no public header under include/agc/ (the dispatch file would not build).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, 'tools', 'registry.tsv')
JOBS_H = os.path.join(ROOT, 'include', 'agc', 'exec', 'jobs.h')
DISPATCH_C = os.path.join(ROOT, 'src', 'exec', 'dispatch.c')
LAYERS = ['exec', 'io', 'imu', 'nav', 'guidance', 'programs', 'csm', 'lm']
VEHICLES = (('csm', 'CSM', 'Comanche055'), ('lm', 'LM', 'Luminary099'))


def load():
    rows = []
    with open(TABLE) as f:
        for line in f:
            if line.startswith('#') or not line.strip():
                continue
            kind, ident, csm, lm, group, comment = (line.rstrip('\n').split('\t') + [''])[:6]
            rows.append({'kind': kind, 'id': ident, 'csm': '' if csm == '-' else csm,
                         'lm': '' if lm == '-' else lm, 'group': group,
                         'comment': comment.replace('*/', '* /')})
    return rows


def layer(group):
    top = group.split('/')[0]
    return LAYERS.index(top) if top in LAYERS else len(LAYERS)


def ordered(rows, kind):
    sel = [r for r in rows if r['kind'] == kind]
    return sorted(sel, key=lambda r: (layer(r['group']), r['group'], r['id']))


def write_jobs_h(rows):
    out = ['/' + '*' * 70,
           ' * FILE NAME: jobs.h',
           ' *',
           ' * PURPOSE:',
           ' *   The registry of executive jobs and waitlist tasks: agc_job_id_t',
           ' *   and agc_task_id_t, the C form of the AGC\'s job and task 2CADRs.',
           ' *   A job or task is named by its AGC entry label (or the NAMING.md',
           ' *   stem); the comment gives the label and the restart/phase use. The',
           ' *   ids are grouped by the src/ folder that owns the handler, in layer',
           ' *   order.',
           ' *',
           ' *   GENERATED by tools/gen_registry.py from tools/registry.tsv. Do not',
           ' *   edit: change the table, run `python3 -I tools/gen_registry.py`,',
           ' *   then format. src/exec/dispatch.c is generated from the same table.',
           ' *',
           ' * AGC SOURCE:',
           ' *   none (registry; the labels are cited per id)',
           ' *',
           ' * REQUIRES:',
           ' *   none (self-contained)',
           ' *',
           ' * GLOBAL VARIABLES:',
           ' *   none',
           ' ' + '*' * 70 + '/',
           '#ifndef AGC_JOBS_H',
           '#define AGC_JOBS_H',
           '']
    for kind, tname, none, count in (('job', 'agc_job_id', 'AGC_JOB_NONE', 'AGC_JOB_COUNT'),
                                     ('task', 'agc_task_id', 'AGC_TASK_NONE', 'AGC_TASK_COUNT')):
        out.append('typedef enum %s' % tname)
        out.append('{')
        out.append('    %s = 0, /* no %s (+0 in a 2CADR word) */' % (none, kind))
        group = None
        for r in ordered(rows, kind):
            if r['group'] != group:
                group = r['group']
                out.append('')
                out.append('    /* ---- src/%s */' % group)
            com = r['comment'] or ''
            veh = ''
            if r['csm'] and not r['lm']:
                veh = 'CSM'
            elif r['lm'] and not r['csm']:
                veh = 'LM'
            if veh:
                com = (veh + ': ' + com) if com else veh
            out.append('    %s,%s' % (r['id'], ('  /* %s */' % com) if com else ''))
        out.append('')
        out.append('    %s /* number of ids; not a %s */' % (count, kind))
        out.append('} %s_t;' % tname)
        out.append('')
    out.append('#endif /* AGC_JOBS_H */')
    with open(JOBS_H, 'w') as f:
        f.write('\n'.join(out) + '\n')


def kind_info(kind):
    """Switch variable, parameter, argument, NONE/COUNT ids, AGC source."""
    if kind == 'job':
        return {'var': 'ctx->id', 'param': 'agc_job_ctx_t *ctx', 'arg': 'ctx',
                'none': 'AGC_JOB_NONE', 'count': 'AGC_JOB_COUNT',
                'what': 'jobs', 'agc': 'EXECUTIVE.agc NUDIRECT / CHANJOB',
                'argdoc': ['ctx -- the job to run (core set 0); ctx->id',
                           '        selects the case']}
    return {'var': 'task', 'param': 'agc_task_id_t task', 'arg': 'task',
            'none': 'AGC_TASK_NONE', 'count': 'AGC_TASK_COUNT',
            'what': 'tasks', 'agc': 'WAITLIST.agc T3RUPT2',
            'argdoc': ['task -- the task to run (LST2 +0), called with',
                       '        interrupts inhibited']}


def prolog(kind, title, returns):
    """Boxed function prolog (docs/templates/function_prolog.c)."""
    k = kind_info(kind)
    out = ['/' + '*' * 70,
           ' * AGC: DTCB to the 2CADR (%s) --' % k['agc'],
           ' *      %s' % title,
           ' *',
           ' * ARGUMENTS:']
    out += [' *   ' + a for a in k['argdoc']]
    out += [' *', ' * RETURNS: agc_status_t -- ' + returns[0]]
    out += [' *          ' + r for r in returns[1:]]
    out.append(' ' + '*' * 70 + '/')
    return out


VOID_JOBS = set()  # handlers declared with a (void) parameter list
VOID_RET = set()   # handlers declared void: they cannot fail (rule 7)


def call(handler, kind):
    if handler.startswith('expr:'):
        return handler[5:]
    takes_ctx = kind == 'job' and handler not in VOID_JOBS
    return '%s(%s)' % (handler, 'ctx' if takes_ctx else '')


def guard(kind):
    """The preconditions of the public entry: the id is a real one (and a
    task runs with interrupts inhibited).  The per-vehicle switches are
    called only from here and do not repeat them; ctx is the executive's
    own core-set address and is never NULL."""
    k = kind_info(kind)
    out = []
    if kind == 'task':
        out += ['    if (!AGC_ASSERT(agc_interrupts_inhibited()))', '    {',
                '        return (AGC_STATUS_BAD_ARG);', '    }', '']
    out += ['    if (!AGC_ASSERT(%s > %s && %s < %s))' % (k['var'], k['none'], k['var'], k['count']),
            '    {', '        return (AGC_STATUS_BAD_ARG);', '    }', '']
    return out


def emit_vehicle(rows, kind, veh, vlabel):
    """One flat switch over every id the vehicle has a function for, in
    registry order, with a one-line comment where the owning folder
    changes. Ids of the other vehicle reach `default`: NOT_FOUND."""
    k = kind_info(kind)
    name = 'agc_dispatch_%s_%s' % (kind, veh)
    title = '%s %s' % (vlabel, k['what'])
    out = prolog(kind, title, ['the status the %s returns;' % kind,
                               'NOT_FOUND when the %s rope has no %s' % (vlabel, kind),
                               'for this id'])
    out += ['static agc_status_t %s(%s)' % (name, k['param']), '{']
    out.append('    switch ((int) %s)' % k['var'])
    out.append('    {')
    group = None
    for r in rows:
        if r['kind'] != kind or not r[veh]:
            continue
        if r['group'] != group:
            group = r['group']
            out.append('        /* src/%s */' % group)
        out.append('        case %s:' % r['id'])
        if r[veh] in VOID_RET:
            out.append('            %s;' % call(r[veh], kind))
            out.append('            return (AGC_STATUS_OK);')
        else:
            out.append('            return (%s);' % call(r[veh], kind))
    out += ['        default:', '            break;', '    } /* switch (%s) */' % k['var'], '',
            '    return (AGC_STATUS_NOT_FOUND);', '} /* %s */' % name, '']
    return name, out


def top_level(kind, roots):
    k = kind_info(kind)
    name = 'agc_dispatch_%s' % kind
    out = prolog(kind, 'the %s of the vehicle being flown' % k['what'],
                 ['the status the %s returns;' % kind,
                  'NOT_FOUND for an id the vehicle has no %s for;' % kind,
                  'BAD_ARG on a failed precondition'])
    out += ['agc_status_t %s(%s)' % (name, k['param']), '{']
    out += guard(kind)
    out += ['    if (agc_state_vehicle() == AGC_VEHICLE_LM)', '    {',
            '        return (%s(%s));' % (roots['lm'], k['arg']), '    }', '',
            '    return (%s(%s));' % (roots['csm'], k['arg']), '} /* %s */' % name, '']
    return out


def headers_for(rows):
    decl = {}
    inc = os.path.join(ROOT, 'include', 'agc')
    for dp, _, files in os.walk(inc):
        for fn in sorted(files):
            if fn.endswith('.h'):
                path = os.path.join(dp, fn)
                text = open(path).read()
                for m in re.finditer(r'\b(agc_\w+)\s*\(', text):
                    decl.setdefault(m.group(1), os.path.relpath(path, os.path.join(ROOT, 'include')))
                for m in re.finditer(r'\b(agc_\w+)\s*\(\s*void\s*\)', text):
                    VOID_JOBS.add(m.group(1))
                for m in re.finditer(r'^\s*void\s+(agc_\w+)\s*\(', text, re.M):
                    VOID_RET.add(m.group(1))
    need = set()
    missing = []
    for r in rows:
        for h in (r['csm'], r['lm']):
            if not h:
                continue
            name = re.match(r'(?:expr:)?(\w+)', h).group(1)
            if name.startswith('AGC_'):
                continue
            if name in decl:
                need.add(decl[name])
            else:
                missing.append((r['id'], name))
    return sorted(need), missing


def write_dispatch(rows):
    headers, missing = headers_for(rows)
    body = []
    tops = []
    for kind in ('job', 'task'):
        roots = {}
        for veh, vlabel, _rope in VEHICLES:
            root, code = emit_vehicle(rows, kind, veh, vlabel)
            roots[veh] = root
            body += code
        tops += top_level(kind, roots)
    out = ['/' + '*' * 70,
           ' * FILE NAME: dispatch.c',
           ' * GENERATED-DISPATCH: rule 4 exempt (docs/CODING_STANDARD.md rule 4)',
           ' *',
           ' * PURPOSE:',
           ' *   The switch from agc_job_id_t to the job functions and the one from',
           ' *   agc_task_id_t to the task functions: the C form of the AGC\'s',
           ' *   2CADR words (rule 9: no function pointers). One switch tree per',
           ' *   vehicle and kind, as each rope has its own set of labels: four',
           ' *   flat switches (CSM jobs, CSM tasks, LM jobs, LM tasks) and the two',
           ' *   public entry points that pick the vehicle.',
           ' *',
           ' *   GENERATED by tools/gen_registry.py from tools/registry.tsv. Do not',
           ' *   edit: change the table, run `python3 -I tools/gen_registry.py`,',
           ' *   then format the two generated files.',
           ' *',
           ' * AGC SOURCE:',
           ' *   Comanche055 EXECUTIVE.agc p.1220 (NUDIRECT), WAITLIST.agc p.1232',
           ' *   (T3RUPT2): DTCB to the 2CADR of the job or task',
           ' *   Luminary099 EXECUTIVE.agc p.1116, WAITLIST.agc p.1128 (identical)',
           ' *',
           ' * EXTERNAL VARIABLES:',
           ' *   none',
           ' *',
           ' * EXTERNAL REFERENCES:',
           ' *   Name                  Description',
           ' *   --------------------  ------------------------------------------',
           ' *   agc_job_* / agc_task_*  every job and task function named in',
           ' *                         tools/registry.tsv',
           ' *   agc_state_vehicle     the rope being flown (core/state.h)',
           ' *',
           ' * ABNORMAL TERMINATION CONDITIONS, ALARMS:',
           ' *   AGC_STATUS_NOT_FOUND for an id with no function on this vehicle;',
           ' *   AGC_STATUS_BAD_ARG on a failed precondition; otherwise the job\'s or',
           ' *   task\'s own status.',
           ' *',
           ' * ASSUMPTIONS, CONSTRAINTS, RESTRICTIONS:',
           ' *   Rule 4 is waived for the four switches (docs/CODING_STANDARD.md,',
           ' *   rule 4 exemption): the unit a reviewer verifies is the table and',
           ' *   the generator. Cases are in tools/registry.tsv order, with a',
           ' *   comment where the owning folder changes.',
           ' *',
           ' * NOTES:',
           ' *   LAYERING: this is the one place where src/exec/ calls every other',
           ' *   layer (documented exception, docs/ARCHITECTURE.md).',
           ' ' + '*' * 70 + '/',
           '#include <stdbool.h>',
           '#include <stddef.h>',
           '',
           '#include "agc/core/assertion.h"',
           '#include "agc/core/state.h"',
           '#include "agc/exec/exec.h"']
    for h in headers:
        if h not in ('agc/exec/exec.h',):
            out.append('#include "%s"' % h)
    out.append('')
    out += body + tops
    with open(DISPATCH_C, 'w') as f:
        f.write('\n'.join(out).rstrip('\n') + '\n')
    return missing


def main():
    rows = load()
    ids = [r['id'] for r in rows]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        sys.exit('gen_registry: duplicate ids: ' + ' '.join(dup))
    if '--check' not in sys.argv:
        write_jobs_h(rows)
    missing = write_dispatch(rows) if '--check' not in sys.argv else headers_for(rows)[1]
    for ident, name in missing:
        print('undeclared handler: %s -> %s' % (ident, name))
    print('%d jobs, %d tasks' % (sum(r['kind'] == 'job' for r in rows),
                                 sum(r['kind'] == 'task' for r in rows)))
    return 1 if missing else 0


if __name__ == '__main__':
    sys.exit(main())
