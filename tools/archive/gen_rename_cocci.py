#!/usr/bin/env python3
"""gen_rename_cocci.py -- build tools/archive/rename.cocci from docs/history/RENAMES.md.

Usage:  python3 -I tools/archive/gen_rename_cocci.py [--list]

Reads the lane tables of docs/history/RENAMES.md (rows "| `old` | `new` | ...")
and writes ONE semantic patch, tools/archive/rename.cocci, with a rule per
identifier kind: function definitions and prototypes, identifier
expressions (calls, enum constants, macro constants, variables), struct
fields (declarations, '.' and '->' access, designated initializers),
parameters, variable declarations, enumerator declarations and
#define names (the map renames no typedef).  Every rule looks the identifier up in one Python table and
builds the replacement with a 'fresh identifier', so the rule count does
not grow with the map.  Comments are never touched by spatch.

The 'files', 'docs' and 'keep' sections are not identifier renames of C
code: 'files' is applied with git mv, 'docs' (and every row) with a plain
word-boundary substitution in docs/modules notes.

--list prints old<TAB>new for the C rows (used by the verification step).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RENAMES = os.path.join(ROOT, 'docs', 'RENAMES.md')
OUT = os.path.join(ROOT, 'tools', 'rename.cocci')

SKIP_SECTIONS = ('files', 'docs', 'keep', 'Duplicate', 'Not resolved',
                 'Baseline', 'Earlier')
ROW = re.compile(r'^\| `([A-Za-z_][A-Za-z0-9_]*)` \| `([A-Za-z_][A-Za-z0-9_]*)` \|')


def load_map():
    """Return {old: new} for the C identifier rows of RENAMES.md."""
    table = {}
    section = ''
    with open(RENAMES) as f:
        for line in f:
            if line.startswith('## '):
                section = line[3:].strip()
                continue
            if section.startswith(SKIP_SECTIONS):
                continue
            m = ROW.match(line)
            if m and m.group(1) != m.group(2):
                old, new = m.group(1), m.group(2)
                if table.get(old, new) != new:
                    sys.exit('conflicting rows for %s' % old)
                table[old] = new
    return table


HEADER = '''// rename.cocci -- GENERATED by tools/archive/gen_rename_cocci.py from
// docs/history/RENAMES.md.  Do not edit; regenerate.
//   spatch --sp-file tools/archive/rename.cocci --in-place \\
//          --dir src --dir include --dir tests

@initialize:python@
@@
RENAME = {
%s
}
'''

# One block per identifier kind.  OLD/NEW are the metavariable names.
META = '''identifier OLD : script:python() { OLD in RENAME };
fresh identifier NEW = script:python(OLD) { RENAME[OLD] };'''

RULES = [
    # function definitions
    ('fn_def', 'type T;\nparameter list PS;', 'T\n- OLD\n+ NEW\n  (PS) {...}'),
    # prototypes
    ('fn_proto', 'type T;\nparameter list PS;', 'T\n- OLD\n+ NEW\n  (PS);'),
    # parameters (definitions and prototypes)
    ('par_def', 'type T, T2;\nidentifier F;',
     'T F(...,\n  T2\n- OLD\n+ NEW\n  ,...) {...}'),
    ('par_proto', 'type T, T2;\nidentifier F;',
     'T F(...,\n  T2\n- OLD\n+ NEW\n  ,...);'),
    # variable declarations (locals, statics, globals, arrays)
    ('var_decl', 'type T;', 'T\n- OLD\n+ NEW\n  ;'),
    ('var_init', 'type T;\nexpression E;', 'T\n- OLD\n+ NEW\n  = E;'),
    ('arr_decl', 'type T;\nexpression N;', 'T\n- OLD\n+ NEW\n  [N];'),
    ('arr_init', 'type T;\nexpression N;\ninitializer list IL;',
     'T\n- OLD\n+ NEW\n  [N] = {IL};'),
    ('arr_init2', 'type T;\ninitializer list IL;',
     'T\n- OLD\n+ NEW\n  [] = {IL};'),
    # struct fields: declaration and access
    ('fld_decl', 'identifier S;\ntype T;',
     'struct S { ...\n  T\n- OLD\n+ NEW\n  ;\n  ... };'),
    ('fld_arr', 'identifier S;\ntype T;\nexpression N;',
     'struct S { ...\n  T\n- OLD\n+ NEW\n  [N];\n  ... };'),
    ('fld_dot', 'expression E;', 'E.\n- OLD\n+ NEW'),
    ('fld_arrow', 'expression E;', 'E->\n- OLD\n+ NEW'),
    # enumerator declarations
    ('enum_decl', 'identifier EN;', 'enum EN { ...,\n- OLD\n+ NEW\n  , ...};'),
    ('enum_val', 'identifier EN;\nexpression E;',
     'enum EN { ...,\n- OLD\n+ NEW\n  = E, ...};'),
    ('tenum_decl', 'identifier EN;\ntype TN;',
     'typedef enum EN { ...,\n- OLD\n+ NEW\n  , ...} TN;'),
    ('tenum_val', 'identifier EN;\ntype TN;\nexpression E;',
     'typedef enum EN { ...,\n- OLD\n+ NEW\n  = E, ...} TN;'),
    ('anon_enum', '', 'enum { ...,\n- OLD\n+ NEW\n  , ...};'),
    # #define names
    ('def_val', 'expression E;', '- #define OLD E\n+ #define NEW E'),
    ('def_bare', '', '- #define OLD\n+ #define NEW'),
    # every remaining use as an expression (calls, enum and macro
    # constants, variables, case labels, function designators)
    ('expr', '', '(\n- OLD\n+ NEW\n)'),
]


def main():
    table = load_map()
    if '--list' in sys.argv:
        for old in sorted(table):
            print('%s\t%s' % (old, table[old]))
        return
    body = ',\n'.join('    %r: %r' % (o, table[o]) for o in sorted(table))
    parts = [HEADER % body]
    for name, extra, pattern in RULES:
        meta = META + ('\n' + extra if extra else '')
        parts.append('@%s@\n%s\n@@\n%s\n' % (name, meta, pattern))
    with open(OUT, 'w') as f:
        f.write('\n'.join(parts))
    print('%d identifiers, %d rules -> %s' % (len(table), len(RULES),
                                               os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    main()
