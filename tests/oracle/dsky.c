/**********************************************************************
 * FILE NAME: dsky.c
 *
 * PURPOSE:
 *   Pinball decimal display against the real AGC code (yaAGC). Every run
 *   is an internal NVSUB: "V06 Nnn" (DECDSP through every SF output
 *   routine of SFOUTABR, DSPDECWD, DSPDC2NR, HMSOUT, M/SOUT, 2INTOUT,
 *   DSPDECVN) or a verb paste (noun 0, UPDATVB -> DSPDECVN). The noun's
 *   erasables are written through the noun data layer (agc_noun_write)
 *   or, for the machine-address nouns 01-03, the ECADR image; the eleven
 *   DSPTAB words, NOUT, VERBREG and NOUNREG are compared bit-exact.
 *   Negative TIG/TTOGO and the two-integer words of nouns 45/64 (no load
 *   in the AGC) go through agc_noun_write too.
 *
 * AGC SOURCE:
 *   Comanche055 PINBALL_GAME_BUTTONS_AND_LIGHTS.agc pp. 330-363 (DECDSP,
 *   SFOUTABR, DSPDECWD .. DSPDECVN); Luminary099 pp. 381-399 (identical).
 *   Inputs and expected words: tools/oracle/cases/dsky.spec / .txt
 *   (Comanche055) and dsky_lm.spec / .txt (Luminary099), generated by
 *   tools/oracle/cases/gen/gen_dsky.py.
 *
 * EXTERNAL VARIABLES:
 *   oracle_spec (oracle_txt.h): the loaded spec text
 *
 * EXTERNAL REFERENCES:
 *   Name                  Description
 *   --------------------  ------------------------------------------
 *   agc_dsky_nvsub ...    the pinball display entry points under test
 *   oracle_load / _cmp    case files and bit-exact comparison
 *
 * ABNORMAL TERMINATION CONDITIONS, ALARMS:
 *   Exit status 1 when any comparison fails (oracle_finish). Missing case
 *   files skip the test.
 **********************************************************************/
