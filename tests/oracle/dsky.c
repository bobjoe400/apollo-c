#define DSKY_MCTBS_NAME "E7,1700" /* ECADR image of nouns 01-03 */

/**********************************************************************
 * AGC: none (test helper) -- bit-exact comparison (all findings
 *      closed; F15 fixed in review-io-dsky)
 *
 * FUNCTION NAME: check
 *
 * ARGUMENTS:
 *   Argument  Type           I/O  Description
 *   --------  -------------  ---  ---------------------------------
 *   t         const char *   I    run tag
 *   what      const char *   I    quantity compared
 *   got       long int       I    C value
 *   want      long int       I    AGC value
 **********************************************************************/
static void check(const char *t, const char *what, long int got,
                  long int want)
{
    (void) oracle_cmp(t, what, got, want, 0);
}

/**********************************************************************
 * AGC: none (test helper) -- erasables of a noun for one vehicle
 *
 * FUNCTION NAME: find_noun
 *
 * ARGUMENTS:
 *   Argument  Type           I/O  Description
 *   --------  -------------  ---  ---------------------------------
 *   lm        bool           I    true for Luminary099
 *   noun      int            I    noun number
 *
 * RETURNS: const dsky_noun_t * -- the row, NULL when the noun is not listed
 **********************************************************************/
static const dsky_noun_t *find_noun(bool lm, int noun)
{
    const dsky_noun_t *t = lm ? k_lm : k_cm; /* table of the vehicle */
    const size_t       n = lm ? /* its row count */
                           sizeof (k_lm) / sizeof (k_lm[0]) :
                           sizeof (k_cm) / sizeof (k_cm[0]);

    for (size_t i = 0; i < n; i++)
    {
        if (t[i].noun == noun)
        {
            return (&t[i]);
        }
    }

    return (NULL);
}

/**********************************************************************
 * AGC: none (test helper) -- store one noun component from the spec
 *
 * FUNCTION NAME: write_comp
 *
 * ARGUMENTS:
 *   Argument  Type                      I/O  Description
 *   --------  ------------------------  ---  ----------------------
 *   t         const char *              I    run tag
 *   id        uint16_t                  I    noun data id
 *   si        const agc_scale_info_t *  I    scale of the component
 *   name      const char *              I    spec erasable name
 *   idx       int                       I    word index into it
 *
 * RETURNS: agc_status_t -- status of the noun write
 **********************************************************************/
static agc_status_t write_comp(const char *t, uint16_t id,
                               const agc_scale_info_t *si, const char *name,
                               int idx)
{
    agc_dp_t v; /* component value, scale of the noun */

    if (si->is_dp)
    {
        v = oracle_in_dp(t, name, idx);
    }
    else if (si->is_raw)
    {
        v = (agc_dp_t) oracle_in_raw(t, name, idx);
    }
    else
    {
        v = agc_dp_from_sp((agc_sp_t) oracle_in(t, name, idx));
    }

    agc_status_t st = agc_dsky_noun_write(id, v); /* pinball-owned ids */

    if (st == AGC_STATUS_NOT_FOUND)
    { /* ids pinball does not own go through the noun data layer */
        st = agc_noun_write(id, v);
    }

    return (st);
}

/**********************************************************************
 * AGC: none (test helper) -- compare DSPTAB, NOUT, VERBREG, NOUNREG
 *
 * FUNCTION NAME: compare
 *
 * ARGUMENTS:
 *   Argument  Type           I/O  Description
 *   --------  -------------  ---  ---------------------------------
 *   t         const char *   I    run tag
 **********************************************************************/
static void compare(const char *t)
{
    char name[16]; /* spec name of a DSPTAB word */

    if (getenv("ORACLE_VERBOSE") != NULL)
    { /* the C display words, for gen/dsky_show.py */
        (void) printf("CDSPTAB %s", t);

        for (int k = 0; k < PIN_DSPTAB_PANEL; k++)
        {
            (void) printf(" %05o", (unsigned int) agc_erase_dsptab(k));
        }

        (void) printf("\n");
    }

    for (int k = 0; k < PIN_DSPTAB_PANEL; k++)
    {
        (void) snprintf(name, sizeof (name), "DSPTAB+%d", k);
        check(t, name, (long int) agc_erase_dsptab(k),
              (long int) oracle_out_raw(t, name));
    }

    check(t, "NOUT", pin_st()->nout, oracle_out_sp(t, "NOUT"));
    check(t, "VERBREG", pin_st()->verbreg, oracle_out_sp(t, "VERBREG"));
    check(t, "NOUNREG", pin_st()->nounreg, oracle_out_sp(t, "NOUNREG"));
}

/**********************************************************************
 * AGC: none (test) -- one "run TAG": load the noun, NVSUB, compare
 *
 * FUNCTION NAME: one
 *
 * ARGUMENTS:
 *   Argument  Type           I/O  Description
 *   --------  -------------  ---  ---------------------------------
 *   t         const char *   I    run tag
 *   lm        bool           I    true for Luminary099
 **********************************************************************/
static void one(const char *t, bool lm)
{
    const int    vnw   = oracle_in(t, "NVTEMP", 0); /* NVTEMP verb/noun */
    const int    verb  = (vnw >> 7) & 0177; /* verb of NVTEMP */
    const int    noun  = vnw & 0177; /* noun of NVTEMP */
    const bool   mctbs = noun >= 1 && noun <= 3; /* machine-address noun */
    agc_status_t st    = AGC_STATUS_OK; /* status so far */

    oracle_require_ok(t, "ENDOFJOB");
    agc_state_init(lm ? AGC_VEHICLE_LM : AGC_VEHICLE_CSM); /* vehicle */
    (void) agc_exec_init();
    (void) agc_waitlist_init();
    (void) agc_dsky_init();

    if (noun == 0)
    {
        st = agc_dsky_nvsub((uint8_t) verb, 0);
    }
    else if (mctbs)
    {
        for (int k = 0; k < 3; k++)
        {
            st = agc_erase_write_ecadr((uint16_t) (03700 + k),
                                       oracle_in_raw(t, DSKY_MCTBS_NAME, k));
        }

        st = agc_dsky_nvsub_mctbs((uint8_t) verb, (uint8_t) noun,
                                  (uint16_t) oracle_in(t, "MPAC+2", 0));
    }
    else
    {
        const dsky_noun_t *dn = find_noun(lm, noun); /* its erasables */
        agc_noun_t         row; /* noun table row */

        if (dn == NULL ||
            agc_noun_lookup((uint8_t) noun, &row) != AGC_STATUS_OK)
        {
            (void) oracle_cmp(t, "noun table", 1, 0, 0);

            return;
        }

        for (int k = 0; k < (int) row.ncomp && st == AGC_STATUS_OK; k++)
        {
            agc_scale_info_t si; /* scale of component k */

            if (dn->name[k] == NULL)
            {
                continue; /* HMS: one DP time for the three registers */
            }

            st = agc_scale_info((agc_scale_t) row.scale_type[k], &si);

            if (st == AGC_STATUS_OK)
            {
                st = write_comp(t, row.data_id[k], &si, dn->name[k],
                                dn->idx[k]);
            }
        }

        (void) oracle_cmp(t, "noun write status", st, AGC_STATUS_OK, 0);
        st = agc_dsky_nvsub((uint8_t) verb, (uint8_t) noun);
    }

    check(t, "nvsub status", st, AGC_STATUS_OK);
    compare(t);
} /* one */

/**********************************************************************
 * AGC: none (test) -- every "run TAG" of the loaded spec
 *
 * FUNCTION NAME: all_runs
 *
 * ARGUMENTS:
 *   Argument  Type           I/O  Description
 *   --------  -------------  ---  ---------------------------------
 *   lm        bool           I    true for Luminary099
 **********************************************************************/
static void all_runs(bool lm)
{
    const char *p = strstr(oracle_spec, "\nrun "); /* next run line */

    while (p != NULL)
    {
        char   tag[64]; /* run tag */
        size_t n = strcspn(p + 5, "\n"); /* tag length */

        if (n >= sizeof (tag))
        {
            n = sizeof (tag) - 1;
        }

        (void) memcpy(tag, p + 5, n);
        tag[n] = '\0';
        one(tag, lm);
        p = strstr(p + 5, "\nrun ");
    }
}
