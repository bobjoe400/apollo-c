/**********************************************************************
 * FILE NAME: imu.c
 *
 * PURPOSE:
 *   imu lane against the real AGC code (yaAGC oracle): CALCGTA, CALCGA
 *   (incl. the gimbal-lock alarm), AXISGEN, 1/PIPA + IRIGCOMP (PIPA and
 *   gyro compensation feeding IMUPULSE), KALCMAN3 set-up (MFI, COFSKEW,
 *   CAM, AM, COF) with the DEL of its first WCALC step, DELCOMP and
 *   DCMTOCDU.
 *
 * AGC SOURCE:
 *   none (tests of src/imu and src/csm/prelaunch_*, whose prologs cite
 *   the listings)
 *
 * EXTERNAL VARIABLES:
 *   none
 *
 * EXTERNAL REFERENCES:
 *   Name                  Description
 *   --------------------  ------------------------------------------
 *   oracle_load, oracle_cmp  case reader and comparison (oracle_txt.h)
 *   agc_imu_*, agc_kalc_*  the functions under test (imu.h)
 *
 * ABNORMAL TERMINATION CONDITIONS, ALARMS:
 *   Exit status 1 when any check fails.
 *
 * NOTES:
 *   Inputs and expected words: tools/oracle/cases/imu.spec / .txt
 *   (Comanche055), generated by tools/oracle/cases/gen/gen_imu.py.
 *   Tolerances (LSB of the AGC word): see docs/modules/oracle-cases.md;
 *   the remaining non-zero ones are oracle finding F5 (word splits).
 **********************************************************************/
