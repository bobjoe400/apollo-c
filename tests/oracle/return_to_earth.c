/**********************************************************************
 * FILE NAME: return_to_earth.c
 *
 * PURPOSE:
 *   P37 conic search against the real AGC (yaAGC oracle). One conic
 *   search from RTE299: INVC100 (a zero-length CSMPREC, so R(T1)/ =
 *   RRECTCSM), RTE317..RTE390 (V2T100, TMRAD100, the X(T2) / RCON
 *   iteration), P37E and RTEDISP; for a transearth, a midcourse and a
 *   near-earth abort, with the entry angle computed and given.
 *
 * AGC SOURCE:
 *   Comanche055 P37_P70.agc pp. 891-930 (run in yaAGC; cases in
 *   tools/oracle/cases/return_to_earth.spec / .txt, generated by
 *   tools/oracle/cases/gen/gen_rte.py)
 *
 * EXTERNAL VARIABLES:
 *   none (the P37 erasables through rte_state())
 *
 * EXTERNAL REFERENCES:
 *   Name                  Description
 *   --------------------  ------------------------------------------
 *   oracle_*              case reader and comparisons (oracle_txt.h)
 *   rte_initial_vectors .. rte_display_values  INVC100 .. RTEDISP
 *
 * ABNORMAL TERMINATION CONDITIONS, ALARMS:
 *   exit status 1 when a comparison fails (oracle_finish); KNOWN entries
 *   (finding F14) are reported, not failed.
 *
 * ASSUMPTIONS, CONSTRAINTS, RESTRICTIONS:
 *   Tolerances (LSB of the AGC word): docs/modules/oracle-cases.md.
 **********************************************************************/
#include <stdio.h>

#include "../../src/csm/burns/return_to_earth/internal.h"
#include "agc/core/assert.h"
#include "agc/core/flags_common.h"
#include "agc/core/interp.h"
#include "agc/core/state.h"
#include "agc/exec/exec.h"
#include "agc/nav/auxiliary.h"
#include "oracle_txt.h"

static void rte(const char *t, long int tol);

/**********************************************************************
 * AGC: none -- run every case; the exit status reports failures.
 *
 * FUNCTION NAME: main
 *
 * ARGUMENTS: none
 *
 * RETURNS: int -- 0 when every comparison passes (or the case files are
 *          missing), 1 otherwise
 **********************************************************************/
int main(void)
{
    if (!oracle_load("return_to_earth"))
    {
        (void) printf("oracle_return_to_earth: SKIP (case files not found)\n");

        return (0);
    }

    rte("rte_transearth", 128);
    rte("rte_transearth_gam", 128);
    rte("rte_midcourse", 128);
    rte("rte_leo", 128);

    return (oracle_finish("oracle_return_to_earth"));
}

/**********************************************************************
 * AGC: none -- assertion hook of the library: print and continue.
 *
 * FUNCTION NAME: agc_assert_report
 *
 * ARGUMENTS:
 *   Argument  Type          I/O  Description
 *   --------  ------------  ---  ----------------------------------
 *   file      const char *  I    source file of the failed assertion
 *   line      int           I    its line
 *   expr      const char *  I    the asserted expression
 *
 * RETURNS: bool -- false (the assertion stays failed)
 **********************************************************************/
bool agc_assert_report(const char *file, int line, const char *expr)
{
    (void) printf("assert %s:%d %s\n", file, line, expr);

    return (false);
}

/**********************************************************************
 * RTE299 .. RTEDISP (P37_P70.agc pp. 891-904) -- one conic search case
 * and its comparisons.
 *
 * FUNCTION NAME: rte
 *
 * ARGUMENTS:
 *   Argument  Type          I/O  Description
 *   --------  ------------  ---  ----------------------------------
 *   t         const char *  I    case name
 *   tol       long int      I    tolerance, LSB of the AGC word
 *
 * RETURNS: none
 **********************************************************************/
static void rte(const char *t, long int tol)
{
    agc_navaux_padload_t pad = {0}; /* pad loads (zero)          */
    rte_display_t        d   = {0}; /* display values             */
    agc_interp_t        *ip;        /* P37 interpreter state      */
    rte_erasable_t      *rs;        /* P37 erasables              */
    agc_vec_t            r;         /* RRECTCSM, m B29            */
    agc_vec_t            v;         /* VRECTCSM, m/cs B7          */
    agc_dp_t             tig;       /* TIG, cs B28                */
    agc_status_t         st;        /* status of the chain        */

    agc_state_init(AGC_VEHICLE_CSM);
    (void) agc_exec_init();
    (void) agc_waitlist_init();
    (void) agc_navaux_set_padload(&pad);
    ip           = rte_ip();
    rs           = rte_state();
    agc_interp_init(ip);
    rs->rtedvd   = oracle_in_dp(t, "VPRED", 0);
    rs->rtegam2d = oracle_in_dp(t, "GAMMAEI", 0);
    agc_erase_set_rted1(oracle_in_dp(t, "1351", 0));
    r            = oracle_in_vec_at(t, "RRECTCSM", 0);
    v            = oracle_in_vec_at(t, "RRECTCSM", 1);
    tig          = oracle_in_dp(t, "TIG", 0);
    st           = rte_initial_vectors(ip, rs, r, v, tig, 0);

    if (st == AGC_STATUS_OK)
    {
        st = rte_conic_setup(ip, rs);
    }

    if (st == AGC_STATUS_OK)
    {
        st = rte_conic_search(ip, rs, agc_erase_rted1());
    }

    if (st == AGC_STATUS_OK)
    {
        st = rte_display_values(ip, rs, tig, 0, &d);
    }

    oracle_require_ok(t, "P370GOFR");
    (void) oracle_cmp(t, "status", st, AGC_STATUS_OK, 0);
    (void) oracle_cmp(t, "R(T1)", rs->r_t1, oracle_out_dp(t, "R(T1)"), 0);
    oracle_cmp_vec(t, "UR1/", rs->ur1, oracle_out_vec(t, "UR1/"), 0);
    (void) oracle_cmp(t, "CFPA", rs->cfpa, oracle_out_dp(t, "CFPA"), 1);
    (void) oracle_cmp(t, "MAMAX2", rs->mamax2, oracle_out_dp(t, "MAMAX2"), 1);

    /* INVC115: the AGC keeps N = UR1 x UV1 as sign-disagreeing DP words
     * (e.g. 00232 76635); the next VXV and UNIT round differently, UH/ by
     * up to ~80 LSB for a near-radial state.                             */
    oracle_cmp_vec(t, "UH/", rs->uh, oracle_out_vec(t, "UH/"), tol);

    /* F14 (review-guid-entry): the C now matches the AGC word for word
     * through V2T100/GAMDV/DVCALC from the same start. What is left comes
     * from outside the lane: UH/ above (INVC115, core VXV on disagreeing
     * words), V(T2)/ from TIMERAD (nav-conic, a few high-word LSB) and
     * the GAMDV X(T1) steps whose words disagree (core). The X(T2)/RCON
     * search then converges inside its tolerance to a slightly different
     * solution; the flat DV minimum moves X(T1) most.                    */
    (void) oracle_cmp(t, "RCON", rs->rcon, oracle_out_dp(t, "RCON"), tol);
    oracle_cmp_known(t, "X(T2)", rs->x_t2, oracle_out_dp(t, "X(T2)"), tol, "F14");
    oracle_cmp_known(t, "X(T1)", rs->x_t1, oracle_out_dp(t, "X(T1)"), tol, "F14");
    (void) oracle_cmp(t, "PCON", rs->pcon, oracle_out_dp(t, "PCON"), tol);
    oracle_cmp_vec_known(t, "V2(T1)/", rs->v2_t1v, oracle_out_vec(t, "V2(T1)/"), tol, "F14");
    (void) oracle_cmp(t, "DV", rs->dv, oracle_out_dp(t, "DV"), tol);
    oracle_cmp_vec(t, "R(T2)/", rs->r_t2v, oracle_out_vec(t, "R(T2)/"), tol);
    oracle_cmp_vec_known(t, "V(T2)/", rs->v_t2v, oracle_out_vec(t, "V(T2)/"), tol, "F14");
    oracle_cmp_known(t, "T2", rs->t2, oracle_out_dp(t, "T2"), tol, "F14");
    (void) oracle_cmp(t, "T12", rs->t12, oracle_out_dp(t, "T12"), tol);
    (void) oracle_cmp(t, "NN1A", rs->nn1a, oracle_out_dp(t, "NN1A"), 2);
    oracle_cmp_known(t, "VPRED", d.vpred, oracle_out_dp(t, "VPRED"), tol, "F14");
    oracle_cmp_known(t, "T3TOT4", d.t3tot4, oracle_out_dp(t, "T3TOT4"), tol, "F14");
    oracle_cmp_known(t, "GAMMAEI", d.gammaei, oracle_out_dp(t, "GAMMAEI"), tol, "F14");
    oracle_cmp_known(t, "LAT(SPL)", d.lat_spl, oracle_out_dp(t, "LAT(SPL)"), tol, "F14");
    oracle_cmp_known(t, "LNG(SPL)", d.lng_spl, oracle_out_dp(t, "LNG(SPL)"), tol, "F14");
    oracle_cmp_vec_known(t, "DELVLVC", d.delvlvc, oracle_out_vec(t, "DELVLVC"), tol, "F14");
} /* rte */
