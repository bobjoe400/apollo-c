/**********************************************************************
 * FILE NAME: nav_auxiliary.c
 *
 * PURPOSE:
 *   nav-aux against the real AGC code (yaAGC oracle).  Routines:
 *   LAT-LONG, LALOTORV, RP-TO-R, R-TO-RP, TFFCONIC, TFFRP/RA, CALCTFF,
 *   LSPOS and LUNVEL (CM), LSPOS (LM), INCORP2 (W update and state
 *   update).  Tolerances (LSB of the AGC word): see
 *   docs/overview/oracle-cases.md.
 *
 * AGC SOURCE:
 *   Comanche055 / Luminary099, the files cited in auxiliary.h.  Inputs
 *   and expected words: tools/oracle/cases/nav_aux.spec / .txt
 *   (Comanche055) and nav_aux_lm.spec / .txt (Luminary099), generated by
 *   tools/oracle/cases/gen/gen_nav_aux.py.
 *
 * EXTERNAL VARIABLES:
 *   oracle_spec (oracle_txt.h): the loaded spec text
 *
 * EXTERNAL REFERENCES:
 *   Name                  Description
 *   --------------------  ------------------------------------------
 *   agc_latlong_*, agc_planet_*, agc_tff_*, agc_ephem_*,
 *   agc_incorp_update_*   the nav-aux functions under test
 *   oracle_load / _cmp    case files and comparison (oracle_txt.h)
 *
 * ABNORMAL TERMINATION CONDITIONS, ALARMS:
 *   Exit status 1 when any comparison fails (oracle_finish).  Missing
 *   case files skip the test.
 **********************************************************************/
