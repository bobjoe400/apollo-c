/**********************************************************************
 * AGC: none (oracle case) -- TFFCONIC, TFFRP/RA, CALCTFF
 *
 * FUNCTION NAME: tff
 *
 * ARGUMENTS:
 *   Argument   Type                   I/O  Description
 *   ---------  ---------------------  ---  ----------------------------
 *   base       const char *           I    case tag stem (_conic/_rpra/_calc)
 *   tol        long int               I    tolerance, LSB
 *
 * RETURNS: void
 **********************************************************************/
static void tff(const char *base, long int tol)
{
    char      tc[96];     /* TFFCONIC case tag   */
    char      tr[96];     /* TFFRP/RA case tag   */
    char      tt[96];     /* CALCTFF case tag    */
    agc_tff_t f    = {0}; /* TFFCONIC result     */
    agc_tff_t g;          /* copy per routine    */
    agc_dp_t  tffv = 0;   /* TFF, scale 2^28 cs  */

    (void) snprintf(tc, sizeof (tc), "%s_conic", base);
    (void) snprintf(tr, sizeof (tr), "%s_rpra", base);
    (void) snprintf(tt, sizeof (tt), "%s_calc", base);
    agc_interp_t ip; /* interpreter state */

    agc_interp_init(&ip);
    tff_conic_of(tc, &ip, &f);
    oracle_require_ok(tc, "POODOO");
    (void) oracle_cmp(tc, "RMAG1", f.rmag1, oracle_out_dp(tc, "VAC1+12"), tol);
    (void) oracle_cmp(tc, "TFFVSQ", f.tffvsq, oracle_out_dp(tc, "VAC1+20"), tol);
    (void) oracle_cmp(tc, "TFF1/ALF", f.tff1_alf, oracle_out_dp(tc, "VAC1+22"), tol);
    (void) oracle_cmp(tc, "TFFRTALF", f.tffrtalf, oracle_out_dp(tc, "VAC1+24"), tol);
    (void) oracle_cmp(tc, "TFFALFA", agc_dp_from_words(f.tffalfa), oracle_out_dp(tc, "VAC1+26"), tol);
    (void) oracle_cmp(tc, "TFFNP", f.tffnp, oracle_out_dp(tc, "VAC1+28"), tol);
    (void) oracle_cmp(tc, "TFF/RTMU", f.rtmu, oracle_out_dp(tc, "VAC1+30"), 0);
    (void) oracle_cmp(tc, "NRMAG", f.nrmag, oracle_out_dp(tc, "VAC1+32"), tol);
    (void) oracle_cmp(tc, "-NR (X1)", -f.nr, oracle_out_sp(tc, "VAC1+38"), 0);
    (void) oracle_cmp(tc, "-NA (X2)", -f.na, oracle_out_sp(tc, "VAC1+39"), 0);
    oracle_cmp_vec(tc, "VONE'", f.vone_p, oracle_out_vec(tc, "VONE'"), tol);

    g = f;
    (void) agc_tff_rp_ra(&ip, &g);
    oracle_require_ok(tr, "POODOO");
    (void) oracle_cmp(tr, "RPER", g.rper, oracle_out_dp(tr, "VAC1+14"), tol);
    (void) oracle_cmp(tr, "RAPO", g.rapo, oracle_out_dp(tr, "VAC1+16"), tol);

    g = f;
    (void) agc_tff_calctff(&ip, &g, oracle_in_dp(tt, "MPAC", 0), &tffv);
    oracle_require_ok(tt, "POODOO");
    (void) oracle_cmp(tt, "TFF", tffv, oracle_out_dp(tt, "MPAC"), tol);
    (void) oracle_cmp(tt, "TFFDELQ", g.tffdelq, oracle_out_dp(tt, "VAC1+10"), tol);
    (void) oracle_cmp(tt, "TFFQ1", g.tffq1, oracle_out_dp(tt, "VAC1+14"), tol);
    (void) oracle_cmp(tt, "NRTERM", g.nrterm, oracle_out_dp(tt, "VAC1+16"), tol);
    (void) oracle_cmp(tt, "RTERM", g.rterm, oracle_out_dp(tt, "VAC1+18"), 0);

    /* TFFX / TFFTEM are only written on the Z-series paths; elsewhere the
     * AGC leaves the push list as it was (the UNIT debris TFFCONIC left
     * there) and C leaves 0: compare only when the AGC wrote them.       */
    const agc_dp_t x_out = oracle_out_dp(tt, "VAC1+34"); /* TFFX, 2^0     */
    const agc_dp_t m_out = oracle_out_dp(tt, "VAC1+36"); /* TFFTEM, scale */

    if (x_out != oracle_in_dp(tt, "VAC1", 34))
    {
        (void) oracle_cmp(tt, "TFFX", g.tffx, x_out, tol);
    }

    if (m_out != oracle_in_dp(tt, "VAC1", 36))
    {
        (void) oracle_cmp(tt, "TFFTEM", g.tfftem, m_out, tol);
    }
} /* tff */

/* ---- LSPOS / LUNVEL ---------------------------------------------------- */
/**********************************************************************
 * AGC: none (test helper) -- CM ephemeris uplink from the case
 *
 * FUNCTION NAME: eph_of
 *
 * ARGUMENTS:
 *   Argument   Type                   I/O  Description
 *   ---------  ---------------------  ---  ----------------------------
 *   t          const char *           I    case tag
 *
 * RETURNS: agc_ephem_csm_t -- TIMEMO, VECOEM, RESO, VESO, OMEGAES
 **********************************************************************/
static agc_ephem_csm_t eph_of(const char *t)
{
    agc_ephem_csm_t e; /* uplink, scales in the type */

    e.timemo = oracle_in_tp(t, "TIMEMO", 0);

    for (int k = 0; k < AGC_EPHEM_NCOEF; k++)
    {
        e.vecoem[k] = oracle_in_vec_at(t, "VECOEM", k);
    }

    e.reso    = oracle_in_vec(t, "RESO");
    e.veso    = oracle_in_vec(t, "VESO");
    e.omegaes = oracle_in_dp(t, "OMEGAES", 0);

    return (e);
}

