/**********************************************************************
 * AGC: none (test helper) -- pad load from the case inputs
 *
 * FUNCTION NAME: pad_of
 *
 * ARGUMENTS:
 *   Argument   Type                   I/O  Description
 *   ---------  ---------------------  ---  ----------------------------
 *   t          const char *           I    case tag
 *
 * RETURNS: agc_navaux_padload_t -- TEPHEM, AZO, AXO, -AYO, 504LM, RLS
 **********************************************************************/
static agc_navaux_padload_t pad_of(const char *t)
{
    agc_navaux_padload_t pad; /* pad load, scales in the type */

    pad.tephem  = oracle_in_tp(t, "TEPHEM", 0);
    pad.azo     = oracle_in_dp(t, "AZO", 0);
    pad.axo     = oracle_in_dp(t, "AXO", 0);
    pad.neg_ayo = oracle_in_dp(t, "-AYO", 0);
    pad.lm504   = oracle_in_vec(t, "E4,1411"); /* 504LM */
    pad.rls     = oracle_in_vec(t, "RLS");

    return (pad);
}

/**********************************************************************
 * AGC: none (test helper) -- LUNAFLAG and ERADFLAG from the case flags
 *
 * FUNCTION NAME: opt_of
 *
 * ARGUMENTS:
 *   Argument   Type                   I/O  Description
 *   ---------  ---------------------  ---  ----------------------------
 *   t          const char *           I    case tag
 *
 * RETURNS: agc_latlong_opt_t -- the options
 **********************************************************************/
static agc_latlong_opt_t opt_of(const char *t)
{
    agc_latlong_opt_t o; /* LUNAFLAG, ERADFLAG */

    o.erad  = (oracle_in(t, "FLAGWRD1", 0) & 010000) != 0; /* ERADFLAG */
    o.lunar = (oracle_in(t, "FLAGWRD3", 0) & 04000) != 0;  /* LUNAFLAG */

    return (o);
}

/* ---- LAT-LONG / LALOTORV --------------------------------------------- */
/**********************************************************************
 * AGC: none (oracle case) -- LAT-LONG
 *
 * FUNCTION NAME: latlong
 *
 * ARGUMENTS:
 *   Argument   Type                   I/O  Description
 *   ---------  ---------------------  ---  ----------------------------
 *   t          const char *           I    case tag
 *   tol        long int               I    tolerance, LSB
 *
 * RETURNS: void
 **********************************************************************/
static void latlong(const char *t, long int tol)
{
    agc_interp_t               ip;              /* interpreter state */
    agc_latlong_t              o;               /* LAT-LONG result   */
    const agc_navaux_padload_t pad = pad_of(t); /* case pad load     */

    agc_interp_init(&ip);
    agc_navaux_set_padload(&pad);
    (void) agc_latlong_from_r(&ip, &pad, opt_of(t), oracle_in_vec(t, "ALPHAV"), oracle_in_dp(t, "MPAC", 0), &o);
    oracle_require_ok(t, "POODOO");
    (void) oracle_cmp(t, "LAT", o.lat, oracle_out_dp(t, "LAT"), tol);
    (void) oracle_cmp(t, "LONG", o.lon, oracle_out_dp(t, "LONG"), tol);
    (void) oracle_cmp(t, "ALT", o.alt, oracle_out_dp(t, "ALT"), tol);
    (void) oracle_cmp(t, "ERADM", o.eradm, oracle_out_dp(t, "ERADM"), tol);
}

/**********************************************************************
 * AGC: none (oracle case) -- LALOTORV
 *
 * FUNCTION NAME: lalotorv
 *
 * ARGUMENTS:
 *   Argument   Type                   I/O  Description
 *   ---------  ---------------------  ---  ----------------------------
 *   t          const char *           I    case tag
 *   tol        long int               I    tolerance, LSB
 *
 * RETURNS: void
 **********************************************************************/
static void lalotorv(const char *t, long int tol)
{
    agc_interp_t               ip;                /* interpreter state */
    agc_latlong_t              in;                /* LAT, LONG, ALT    */
    agc_vec_t                  r;                 /* R, scale 2^29 m   */
    agc_dp_t                   eradm = 0;         /* ERADM, 2^29 m     */
    const agc_navaux_padload_t pad   = pad_of(t); /* case pad load     */

    agc_interp_init(&ip);
    agc_navaux_set_padload(&pad);
    in.lat   = oracle_in_dp(t, "LAT", 0);
    in.lon   = oracle_in_dp(t, "LONG", 0);
    in.alt   = oracle_in_dp(t, "ALT", 0);
    in.eradm = 0;
    (void) agc_latlong_to_r(&ip, &pad, opt_of(t), &in, oracle_in_dp(t, "MPAC", 0), &r, &eradm);
    oracle_require_ok(t, "POODOO");
    oracle_cmp_vec(t, "ALPHAV", r, oracle_out_vec(t, "ALPHAV"), tol);
    (void) oracle_cmp(t, "ERADM", eradm, oracle_out_dp(t, "ERADM"), tol);
}

/* ---- RP-TO-R / R-TO-RP ------------------------------------------------ */
/**********************************************************************
 * AGC: none (oracle case) -- RP-TO-R or R-TO-RP
 *
 * FUNCTION NAME: rp_r
 *
 * ARGUMENTS:
 *   Argument   Type                   I/O  Description
 *   ---------  ---------------------  ---  ----------------------------
 *   t          const char *           I    case tag
 *   to_r       bool                   I    true: RP-TO-R, false: R-TO-RP
 *   tol        long int               I    tolerance, LSB
 *
 * RETURNS: void
 **********************************************************************/
static void rp_r(const char *t, bool to_r, long int tol)
{
    agc_interp_t               ip;               /* interpreter state */
    agc_vec_t                  out;              /* scale of in       */
    const agc_navaux_padload_t pad  = pad_of(t); /* case pad load     */
    bool                       moon = false;     /* MPAC != 0: moon   */
    agc_vec_t                  in;               /* R or RP, 2^29 m   */
    agc_dp_t                   tt   = 0;         /* T, scale 2^28 cs  */

    moon = (oracle_in(t, "MPAC", 0) != 0);
    in   = oracle_in_vec(t, "VAC1");
    tt   = oracle_in_dp(t, "VAC1+6", 0);

    agc_interp_init(&ip);
    agc_navaux_set_padload(&pad);

    if (to_r)
    {
        (void) agc_planet_rp_to_r(&ip, &pad, moon, in, tt, &out);
    }
    else
    {
        (void) agc_planet_r_to_rp(&ip, &pad, moon, in, tt, &out);
    }

    oracle_require_ok(t, "POODOO");
    oracle_cmp_vec(t, "MPAC", out, oracle_out_mpac_vec(t), tol);
}

