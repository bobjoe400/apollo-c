/**********************************************************************
 * FILE NAME: dap_lm.c
 *
 * PURPOSE:
 *   LM digital autopilot against the real AGC code (yaAGC oracle).
 *
 * AGC SOURCE:
 *   Luminary099 rope via yaAGC: AOSTASK_AND_AOSJOB, TJET_LAW,
 *     KALMAN_FILTER, TRIM_GIMBAL_CONTROL_SYSTEM, T4RUPT GPMATRIX
 *
 * EXTERNAL VARIABLES:  (AGC erasables)
 *   Name          Type      I/O  Scale          Description
 *   ------------  --------  ---  -------------  ----------------------
 *   DAP block     lm_dap_t  I/O  per field      EBANK 6 DAP erasables (lm_dap_state())
 *   CDUX          uint16_t  I    2^0 rev        CDU X angle (agc_erase_cdux())
 *   CDUZ          uint16_t  I    2^0 rev        CDU Z angle (agc_erase_cduz())
 *   COSMG         agc_sp_t  I    2^0            cos MG (agc_erase_cosmg())
 *   CSMMASS       agc_sp_t  I    B16 kg         CSM mass (agc_erase_csmmass())
 *   LEMMASS       agc_sp_t  I/O  B16 kg         LM mass (agc_erase_lemmass())
 *   M11           agc_sp_t  I    2^0            gimbal matrix (agc_erase_m11())
 *   M21           agc_sp_t  I    2^0            gimbal matrix (agc_erase_m21())
 *   M22           agc_sp_t  I    2^0            gimbal matrix (agc_erase_m22())
 *   M31           agc_sp_t  I    2^0            gimbal matrix (agc_erase_m31())
 *   M32           agc_sp_t  I    2^0            gimbal matrix (agc_erase_m32())
 *
 * EXTERNAL REFERENCES:
 *   Name                        Description
 *   --------------------------  ------------------------------------
 *   agc_exec_init               executive reset
 *   agc_flagword_set            store a whole flagword (flags.h)
 *   agc_guid_init               guidance state reset
 *   agc_guid_state              guidance erasables (MASS, ABDELV ...)
 *   agc_lm_dap_fresh_start      DAP part of fresh start (state.c)
 *   agc_lm_dap_jet_accel_update  1/ACCS job (accs.c)
 *   agc_lm_dap_timegmbl         TIMEGMBL: trim-gimbal null drive (gts.c)
 *   agc_state_init              power-on erasable state
 *   agc_t4_gimbal_matrix        T4RUPT gimbal-angle matrix M11..M32
 *   agc_waitlist_init           waitlist reset
 *   lm_dap_backp                BACKP rate derivation (rate.c)
 *   lm_dap_gts                  GTS .. CLOSEOUT (gts.c)
 *   lm_dap_offset_est           offset estimator (rate.c)
 *   lm_dap_rateloop             RATELOOP + ROTORQUE (rate.c)
 *   lm_dap_state                DAP erasables (state.c)
 *   lm_dap_tjetlaw              TJETLAW (tjetlaw.c)
 *
 * ABNORMAL TERMINATION CONDITIONS, ALARMS:
 *   Exit status 1 when a check fails or a case is missing.
 *
 * NOTES:
 *   Inputs and expected words: tools/oracle/cases/dap_lm.spec / .txt
 *   (Luminary099), generated by tools/oracle/cases/gen/gen_dap_lm.py.
 *   1/ACCS + 1/ACCONT (jet accelerations, coupling coefficients, gimbal
 *   jerks, the 48-word TJETLAW parameter block), TJETLAW for P, U and V with
 *   positive and negative errors, rate-limited and RUFLAW cases, GPMATRIX
 *   (the T4RUPT DAP matrix) and one pass of the KALMAN_FILTER rate/offset
 *   estimator (RATELOOP, ROTORQUE, BACKP, offset estimator).
 *
 *   Tolerances (LSB of the AGC word): see docs/modules/oracle-cases.md.
 **********************************************************************/
