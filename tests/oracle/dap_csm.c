    pitch("pitch_lm");
    pitch("pitch_big");
    roll("roll_coast");
    roll("roll_start");
    roll("roll_neg");
    roll("roll_firing");
    roll("roll_wait");
    roll("roll_ratelim");
    roll("roll_wrap");
    roll("roll_wrap_neg");
    rate("rate_quiet");
    rate("rate_moving");
    rate("rate_kalman");
    rate("rate_disagree");
    rate("rate_big");
    needles("needles_small");
    needles("needles_edge");
    needles("needles_limit");
    needles("needles_track");
    phase_plane("pp_hold");
    phase_plane("pp_coast");
    phase_plane("pp_auto");
    phase_plane("pp_disagree");
    phase_plane("pp_disagree2");
    phase_plane("pp_forced");
