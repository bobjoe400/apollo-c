/**********************************************************************
 * FILE NAME: dap_csm.c
 *
 * PURPOSE:
 *   The CSM digital autopilot against the real AGC code (yaAGC oracle):
 *   jet selection (JETSLECT through CALCDT6: the PYTABLE/RTABLE/YZTABLE
 *   look-up, quad failures, on-time limits and the sorted T6 intervals),
 *   one TVC pitch sample (PITCHDAP: CDU rates, body rate, error integral,
 *   the three-cascade filter with VARK, offset tracker, copycycle) and
 *   ROLLDAP (the TVC roll phase-plane logic).
 *
 * AGC SOURCE:
 *   Comanche055 JET_SELECTION_LOGIC.agc pp. 1039-1062, TVCDAPS.agc
 *   pp. 961-978, TVCROLLDAP.agc pp. 984-998 (run in yaAGC; cases in
 *   tools/oracle/cases/dap_csm.spec / .txt, generated by
 *   tools/oracle/cases/gen/gen_dap_csm.py)
 *
 * EXTERNAL VARIABLES:
 *   none (the DAP blocks are reached through agc_csm_dap_rcs() /
 *   _tvc() / _com() and zeroed before each case)
 *
 * EXTERNAL REFERENCES:
 *   Name                  Description
 *   --------------------  ------------------------------------------
 *   oracle_*              case reader and comparisons (oracle_txt.h)
 *   agc_csm_jet_select    JETSLECT .. CALCDT6 as a pure function
 *   agc_task_pitchdap     PITCHDAP T5 task
 *   agc_task_rolldap      ROLLDAP waitlist task
 *
 * ABNORMAL TERMINATION CONDITIONS, ALARMS:
 *   exit status 1 when a comparison fails (oracle_finish)
 *
 * ASSUMPTIONS, CONSTRAINTS, RESTRICTIONS:
 *   Every comparison is bit-exact, word by word for the DP filter
 *   quantities (the DAP keeps the AGC's sign-disagreeing word pairs,
 *   oracle finding F9). Tolerances: docs/modules/oracle-cases.md.
 **********************************************************************/
