/**********************************************************************
 * FILE NAME: dap_csm.c
 *
 * PURPOSE:
 *   The CSM digital autopilot against the real AGC code (yaAGC oracle):
 *   jet selection (JETSLECT through CALCDT6: the PYTABLE/RTABLE/YZTABLE
 *   look-up, quad failures, on-time limits and the sorted T6 intervals),
 *   one TVC pitch sample (PITCHDAP: CDU rates, body rate, error integral,
 *   the three-cascade filter with VARK, offset tracker, copycycle) and
 *   ROLLDAP (the TVC roll phase-plane logic).
 *
 * AGC SOURCE:
 *   Comanche055 JET_SELECTION_LOGIC.agc pp. 1039-1062, TVCDAPS.agc
 *   pp. 961-978, TVCROLLDAP.agc pp. 984-998 (run in yaAGC; cases in
 *   tools/oracle/cases/dap_csm.spec / .txt, generated by
 *   tools/oracle/cases/gen/gen_dap_csm.py)
 *
 * EXTERNAL VARIABLES:
 *   none (the DAP blocks are reached through agc_csm_dap_rcs() /
 *   _tvc() / _com() and zeroed before each case)
 *
 * EXTERNAL REFERENCES:
 *   Name                  Description
 *   --------------------  ------------------------------------------
 *   oracle_*              case reader and comparisons (oracle_txt.h)
 *   agc_csm_jet_select    JETSLECT .. CALCDT6 as a pure function
 *   agc_task_pitchdap     PITCHDAP T5 task
 *   agc_task_rolldap      ROLLDAP waitlist task
 *
 * ABNORMAL TERMINATION CONDITIONS, ALARMS:
 *   exit status 1 when a comparison fails (oracle_finish)
 *
 * ASSUMPTIONS, CONSTRAINTS, RESTRICTIONS:
 *   Every comparison is bit-exact, word by word for the DP filter
 *   quantities (the DAP keeps the AGC's sign-disagreeing word pairs,
 *   oracle finding F9). Tolerances: docs/modules/oracle-cases.md.
 **********************************************************************/
#include <stdio.h>

#include <string.h>

#include "../../src/csm/dap/internal.h"
#include "agc/core/assert.h"
#include "agc/core/interp.h"
#include "agc/core/state.h"
#include "agc/csm/dap.h"
#include "agc/exec/exec.h"
#include "agc/guidance/guidance.h"
#include "oracle_txt.h"

static void              cmp_raw(const char *t, const char *what, unsigned int got, const char *n);
static void              cmp_sp(const char *t, const char *what, long int got, const char *n);
static void              cmp_pair(const char *t, const char *n, agc_csm_dp_pair_t got);
static agc_csm_dp_pair_t pair_in(const char *t, const char *n, int idx);
static void              fresh(void);
static void              jets(const char *t);
static void              pitch(const char *t);
static void              roll(const char *t);

/**********************************************************************
 * AGC: none -- run every case; the exit status reports failures.
 *
 * ARGUMENTS: none
 *
 * RETURNS: int -- 0 when every comparison passes (or the case files are
 *          missing), 1 otherwise
 **********************************************************************/
int main(void)
{
    if (!oracle_load("dap_csm"))
    {
        (void) printf("oracle_dap_csm: SKIP (case files not found)\n");

        return (0);
    }

    fresh();
    jets("jets_pitch");
    jets("jets_all");
    jets("jets_long");
    jets("jets_fail_a");
    jets("jets_fail_cd");
    jets("jets_short");
    pitch("pitch_quiet");
    pitch("pitch_rate");
    pitch("pitch_lm");
    pitch("pitch_big");
    roll("roll_coast");
    roll("roll_start");
    roll("roll_neg");
    roll("roll_firing");
    roll("roll_wait");
    roll("roll_ratelim");
    roll("roll_wrap");
    roll("roll_wrap_neg");

    return (oracle_finish("oracle_dap_csm"));
}

/**********************************************************************
 * AGC: none -- assertion hook of the library: print and continue.
 *
 * ARGUMENTS:
 *   file  const char *  I  source file of the failed assertion
 *   line  int           I  its line
 *   expr  const char *  I  the asserted expression
 *
 * RETURNS: bool -- false (the assertion stays failed)
 **********************************************************************/
bool agc_assert_report(const char *file, int line, const char *expr)
{
    (void) printf("assert %s:%d %s\n", file, line, expr);

    return (false);
}

/**********************************************************************
 * AGC: none -- compare a raw 15-bit word (channel images, CDU words).
 *
 * ARGUMENTS:
 *   t     const char *  I  case tag
 *   what  const char *  I  label printed on a mismatch
 *   got   unsigned int  I  C word
 *   n     const char *  I  AGC output name
 **********************************************************************/
static void cmp_raw(const char *t, const char *what, unsigned int got, const char *n)
{
    (void) oracle_cmp(t, what, (long int) got, (long int) oracle_out_raw(t, n), 0);
}

/**********************************************************************
 * AGC: none -- compare a signed SP word exactly.
 *
 * ARGUMENTS:
 *   t     const char *  I  case tag
 *   what  const char *  I  label printed on a mismatch
 *   got   long int      I  C value (unscaled word)
 *   n     const char *  I  AGC output name
 **********************************************************************/
static void cmp_sp(const char *t, const char *what, long int got, const char *n)
{
    (void) oracle_cmp(t, what, got, oracle_out_sp(t, n), 0);
}

/**********************************************************************
 * AGC: none -- compare both words of a DP pair as the AGC stores them
 * (NAME and NAME+1).
 *
 * ARGUMENTS:
 *   t    const char *       I  case tag
 *   n    const char *       I  AGC output name of the upper word
 *   got  agc_csm_dp_pair_t  I  C pair
 **********************************************************************/
static void cmp_pair(const char *t, const char *n, agc_csm_dp_pair_t got)
{
    char lo[96]; /* NAME+1 or NAME+(k+1)                               */

    oracle_next_name(n, lo, sizeof (lo));
    cmp_sp(t, n, (long int) got.hi, n);
    cmp_sp(t, lo, (long int) got.lo, lo);
}

/**********************************************************************
 * AGC: none -- a DP input pair, words as given in the case.
 *
 * ARGUMENTS:
 *   t    const char *  I  case tag
 *   n    const char *  I  input name
 *   idx  int           I  index of the upper word in the input list
 *
 * RETURNS: agc_csm_dp_pair_t -- the two words (scale of the quantity)
 **********************************************************************/
static agc_csm_dp_pair_t pair_in(const char *t, const char *n, int idx)
{
    agc_csm_dp_pair_t p; /* upper, lower word                           */

    p.hi = (agc_sp_t) oracle_in(t, n, idx);
    p.lo = (agc_sp_t) oracle_in(t, n, idx + 1);

    return (p);
}

/**********************************************************************
 * AGC: none -- fresh state for a case. Each AGC run starts from zeroed
 * erasable, so the DAP blocks are zeroed too (no leftovers such as
 * DELOGA from the previous case).
 *
 * ARGUMENTS: none
 **********************************************************************/
static void fresh(void)
{
    agc_state_init(AGC_VEHICLE_CSM);
    (void) agc_exec_init();
    (void) agc_waitlist_init();
    (void) agc_guid_init(AGC_VEHICLE_CSM);
    (void) memset(agc_csm_dap_tvc(), 0, sizeof (agc_csm_tvc_t));
    (void) memset(agc_csm_dap_rcs(), 0, sizeof (agc_csm_rcs_t));
    (void) memset(agc_csm_dap_com(), 0, sizeof (agc_csm_dapcom_t));
}

/**********************************************************************
 * JETSLECT 17,2552 -> ENDJETS (JET_SELECTION_LOGIC.agc pp. 1039-1060):
 * one jet selection with the case's TAUs and quad failures.
 *
 * ARGUMENTS:
 *   t  const char *  I  case tag
 **********************************************************************/
static void jets(const char *t)
{
    agc_csm_jet_in_t  in; /* TAUs (1/1600 s), failures, THC    */
    agc_csm_jet_out_t o;  /* jet words, BLASTs, DFTs           */

    static const char *const bl[3] = {"BLAST", "BLAST1", "BLAST2"};

    in.chan31 = 077777; /* yaAGC power-up: no THC command               */
    in.lem_on = (oracle_in_raw(t, "DAPDATR1", 0) & 020000u) != 0u;

    for (int k = 0; k < 3; k++)
    {
        in.tau[k] = (agc_sp_t) oracle_in(t, "TAU", k);
    }

    in.racfail = (agc_sp_t) oracle_in(t, "RACFAIL", 0);
    in.rbdfail = (agc_sp_t) oracle_in(t, "RACFAIL", 1);
    in.acorbd  = (agc_sp_t) oracle_in(t, "RACFAIL", 2);
    in.xtrans  = (agc_sp_t) oracle_in(t, "RACFAIL", 3);
    (void) agc_csm_jet_select(&in, &o);
    oracle_require_ok(t, "ENDJETS");
    cmp_raw(t, "RWORD1", o.rword1, "RWORD1");
    cmp_raw(t, "RWORD2", o.rword2, "RWORD2");
    cmp_raw(t, "PWORD1", o.pword1, "PWORD1");
    cmp_raw(t, "PWORD2", o.pword2, "PWORD2");
    cmp_raw(t, "YWORD1", o.yword1, "YWORD1");
    cmp_raw(t, "YWORD2", o.yword2, "YWORD2");

    for (int k = 0; k < 3; k++)
    {
        char lo[16]; /* BLASTn +1: branch index                          */
        char d[8];   /* DFTn / TAUn                                      */

        (void) snprintf(lo, sizeof (lo), "%s+1", bl[k]);
        cmp_sp(t, bl[k], o.blast[k].time, bl[k]);
        cmp_sp(t, lo, (long int) o.blast[k].axis, lo);
        (void) snprintf(d, sizeof (d), (k == 0) ? "DFT" : "DFT%d", k); /* ?: */
        cmp_sp(t, d, o.dft[k], d);
        (void) snprintf(d, sizeof (d), (k == 0) ? "TAU" : "TAU%d", k); /* ?: */
        cmp_sp(t, d, o.tau[k], d);
    }

    if (o.attkalmn_xln != 0x7FFF)
    {
        cmp_sp(t, "ATTKALMN", o.attkalmn_xln, "ATTKALMN");
    }
}

/**********************************************************************
 * PITCHDAP 20,2530 -> RESUME (TVCDAPS.agc pp. 963-966): one pitch DAP
 * sample; every DP output compared word by word.
 *
 * ARGUMENTS:
 *   t  const char *  I  case tag
 **********************************************************************/
static void pitch(const char *t)
{
    agc_csm_tvc_t *v = agc_csm_dap_tvc(); /* TVC DAP erasables          */
    agc_cdutrig_t *g;                     /* QUICTRIG trig, scale 2^1   */

    fresh();
    g                     = &agc_guid_state()->trig;
    agc_erase_set_cduy(oracle_in_raw(t, "CDUY", 0));
    agc_erase_set_cduz(oracle_in_raw(t, "CDUY", 1));
    v->pcduypst           = oracle_in_raw(t, "PCDUYPST", 0);
    v->pcduzpst           = oracle_in_raw(t, "PCDUYPST", 1);
    v->perrb              = pair_in(t, "PERRB", 0);
    v->omegac[1]          = oracle_in_dp(t, "OMEGAYC", 0);
    g->sincdu[AGC_TRIG_X] = agc_dp_from_sp((agc_sp_t) oracle_in(t, "SINCDUX", 0));
    g->coscdu[AGC_TRIG_X] = agc_dp_from_sp((agc_sp_t) oracle_in(t, "COSCDUX", 0));
    g->coscdu[AGC_TRIG_Z] = agc_dp_from_sp((agc_sp_t) oracle_in(t, "COSCDUZ", 0));

    for (int k = 0; k < 6; k++)
    {
        v->ptmp[k] = pair_in(t, "PTMP1", 2 * k);
    }

    for (int k = 0; k < AGC_CSM_N10_WORDS; k++)
    {
        v->n10[k] = (agc_sp_t) oracle_in(t, "N10", k);
    }

    v->vark     = (agc_sp_t) oracle_in(t, "VARK", 0);
    v->pdeloff  = pair_in(t, "PDELOFF", 0);
    v->pcmd     = (agc_sp_t) oracle_in(t, "PCMD", 0);
    v->delpbar  = pair_in(t, "DELPBAR", 0);
    v->stroker  = 0;
    v->t5tvcdt  = (agc_sp_t) oracle_in(t, "T5TVCDT", 0);
    v->tvcphase = 0;
    agc_erase_set_tvcpitch((agc_sp_t) oracle_in(t, "TVCPITCH", 0));
    agc_erase_set_dapdatr1(oracle_in_raw(t, "DAPDATR1", 0));
    (void) agc_task_pitchdap();
    oracle_require_ok(t, "RESUME");
    cmp_sp(t, "MCDUYDOT", v->mcduydot, "MCDUYDOT");
    cmp_sp(t, "MCDUZDOT", v->mcduzdot, "MCDUZDOT");
    cmp_pair(t, "OMEGAYB", v->omegab[1]);
    cmp_pair(t, "PERRB", v->perrb);

    for (int k = 0; k < 6; k++)
    {
        char n[16]; /* PTMP1, PTMP1+2 .. PTMP1+10                       */

        (void) snprintf(n, sizeof (n), (k == 0) ? "PTMP1" : "PTMP1+%d", 2 * k); /* ?: */
        cmp_pair(t, n, v->ptmp[k]);
    }

    cmp_sp(t, "PCMD", v->pcmd, "PCMD");
    cmp_pair(t, "DELPBAR", v->delpbar);
    cmp_sp(t, "TVCPITCH", agc_erase_tvcpitch(), "TVCPITCH");
    cmp_sp(t, "AK1", agc_csm_dap_com()->ak[1], "AK1");
    cmp_sp(t, "TVCPHASE", v->tvcphase, "TVCPHASE");
    cmp_raw(t, "PCDUYPST", v->pcduypst, "PCDUYPST");
    cmp_raw(t, "PCDUZPST", v->pcduzpst, "PCDUZPST");
}

/**********************************************************************
 * ROLLDAP 16,3272 -> TASKOVER (TVCROLLDAP.agc pp. 989-997): one roll
 * DAP pass.
 *
 * ARGUMENTS:
 *   t  const char *  I  case tag
 **********************************************************************/
static void roll(const char *t)
{
    agc_csm_tvc_t *v = agc_csm_dap_tvc(); /* TVC DAP erasables          */

    fresh();
    v->oganow     = oracle_in_raw(t, "OGANOW", 0);
    v->ogapast    = oracle_in_raw(t, "OGANOW", 1);
    v->rollfire   = (agc_sp_t) oracle_in(t, "ROLLFIRE", 0);
    v->rollword   = oracle_in_raw(t, "ROLLFIRE", 1);
    v->temreg     = (agc_sp_t) oracle_in(t, "ROLLFIRE", 2);
    v->one_conacc = (agc_sp_t) oracle_in(t, "E6,1640", 0);
    v->ogaerr     = (agc_sp_t) oracle_in(t, "OGA", 0);
    agc_rupt_set_time(CSM_DAP_TIME6, oracle_in_raw(t, "TIME6", 0));
    (void) agc_task_rolldap();
    oracle_require_ok(t, "TASKOVER");
    cmp_sp(t, "OGARATE", v->ogarate, "OGARATE");
    cmp_sp(t, "TEMREG", v->temreg, "TEMREG");
    cmp_sp(t, "ROLLFIRE", v->rollfire, "ROLLFIRE");
    cmp_raw(t, "ROLLWORD", v->rollword, "ROLLWORD");
    cmp_sp(t, "DELOGA", v->deloga, "DELOGA");
    cmp_sp(t, "DELOGART", v->delogart, "DELOGART");
    cmp_sp(t, "SGNRT", v->sgnrt, "SGNRT");
    cmp_sp(t, "IOGARATE", v->iogarate, "IOGARATE");
    cmp_raw(t, "TIME6", agc_rupt_time(CSM_DAP_TIME6), "TIME6");
}
