static int       goto_word(agc_entry_goto_t g);
static void      avg_in(const char *t);
static void      cmp_flag(const char *t, const char *n, agc_flag_id_t f, const char *word, unsigned int bit);
static void      compare(const char *t, long int tol);
static void      pass(const char *t, long int tol);
static agc_mat_t mat_in(const char *t, const char *name);
static agc_sp_t  cdu2s(uint16_t w);
static void      cm_pose(const char *t, long int tol);

/**********************************************************************
 * AGC: none -- run every case; the exit status reports failures.
 *
 * FUNCTION NAME: main
 *
 * ARGUMENTS: none
 *
 * RETURNS: int -- int -- 0 when every comparison passes (or the case files
 *          are missing), 1 otherwise
 **********************************************************************/
int main(void)
{
    agc_navaux_padload_t pad = {0};
    const char          *t   = "entry_startent"; /* case name */

    if (!oracle_load("entry"))
    {
        (void) printf("oracle_entry: SKIP (case files not found)\n");

        return (0);
    }

    agc_state_init(AGC_VEHICLE_CSM);
    (void) agc_exec_init();
    (void) agc_waitlist_init();
    (void) agc_guid_init(AGC_VEHICLE_CSM);
    (void) agc_navaux_set_padload(&pad);
    agc_entry_lexicon_reset();
    agc_entry_state_t *e = agc_entry_state(); /* entry erasables */

    e->ladpad                   = (agc_sp_t) oracle_in(t, "LADPAD", 0);
    e->lodpad                   = (agc_sp_t) oracle_in(t, "LODPAD", 0);
    e->headsup                  = (agc_sp_t) oracle_in(t, "HEADSUP", 0);
    e->lat_spl                  = oracle_in_dp(t, "LAT(SPL)", 0);
    e->lng_spl                  = oracle_in_dp(t, "LNG(SPL)", 0);
    agc_guid_state()->avg.unitw = oracle_in_vec(t, "UNITW");
    avg_in(t);
    (void) agc_entry_startent();
    oracle_require_ok(t, "SERVNOUT");
    compare(t, 4);
    pass("entry_pass_initroll", 4);
    pass("entry_pass_initroll2", 4);
    pass("entry_pass_huntest", 4);
    pass("entry_pass_next", 4);
    pass("entry_pass_upcontrl", 4);
    pass("entry_pass_upcontrl2", 4);
    pass("entry_pass_kep2", 4);
    pass("entry_pass_predict3", 4);
    pass("entry_pass_predict3b", 4);
    cm_pose("cm_pose_a", 8);
    cm_pose("cm_pose_b", 8);
    cm_pose("cm_pose_slow", 8);

    return (oracle_finish("oracle_entry"));
} /* main */

/**********************************************************************
 * AGC: none -- assertion hook of the library: print and continue.
 *
 * FUNCTION NAME: agc_assert_report
 *
 * ARGUMENTS:
 *   Argument  Type          I/O  Description (scale)
 *   --------  ------------  ---  ----------------------------------------
 *   file      const char *  I    source file of the failed assertion
 *   line      int           I    its line
 *   expr      const char *  I    the asserted expression
 *
 * RETURNS: bool -- bool -- false (the assertion stays failed)
 **********************************************************************/
bool agc_assert_report(const char *file, int line, const char *expr)
{
    (void) printf("assert %s:%d %s\n", file, line, expr);

    return (false);
}

/* GOTOADDR words (interpretive addresses, bank 25/26) by C phase.        */
static const struct
{
    agc_entry_goto_t g;    /* C phase                 */
    int              word; /* AGC GOTOADDR word       */
} GOTOS[] = { {AGC_ENTRY_GOTO_INITROLL, 052260}, {AGC_ENTRY_GOTO_HUNTEST, 052373}, {AGC_ENTRY_GOTO_UPCONTRL, 053035}, {AGC_ENTRY_GOTO_KEPLER, 053317}, {AGC_ENTRY_GOTO_PREFINAL, 053333}, {AGC_ENTRY_GOTO_FINAL_PREDICT, 053343}, };

/**********************************************************************
 * AGC: none -- the GOTOADDR word (interpretive address) of a C phase.
 *
 * FUNCTION NAME: goto_word
 *
 * ARGUMENTS:
 *   Argument  Type              I/O  Description (scale)
 *   --------  ----------------  ---  ------------------------------------
 *   g         agc_entry_goto_t  I    the C phase
 *
 * RETURNS: int -- int -- the AGC GOTOADDR word, -1 when the phase has none
 **********************************************************************/
static int goto_word(agc_entry_goto_t g)
{
    for (size_t i = 0; i < sizeof (GOTOS) / sizeof (GOTOS[0]); i++)
    {
        if (GOTOS[i].g == g)
        {
            return (GOTOS[i].word);
        }
    }

    return (-1);
}

/**********************************************************************
 * AGC: none -- load a pass's average-G data (RN VN PIPTIME UNITR DELV
 * DELVREF) from the case.
 *
 * FUNCTION NAME: avg_in
 *
 * ARGUMENTS:
 *   Argument  Type          I/O  Description (scale)
 *   --------  ------------  ---  ----------------------------------------
 *   t         const char *  I    case name
 *
 * RETURNS: none
 **********************************************************************/
static void avg_in(const char *t)
{
    agc_state_vector_t sv; /* state vector RN VN PIPTIME (m B29, m/cs B7) */

    sv.r                          = oracle_in_vec(t, "RN");
    sv.v                          = oracle_in_vec(t, "VN");
    sv.t                          = oracle_in_dp(t, "PIPTIME", 0);
    sv.moon                       = false;
    (void) agc_sv_set(AGC_SV_THIS, &sv);
    agc_guid_state()->avg.unitr   = oracle_in_vec(t, "UNITR");
    agc_guid_state()->avg.delvref = oracle_in_vec(t, "DELVREF");
    agc_erase_set_delv(oracle_in_vec(t, "DELV"));
}

/**********************************************************************
 * AGC: none -- compare one flag with a bit of an AGC flag word.
 *
 * FUNCTION NAME: cmp_flag
 *
 * ARGUMENTS:
 *   Argument  Type           I/O  Description (scale)
 *   --------  -------------  ---  ---------------------------------------
 *   t         const char *   I    case name
 *   n         const char *   I    flag name for the report
 *   f         agc_flag_id_t  I    the C flag
 *   word      const char *   I    the AGC flag word name
 *   bit       unsigned       I    the bit within word
 *
 * RETURNS: none
 **********************************************************************/
static void cmp_flag(const char *t, const char *n, agc_flag_id_t f, const char *word, unsigned int bit)
{
    (void) oracle_cmp(t, n, agc_flag_test(f), (oracle_out_raw(t, word) & bit) != 0, 0);
}

/**********************************************************************
 * AGC: none (ENTRY_LEXICON.agc erasables) -- compare the entry erasables
 * after a pass with the AGC words; tolerances in the comment above.
 *
 * FUNCTION NAME: compare
 *
 * ARGUMENTS:
 *   Argument  Type          I/O  Description (scale)
 *   --------  ------------  ---  ----------------------------------------
 *   t         const char *  I    case name
 *   tol       long int      I    general tolerance, LSB of the AGC word
 *
 * RETURNS: none
 **********************************************************************/
static void compare(const char *t, long int tol)
{
    const agc_entry_state_t *e = agc_entry_state(); /* entry erasables */

    (void) oracle_cmp(t, "D", e->d, oracle_out_dp(t, "D"), 256);
    (void) oracle_cmp(t, "V", e->v, oracle_out_dp(t, "V"), tol);
    (void) oracle_cmp(t, "VSQUARE", e->vsquare, oracle_out_dp(t, "VSQUARE"), tol);

    /* PREDICT3 writes its table look-up over LEQ (= FX +1) and GAMMAL
     * (= GAMMAEI = PREDANG): compare those instead in the final phase.  */
    const bool final = (oracle_out_raw(t, "GOTOADDR") == 053343); /* PREDICT3 table look-up pass */

    if (final)
    {
        static const char *const fx[6] = {"FX", "FX+1", "FX+2", "FX+3", "FX+4", "FX+5"};

        for (int k = 0; k < 6; k++)
        {
            (void) oracle_cmp(t, fx[k], e->fx[k], oracle_out_sp(t, fx[k]), 1);
        }

        /* BACK2 leaves JJ = table index + 6 x 13 (ADS JJ per column). */
        (void) oracle_cmp(t, "JJ", e->jj + 78, oracle_out_sp(t, "JJ"), 0);
        (void) oracle_cmp(t, "GRAD", e->grad, oracle_out_sp(t, "GRAD"), 1);
        (void) oracle_cmp(t, "PREDANG", e->predang, oracle_out_sp(t, "PREDANG"), 1);
    }
    else
    {
        (void) oracle_cmp(t, "LEQ", e->leq, oracle_out_dp(t, "LEQ"), tol);
        (void) oracle_cmp(t, "GAMMAL", e->gammal, oracle_out_dp(t, "GAMMAL"), tol);
    }

    (void) oracle_cmp(t, "RDOT", e->rdot, oracle_out_dp(t, "RDOT"), tol);
    (void) oracle_cmp(t, "THETAH", e->thetah, oracle_out_dp(t, "THETAH"), 8);
    (void) oracle_cmp(t, "LATANG", e->latang, oracle_out_dp(t, "LATANG"), tol);
    (void) oracle_cmp(t, "ROLLC", e->rollc, oracle_out_dp(t, "ROLLC"), 16);
    (void) oracle_cmp(t, "L/D", e->l_d, oracle_out_dp(t, "L/D"), 320);
    (void) oracle_cmp(t, "L/D1", e->l_d1, oracle_out_dp(t, "L/D1"), 320);
    (void) oracle_cmp(t, "K2ROLL", e->k2roll, oracle_out_dp(t, "K2ROLL"), 0);
    (void) oracle_cmp(t, "GOTOADDR", goto_word(e->gotoaddr), (long int) oracle_out_raw(t, "GOTOADDR"), 0);
    (void) oracle_cmp(t, "A1", e->a1, oracle_out_dp(t, "A1"), tol);
    (void) oracle_cmp(t, "VL", e->vl, oracle_out_dp(t, "VL"), 64);
    (void) oracle_cmp(t, "LEWD", e->lewd, oracle_out_dp(t, "LEWD"), tol);
    (void) oracle_cmp(t, "DIFF", e->diff, oracle_out_dp(t, "DIFF"), tol);
    (void) oracle_cmp(t, "Q7", e->q7, oracle_out_dp(t, "Q7"), tol);
    (void) oracle_cmp(t, "DTEAROT", e->dtearot, oracle_out_dp(t, "DTEAROT"), tol);
    (void) oracle_cmp(t, "L/DCALC", e->l_dcalc, oracle_out_dp(t, "L/DCALC"), tol);
    (void) oracle_cmp(t, "Q2", e->q2, oracle_out_dp(t, "Q2"), tol);
    (void) oracle_cmp(t, "KLAT", e->klat, oracle_out_dp(t, "KLAT"), tol);
    (void) oracle_cmp(t, "LAD", e->lad, oracle_out_dp(t, "LAD"), 0);
    (void) oracle_cmp(t, "LOD", e->lod, oracle_out_dp(t, "LOD"), 0);
    oracle_cmp_vec(t, "UNI", e->uni, oracle_out_vec(t, "UNI"), tol);
    oracle_cmp_vec(t, "RT", e->rt, oracle_out_vec(t, "RT"), 8);
    oracle_cmp_vec(t, "RTINIT", e->rtinit, oracle_out_vec(t, "RTINIT"), tol);
    cmp_flag(t, ".05GSW", AGC_FLAG__05GSW, "CM/FLAGS", 04);
    cmp_flag(t, "INRLSW", AGC_FLAG_INRLSW, "CM/FLAGS", 020);
    cmp_flag(t, "HIND", AGC_FLAG_HIND, "CM/FLAGS", 040);
    cmp_flag(t, "NOSWITCH", AGC_FLAG_NOSWITCH, "CM/FLAGS", 0100);
    cmp_flag(t, "EGSW", AGC_FLAG_EGSW, "CM/FLAGS", 0200);
    cmp_flag(t, "RELVELSW", AGC_FLAG_RELVELSW, "CM/FLAGS", 0400);
    cmp_flag(t, "GONEPAST", AGC_FLAG_GONEPAST, "CM/FLAGS", 01000);
    cmp_flag(t, "GONEBY", AGC_FLAG_GONEBY, "FLAGWRD7", 0200);
} /* compare */

/**********************************************************************
 * AGC: none (SCALEPOP, REENTRY_CONTROL.agc p. 847) -- one guidance pass:
 * average-G data, the forced GOTOADDR if any, SCALEPOP, compare.
 *
 * FUNCTION NAME: pass
 *
 * ARGUMENTS:
 *   Argument  Type          I/O  Description (scale)
 *   --------  ------------  ---  ----------------------------------------
 *   t         const char *  I    case name
 *   tol       long int      I    general tolerance, LSB
 *
 * RETURNS: none
 **********************************************************************/
static void pass(const char *t, long int tol)
{
    bool      display = false;                       /* ENDEXIT display wanted */
    const int forced  = oracle_in(t, "GOTOADDR", 0); /* forced GOTOADDR word (0: none) */

    avg_in(t);

    for (size_t i = 0; forced != 0 && i < sizeof (GOTOS) / sizeof (GOTOS[0]); i++)
    {
        if (GOTOS[i].word == (forced < 0 ? forced + 077777 : forced)) /* ones' comp */
        {
            agc_entry_state()->gotoaddr = GOTOS[i].g; /* forced, as the AGC */
        }
    }

    (void) agc_entry_scalepop(&display);
    oracle_require_ok(t, NULL);
    compare(t, tol);
}

/**********************************************************************
 * AGC: none -- a 3x3 matrix (three half-unit rows) from the case inputs.
 *
 * FUNCTION NAME: mat_in
 *
 * ARGUMENTS:
 *   Argument  Type          I/O  Description (scale)
 *   --------  ------------  ---  ----------------------------------------
 *   t         const char *  I    case name
 *   name      const char *  I    input name
 *
 * RETURNS: agc_mat_t -- agc_mat_t -- the matrix, half-unit rows (B1)
 **********************************************************************/
static agc_mat_t mat_in(const char *t, const char *name)
{
    agc_mat_t m; /* the matrix, B1 rows */

    for (int r = 0; r < 3; r++)
    {
        m.row[r] = oracle_in_vec_at(t, name, r);
    }

    return (m);
}

/**********************************************************************
 * AGC: none -- a CDU word is a two's complement pattern: AOG/PIP etc. hold
 * it as is.
 *
 * FUNCTION NAME: cdu2s
 *
 * ARGUMENTS:
 *   Argument  Type      I/O  Description (scale)
 *   --------  --------  ---  --------------------------------------------
 *   w         uint16_t  I    CDU word
 *
 * RETURNS: agc_sp_t -- agc_sp_t -- the angle /180, B0
 **********************************************************************/
static agc_sp_t cdu2s(uint16_t w)
{
    return ((agc_sp_t) ((w >= 040000) ? (int) w - 0100000 : (int) w)); /* 15-bit sign */
}

/**********************************************************************
 * CM/POSE .. CM/TRIO (CM_BODY_ATTITUDE.agc) from a fresh state.
 *
 * FUNCTION NAME: cm_pose
 *
 * ARGUMENTS:
 *   Argument  Type          I/O  Description (scale)
 *   --------  ------------  ---  ----------------------------------------
 *   t         const char *  I    case name
 *   tol       long int      I    tolerance, LSB
 *
 * RETURNS: none
 **********************************************************************/
static void cm_pose(const char *t, long int tol)
{
    agc_dp_t           ang[4] = {0, 0, 0, 0};
    agc_entry_state_t *e      = agc_entry_state(); /* entry erasables */
    agc_state_vector_t sv;                         /* state vector (VN), m/cs B7 */

    agc_state_init(AGC_VEHICLE_CSM);
    (void) agc_guid_init(AGC_VEHICLE_CSM);
    agc_entry_lexicon_reset();
    sv.r                        = agc_vec_zero();
    sv.v                        = oracle_in_vec(t, "VN");
    sv.t                        = 0;
    sv.moon                     = false;
    (void) agc_sv_set(AGC_SV_THIS, &sv);
    agc_guid_state()->avg.unitr = oracle_in_vec(t, "UNITR");
    agc_guid_state()->avg.unitw = oracle_in_vec(t, "UNITW");
    agc_erase_set_refsmmat(mat_in(t, "REFSMMAT"));
    e->olduya                   = oracle_in_vec(t, "OLDUYA");
    e->aog_pip                  = cdu2s(oracle_in_raw(t, "AOG/PIP", 0));
    e->aig_pip                  = cdu2s(oracle_in_raw(t, "AOG/PIP", 1));
    e->amg_pip                  = cdu2s(oracle_in_raw(t, "AOG/PIP", 2));
    (void) agc_entry_cm_pose_triad();
    (void) agc_entry_cm_trio(ang);
    oracle_require_ok(t, "CM/ATUP");
    oracle_cmp_vec(t, "-VREL", e->mvrel, oracle_out_vec(t, "-VREL"), tol);
    oracle_cmp_vec(t, "UXA/2", e->uxa, oracle_out_vec(t, "UXA/2"), tol);
    oracle_cmp_vec(t, "UYA/2", e->uya, oracle_out_vec(t, "UYA/2"), tol);
    oracle_cmp_vec(t, "UZA/2", e->uza, oracle_out_vec(t, "UZA/2"), tol);
    oracle_cmp_vec(t, "OLDUYA", e->olduya, oracle_out_vec(t, "OLDUYA"), tol);
    oracle_cmp_vec(t, "UBX/2", e->ubx, oracle_out_vec(t, "UBX/2"), tol);
    oracle_cmp_vec(t, "UBY/2", e->uby, oracle_out_vec(t, "UBY/2"), tol);
    oracle_cmp_vec(t, "UBZ/2", e->ubz, oracle_out_vec(t, "UBZ/2"), tol);
    (void) oracle_cmp(t, "-ROLL", agc_dp_high(ang[0]), oracle_out_sp(t, "VAC1+6"), 1);
    (void) oracle_cmp(t, "-BETA", agc_dp_high(ang[1]), oracle_out_sp(t, "VAC1+7"), 1);
    (void) oracle_cmp(t, "-ALFA", ang[2], oracle_out_dp(t, "VAC1+8"), tol);
    (void) oracle_cmp(t, "-GAMA", ang[3], oracle_out_dp(t, "VAC1+10"), tol);
}
