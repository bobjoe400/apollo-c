/**********************************************************************
 * FILE NAME: entry.c
 *
 * PURPOSE:
 *   CM entry guidance against the real AGC code (yaAGC oracle). A chain
 *   of passes: STARTENT, then SCALEPOP (TARGETNG + the GOTOADDR phase:
 *   INITROLL, HUNTEST/RANGER, UPCONTRL, KEP2, PREDICT3) with new
 *   average-G data each pass, and three CM/POSE .. CM/TRIO cases. The AGC
 *   side of each pass starts from the erasable memory its previous pass
 *   left; the C side carries its own agc_entry_state() along, so a
 *   difference propagates as it would in flight. Where the generator
 *   forced GOTOADDR the C does the same.
 *
 * AGC SOURCE:
 *   Comanche055 REENTRY_CONTROL.agc pp. 844-881, CM_BODY_ATTITUDE.agc
 *   pp. 883-888 (run in yaAGC; cases in tools/oracle/cases/entry.spec /
 *   .txt, generated by tools/oracle/cases/gen/gen_entry.py)
 *
 * EXTERNAL VARIABLES:
 *   none (the entry erasables through agc_entry_state())
 *
 * EXTERNAL REFERENCES:
 *   Name                  Description
 *   --------------------  ------------------------------------------
 *   oracle_*              case reader and comparisons (oracle_txt.h)
 *   agc_entry_startent    STARTENT
 *   agc_entry_scalepop    SCALEPOP
 *   agc_entry_cm_pose_triad / agc_entry_cm_trio  CM/POSE, CM/TRIO
 *
 * ABNORMAL TERMINATION CONDITIONS, ALARMS:
 *   exit status 1 when a comparison fails (oracle_finish)
 *
 * ASSUMPTIONS, CONSTRAINTS, RESTRICTIONS:
 *   Tolerances (LSB of the AGC word): docs/modules/oracle-cases.md and
 *   the comment of compare().
 **********************************************************************/
